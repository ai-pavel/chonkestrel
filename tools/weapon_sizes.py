#!/usr/bin/env python3
"""
Make the images of the twin and triple weapons (see doc/game/weapon-sizes.md) for
the Chonkestrel mod, from the vanilla weapons' animations in ftl.dat.

    python3 tools/weapon_sizes.py ftl.dat              # make them all
    python3 tools/weapon_sizes.py ftl.dat --preview out/

A twin or triple weapon isn't two or three weapons stuck together: like the
bigger ships, it's one weapon made wider. Each frame of its animation is the
vanilla weapon's with its body widened, by repeating the column of pixels
that changes least (below the barrel, beside it), and two or three barrels
sticking out of it, side by side, each its own copy of the vanilla one (so
each shot comes out of its own). A beam weapon or a bomb launcher keeps one
barrel (or hatch), widened in the middle, so the beam comes straight out of
its centre.

The triple ion weapons, Heavy Lasers, Hull Laser and missile launchers (see
TRIANGLE) are three of the weapon in a triangle instead: two behind and one
in front, which every shot comes out of, charging copy by copy.

The weapon's dark mount (on the left of its image, which goes against the
ship's hull) is kept as it is, so the weapon sits on the hull the same way.

The images go in the mod's img/weapons, and their animations (an animSheet
and a weaponAnim each, with an xftlBarrels element saying where each barrel's
shots come out, relative to the fire point) between the markers in its
animations.xml.append. --preview draws each weapon's single, twin and triple
versions side by side, and every frame of the triple one, with their mount
(green) and fire points (red), to check them for artefacts.

It needs Pillow and numpy.
"""
import io
import re
import struct
import sys
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw

MOD = Path(__file__).resolve().parent.parent / "mods" / "chonkestrel"
ANIMATIONS_FILE = MOD / "data" / "animations.xml.append"
IMAGES_DIR = MOD / "img" / "weapons"
BEGIN_MARK = "<!-- BEGIN generated by tools/weapon_sizes.py -->"
END_MARK = "<!-- END generated by tools/weapon_sizes.py -->"

SIZES = (2, 3)

# The weapons that can be combined (see WeaponSizes.canCombine): their
# animations, from the vanilla weapons that aren't Advanced Edition's,
# artillery, drones' or bosses'. The beam weapons and bomb launchers keep one
# barrel; the rest (in BARRELS, below) get one for each copy.
SINGLE_BARREL = {"beam_1", "beam_2", "beam_3", "beam_bio", "beam_fire", "beam_hull", "beam_long",
                 "bomb_1", "bomb_breach", "bomb_fire", "bomb_heal", "bomb_ion", "bomb_lockdown"}
# Where each weapon with a barrel for each copy has its barrel: the columns
# it's in (x0 to x1), and the row where it goes into the weapon's body (for
# reference). That band of columns is repeated for the other copies, side by
# side (see Widening).
BARRELS = {
    "laser_burst_1": (7, 13, 20),
    "laser_burst_2": (7, 13, 20),
    "laser_burst_3": (10, 15, 21),
    "laser_burst_5": (11, 19, 20),
    "laser_heavy_1": (12, 23, 27),
    "laser_heavy_2": (13, 22, 20),
    "laser_hull": (12, 19, 25),
    "missiles_1": (9, 21, 8),
    "missiles_2": (8, 22, 20),
    "crystal_burst_1": (9, 17, 28),
    "crystal_burst_2": (11, 22, 30),
    "crystal_heavy_1": (12, 26, 34),
    "crystal_heavy_2": (18, 29, 38),
    "ion_1": (10, 21, 17),
    "ion_2": (8, 20, 16),
    "ion_4": (9, 22, 16),
}
MULTI_BARREL = set(BARRELS)

# The weapons whose triple one is three of them in a triangle (see Triangle),
# rather than three barrels side by side: two behind, at the sides, and one
# in front, in the middle, which every shot comes out of. (The burst lasers
# and the Crystal weapons keep their barrels side by side, as do every twin
# one, and the beams and bomb launchers stay as they are.)
TRIANGLE = {"ion_1", "ion_2", "ion_4", "laser_heavy_1", "laser_heavy_2", "laser_hull", "missiles_1", "missiles_2"}
# How far the copies behind are to the sides, and how far the one in front
# is ahead of them, as fractions of the weapon's width and height (with at
# least TRIANGLE_MIN_SHIFT pixels to the side, so a narrow weapon's copies
# behind aren't hidden), and how dark the copies behind are
TRIANGLE_SHIFT = 0.45
TRIANGLE_MIN_SHIFT = 10
TRIANGLE_RISE = 0.20
TRIANGLE_BACK = 0.72
# The triangle's charging frames for each copy, at least: the copies charge
# one after another (the left, the right, then the middle, when it's ready to
# fire), each with its own charging glow drawn into its frames
TRIANGLE_CHARGE_STEPS = 4

# Where each beam weapon's base is: the columns between the prongs (or rails)
# on either side of it. That band of columns is repeated, the whole height of
# the image, so the twin or triple one has two or three bases glued together
# between its prongs, which stay as wide as they are at the sides, and the
# beam comes out of the middle. (The band is cleared above the base, so any
# bits of the prongs in it aren't repeated or left behind, but a bar across
# the top between them, like the Glaive Beam's, is kept.)
BEAM_BANDS = {
    "beam_1": (12, 17),
    "beam_2": (13, 20),
    "beam_3": (13, 24),
    "beam_long": (13, 19),
    "beam_bio": (13, 20),
    "beam_fire": (14, 17),
    "beam_hull": (14, 19),
}

# The bomb launchers (which are all the same shape): the band of columns of
# their box with the hatch on top, repeated for a second hatch, and the rows
# above their box, where the bomb comes up before it's teleported. A twin
# one has a bomb over each hatch; a triple one has a third over them, in the
# middle, so they're a triangle (with the image made taller for it by
# BOMB_RISE rows).
BOMB_ARTS = {"bomb_1", "bomb_breach", "bomb_fire", "bomb_heal", "bomb_ion", "bomb_lockdown"}
BOMB_BAND = (13, 25)
BOMB_LAYER_ROWS = 19
BOMB_RISE = 11

# A pixel counts as part of the weapon if it's at least this opaque
SOLID = 128
# A beam weapon's base starts at the first row its band is this much filled
# across (see beam_cleared_rows)
BASE_FILL = 0.7
# The gap between barrels (in pixels), and how much wider a single-barrelled
# weapon gets for each extra copy, as a fraction of its width
BARREL_GAP = 0
SINGLE_WIDEN = 0.3
# The most columns of pixels repeated to widen a weapon: the smoothest ones
# (see spread_columns), so there's no one wide flat stripe
MAX_SEAMS = 6


class Dat:
    """The files in ftl.dat (FTL 1.6's format)."""

    def __init__(self, path):
        self.data = Path(path).read_bytes()
        header, entry, count, names_size = struct.unpack(">HHII", self.data[4:16])
        table = self.data[header + count * entry:header + count * entry + names_size]
        self.files = {}
        for i in range(count):
            e = self.data[header + i * entry:header + (i + 1) * entry]
            name_offset = int.from_bytes(e[5:8], "big")
            offset, _, size = struct.unpack(">III", e[8:20])
            self.files[table[name_offset:table.index(b"\0", name_offset)].decode()] = (offset, size)

    def read(self, name):
        offset, size = self.files[name]
        return self.data[offset:offset + size]

    def image(self, name):
        return Image.open(io.BytesIO(self.read(name))).convert("RGBA")


class WeaponArt:
    """A vanilla weapon's animation: its sheet's frames, and its points."""

    def __init__(self, dat, animations, name):
        self.name = name
        anim = re.search(r'<weaponAnim name="%s">(.*?)</weaponAnim>' % name, animations, re.S).group(1)
        self.sheet_name = re.search(r"<sheet>(\w+)", anim).group(1)
        sheet = re.search(r'<animSheet name="%s"\s+w="(\d+)"\s+h="(\d+)"\s+fw="(\d+)"\s+fh="(\d+)">([^<]+)<'
                          % self.sheet_name, animations)
        self.fw, self.fh = int(sheet.group(3)), int(sheet.group(4))
        self.sheet_path = sheet.group(5).strip()
        self.desc = re.search(r"<desc[^>]*/>", anim).group(0)
        self.charged_frame = int(re.search(r"<chargedFrame>(\d+)", anim).group(1))
        self.fire_frame = int(re.search(r"<fireFrame>(\d+)", anim).group(1))
        fire = re.search(r'<firePoint\s+x="(-?\d+)"\s+y="(-?\d+)"', anim)
        mount = re.search(r'<mountPoint\s+x="(-?\d+)"\s+y="(-?\d+)"', anim)
        self.fire = (int(fire.group(1)), int(fire.group(2)))
        self.mount = (int(mount.group(1)), int(mount.group(2)))
        glow = re.search(r"<chargeImage>([^<]+)</chargeImage>", anim)
        self.glow_path = glow.group(1).strip() if glow else None

        image = np.asarray(dat.image("img/" + self.sheet_path))
        count = image.shape[1] // self.fw
        self.frames = [image[:self.fh, i * self.fw:(i + 1) * self.fw].copy() for i in range(count)]
        self.glow = np.asarray(dat.image("img/" + self.glow_path)).copy() if self.glow_path else None


class Widening:
    """
    How a weapon's frames are made wider (see the top of this file, and
    BARRELS, BEAM_BANDS and BOMB_ARTS): a band of columns repeated, the
    whole height of the image, and for a bomb launcher, its bombs drawn over
    the hatches. Any other weapon has its smoothest columns near the middle
    of its barrel repeated (seams).
    """

    def __init__(self, art, size):
        self.size = size
        self.kind = ("multi" if art.name in BARRELS else "beam" if art.name in BEAM_BANDS
                     else "bomb" if art.name in BOMB_ARTS else "seams")
        self.rise = 0
        self.seams = {}
        if self.kind == "multi":
            self.band = BARRELS[art.name][:2]
        elif self.kind == "beam":
            self.band = BEAM_BANDS[art.name]
            self.cleared_rows = beam_cleared_rows(art, self.band)
        elif self.kind == "bomb":
            self.band = BOMB_BAND
            if size >= 3:
                self.rise = BOMB_RISE
        else:
            self.band = None
            centre = art.fire[0]
            self.extra = (size - 1) * max(2, round(art.fw * SINGLE_WIDEN))
            candidates = list(range(max(art.mount[0] + 2, centre - 3), min(art.fw - 1, centre + 4)))
            self.seams = spread_columns(art, candidates, self.extra)
        if self.band is not None:
            self.step = self.band[1] - self.band[0] + 1
            # (a triple bomb launcher has two hatches, with a bomb over them)
            repeats = 1 if self.kind == "bomb" else size - 1
            self.repeats = repeats
            self.extra = repeats * self.step

    def shifted(self, x):
        """Where column x of the vanilla weapon goes."""
        if self.band is not None:
            return x + self.extra if x > self.band[1] else x
        return x + sum(n for seam, n in self.seams.items() if seam < x)

    def barrel_offsets(self):
        """Where each barrel's shots come out, relative to the first's."""
        if self.kind != "multi":
            return [0]
        return [i * self.step for i in range(self.size)]

    def fire_point(self, art):
        x, y = art.fire
        y += self.rise
        if self.kind == "multi":
            return (self.shifted(x), y)
        # The middle of the widened weapon's barrel (or hatches)
        return (x + self.extra // 2, y)

    def mount_point(self, art):
        return (art.mount[0], art.mount[1] + self.rise)

    def apply(self, frame):
        """The frame (or glow image) made wider."""
        if self.band is None:
            parts = []
            for x in range(frame.shape[1]):
                parts.append(frame[:, x:x + 1])
                for _ in range(self.seams.get(x, 0)):
                    parts.append(frame[:, x:x + 1])
            return np.concatenate(parts, axis=1)

        left, right = self.band
        band = frame[:, left:right + 1]
        if self.kind == "beam":
            # (and the band itself, so a bit of a prong in it isn't left
            # behind in the middle when the rest of it moves out)
            band = band.copy()
            band[self.cleared_rows] = 0
            frame = frame.copy()
            frame[:, left:right + 1] = band
        wide = np.concatenate([frame[:, :right + 1]] + [band] * self.repeats + [frame[:, right + 1:]], axis=1)
        if self.kind != "bomb":
            return wide

        # A bomb over each hatch (and for a triple one, a third over them,
        # behind, in the middle), in place of the repeated band's bits of one
        layer = frame[:BOMB_LAYER_ROWS]
        wide[:BOMB_LAYER_ROWS] = 0
        if self.rise:
            wide = np.concatenate([np.zeros((self.rise, wide.shape[1], 4), dtype=wide.dtype), wide], axis=0)
            paste(wide, layer, self.step // 2, 0)
        for i in range(2):
            paste(wide, layer, i * self.step, self.rise)
        return wide


class Triangle:
    """
    A triple weapon as three of them in a triangle (see TRIANGLE): two
    behind, at the sides, darker, and one in front of them, in the middle,
    which every shot comes out of. The copies charge one after another, the
    left, the right, then the middle, so the weapon's lights come on copy by
    copy: it has frames of its own for that (charged_frame of them), with
    each copy's charging glow drawn in, rather than a glow image over it
    all. Then the three fire together. The same interface as Widening.
    """

    def __init__(self, art):
        self.art = art
        self.shift = max(TRIANGLE_MIN_SHIFT, round(art.fw * TRIANGLE_SHIFT))
        self.rise = max(6, round(art.fh * TRIANGLE_RISE))
        self.charged_frame = 3 * max(art.charged_frame, TRIANGLE_CHARGE_STEPS)
        self.fire_frame = self.charged_frame + art.fire_frame - art.charged_frame

    def barrel_offsets(self):
        return [0]

    def fire_point(self, art):
        return (art.fire[0] + self.shift, art.fire[1])

    def mount_point(self, art):
        # (the copy behind on the left's, which is against the hull)
        return (art.mount[0], art.mount[1] + self.rise)

    def copy(self, progress):
        """One copy, charged as far as progress (0 to 1), with its glow."""
        art = self.art
        if progress >= 1:
            return art.frames[art.charged_frame]
        frame = art.frames[int(art.charged_frame * progress)].copy()
        if art.glow is not None and progress > 0:
            blend(frame, art.glow, progress)
        return frame

    def compose(self, left, right, middle):
        art = self.art
        image = np.zeros((art.fh + self.rise, art.fw + 2 * self.shift, 4), dtype=np.uint8)
        paste(image, darken(left, TRIANGLE_BACK), 0, self.rise)
        paste(image, darken(right, TRIANGLE_BACK), 2 * self.shift, self.rise)
        paste(image, middle, self.shift, 0)
        return image

    def frames(self):
        """Charging copy by copy, then firing together."""
        frames = []
        for step in range(self.charged_frame + 1):
            progress = step / self.charged_frame
            frames.append(self.compose(*(self.copy(min(1, max(0, 3 * progress - i))) for i in range(3))))
        for frame in self.art.frames[self.art.charged_frame + 1:]:
            frames.append(self.compose(frame, frame, frame))
        return frames


def darken(frame, amount):
    """The frame with its colours darkened by amount (0 to 1), as it's further back."""
    dark = frame.astype(np.float32)
    dark[..., :3] *= amount
    return dark.clip(0, 255).astype(np.uint8)


def blend(frame, glow, alpha):
    """Draw the glow over the frame, at alpha (0 to 1)."""
    a = glow[..., 3:4].astype(np.float32) / 255 * alpha
    frame[..., :3] = (glow[..., :3] * a + frame[..., :3] * (1 - a)).astype(np.uint8)
    frame[..., 3] = np.maximum(frame[..., 3], (glow[..., 3] * alpha).astype(np.uint8))


def beam_cleared_rows(art, band):
    """
    The rows of a beam weapon's band (see BEAM_BANDS) that are cleared in its
    repeats: those above its base (the first three rows in a row, from the
    top, that the band is mostly filled across, in any frame), except for
    any that are themselves mostly filled (a bar across the top).
    """
    left, right = band
    width = right - left + 1
    solid = np.max(np.stack([f[:, left:right + 1, 3] for f in art.frames]), axis=0) >= SOLID
    filled = [row.sum() >= width * BASE_FILL for row in solid]
    base = next((y for y in range(len(filled) - 2) if all(filled[y:y + 3])), 0)
    return [y for y in range(base) if not filled[y]]


def spread_columns(art, candidates, extra):
    """
    The columns (of candidates) to repeat to make a weapon extra pixels
    wider, and how many times each: the smoothest up to MAX_SEAMS of them
    (whose pixels change least from the next column's, in every frame, so
    repeating them leaves no streaks), each repeated about as many times.
    """
    if extra <= 0 or not candidates:
        return {}
    ranked = sorted(candidates, key=lambda x: best_seam_cost(art, x))
    chosen = sorted(ranked[:max(1, min(MAX_SEAMS, extra, len(ranked)))])
    seams = {x: extra // len(chosen) for x in chosen}
    for x in chosen[:extra % len(chosen)]:
        seams[x] += 1
    return seams


def best_seam_cost(art, x):
    total = 0
    for frame in art.frames:
        a = frame[:, x].astype(int)
        b = frame[:, min(x + 1, art.fw - 1)].astype(int)
        total += np.abs(a - b).sum()
    return total


def paste(target, source, x, y):
    """Draw source over target at (x, y), keeping target's pixels where source's are clear."""
    h, w = source.shape[:2]
    region = target[y:y + h, x:x + w]
    h, w = region.shape[:2]
    alpha = source[:h, :w, 3:4] > 0
    region[:] = np.where(alpha, source[:h, :w], region)


def generate(dat):
    animations = dat.read("data/animations.xml").decode("utf-8", "replace")
    IMAGES_DIR.mkdir(parents=True, exist_ok=True)
    xml = []
    made = []
    for name in sorted(SINGLE_BARREL | MULTI_BARREL):
        art = WeaponArt(dat, animations, name)
        for size in SIZES:
            triangle = size == 3 and name in TRIANGLE
            widening = Triangle(art) if triangle else Widening(art, size)
            frames = widening.frames() if triangle else [widening.apply(f) for f in art.frames]
            charged_frame = widening.charged_frame if triangle else art.charged_frame
            fire_frame = widening.fire_frame if triangle else art.fire_frame
            fw = frames[0].shape[1]
            sheet = np.concatenate(frames, axis=1)
            sheet_file = "xftl_x%d_%s" % (size, Path(art.sheet_path).name)
            Image.fromarray(sheet).save(IMAGES_DIR / sheet_file)
            glow_xml = ""
            # (a triangle's copies have their glow drawn into their frames)
            if art.glow is not None and triangle:
                (IMAGES_DIR / ("xftl_x%d_%s" % (size, Path(art.glow_path).name))).unlink(missing_ok=True)
            if art.glow is not None and not triangle:
                glow_file = "xftl_x%d_%s" % (size, Path(art.glow_path).name)
                Image.fromarray(widening.apply(art.glow)).save(IMAGES_DIR / glow_file)
                glow_xml = "\n\t<chargeImage>weapons/%s</chargeImage>" % glow_file
            fire = widening.fire_point(art)
            mount = widening.mount_point(art)
            height = art.fh + widening.rise
            sheet_name = "xftl_x%d_%s" % (size, art.sheet_name)
            barrels = ",".join(str(o) for o in widening.barrel_offsets())
            # (with as many frames as it has, as a triangle has more)
            desc = re.sub(r'length="\d+"', 'length="%d"' % len(frames), art.desc)
            xml.append(
                '<animSheet name="%s" w="%d" h="%d" fw="%d" fh="%d">weapons/%s</animSheet>\n'
                '<weaponAnim name="xftl_x%d_%s">\n'
                '\t<sheet>%s</sheet>\n\t%s\n'
                '\t<chargedFrame>%d</chargedFrame>\n\t<fireFrame>%d</fireFrame>\n'
                '\t<firePoint x="%d" y="%d"/>\n\t<mountPoint x="%d" y="%d"/>%s\n'
                '\t<xftlBarrels>%s</xftlBarrels>\n'
                '</weaponAnim>\n'
                % (sheet_name, sheet.shape[1], height, fw, height, sheet_file,
                   size, name, sheet_name, desc, charged_frame, fire_frame,
                   fire[0], fire[1], mount[0], mount[1], glow_xml, barrels))
            made.append((art, size, widening, frames))

    text = ANIMATIONS_FILE.read_text() if ANIMATIONS_FILE.exists() else ""
    block = BEGIN_MARK + "\n" + "\n".join(xml) + END_MARK + "\n"
    if BEGIN_MARK in text:
        text = text[:text.index(BEGIN_MARK)] + block + text[text.index(END_MARK) + len(END_MARK) + 1:]
    else:
        text = text + ("\n" if text else "") + block
    ANIMATIONS_FILE.write_text(text)
    return made


def preview(made, out):
    """Draw each weapon's versions side by side, to check them for artefacts."""
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    scale = 4
    by_name = {}
    for art, size, widening, frames in made:
        by_name.setdefault(art.name, (art, []))[1].append((size, widening, frames))
    sheets = []
    for name, (art, versions) in sorted(by_name.items()):
        charged = [(art.frames[art.charged_frame], art.fire, [0], art.mount)]
        for size, widening, frames in versions:
            charged_frame = getattr(widening, "charged_frame", art.charged_frame)
            charged.append((frames[charged_frame], widening.fire_point(art), widening.barrel_offsets(),
                            widening.mount_point(art)))
        tallest = max(f.shape[0] for f, *_ in charged)
        triple_frames = versions[-1][2]
        width = sum(f.shape[1] + 6 for f, *_ in charged) + 20
        width = max(width, sum(f.shape[1] + 2 for f in triple_frames) + 20)
        height = tallest * 2 + 30
        sheet = Image.new("RGBA", (width * scale, height * scale), (34, 36, 52, 255))
        draw = ImageDraw.Draw(sheet)
        x = 10
        for frame, fire, barrels, mount in charged:
            # (lined up by their bottoms, as a taller one's taller at the top)
            top = 10 + tallest - frame.shape[0]
            img = Image.fromarray(frame).resize((frame.shape[1] * scale, frame.shape[0] * scale), Image.NEAREST)
            sheet.alpha_composite(img, (x * scale, top * scale))
            mx, my = (x + mount[0]) * scale, (top + mount[1]) * scale
            draw.rectangle([mx - 3, my - 3, mx + 3, my + 3], outline=(0, 255, 0, 255))
            for b in barrels:
                fx, fy = (x + fire[0] + b) * scale, (top + fire[1]) * scale
                draw.rectangle([fx - 3, fy - 3, fx + 3, fy + 3], outline=(255, 60, 60, 255))
            x += frame.shape[1] + 6
        x = 10
        for frame in triple_frames:
            img = Image.fromarray(frame).resize((frame.shape[1] * scale, frame.shape[0] * scale), Image.NEAREST)
            sheet.alpha_composite(img, (x * scale, (20 + tallest) * scale))
            x += frame.shape[1] + 2
        sheet.save(out / ("%s.png" % name))
        sheets.append(sheet.crop((0, 0, sheet.width, (tallest + 15) * scale)))

    # All of them, single, twin and triple, one under the other
    width = max(s.width for s in sheets)
    overview = Image.new("RGBA", (width, sum(s.height for s in sheets)), (34, 36, 52, 255))
    y = 0
    for s in sheets:
        overview.alpha_composite(s, (0, y))
        y += s.height
    overview.save(out / "_all.png")
    return sheets


def main():
    dat = Dat(sys.argv[1])
    made = generate(dat)
    if len(sys.argv) > 3 and sys.argv[2] == "--preview":
        preview(made, sys.argv[3])
    print("Made %d weapon images" % len(made))


if __name__ == "__main__":
    main()

def S(system, power=1, start=True, **attrs):
    """
    A new room's system: its starting power, whether it's installed from the
    start, and any other attributes (such as an artillery system's weapon).
    """
    return (system, power, start, attrs)


def system_element(spec, room):
    name, power, start, attrs = spec
    elem = ET.Element(name, {"power": str(power), "room": str(room), "start": "true" if start else "false"})
    for key, value in attrs.items():
        elem.set(key, value)
    return elem



def draw_rooms(canvas, layout, origin, systems, doors=True):
    draw = ImageDraw.Draw(canvas)
    names = {}
    for elem in systems:
        names.setdefault(int(elem.get("room")), []).append(
            elem.tag[:5] + ("" if elem.get("start") != "false" else "*"))
    for rid, (x, y, w, h) in layout.rooms.items():
        box = [origin[0] + x * ROOM, origin[1] + y * ROOM, origin[0] + (x + w) * ROOM - 1,
               origin[1] + (y + h) * ROOM - 1]
        draw.rectangle(box, outline=(30, 30, 30, 255))
        draw.text((box[0] + 2, box[1] + 1), str(rid), fill=(255, 255, 255, 255))
        for i, label in enumerate(names.get(rid, [])):
            draw.text((box[0] + 2, box[1] + 11 + 9 * i), label, fill=(255, 220, 0, 255))
    if doors:
        for x, y, a, b, vertical in layout.doors:
            px, py = origin[0] + x * ROOM, origin[1] + y * ROOM
            colour = (255, 60, 60, 255) if -1 in (a, b) else (255, 150, 0, 255)
            if vertical:
                draw.line([px, py + 9, px, py + 26], fill=colour, width=3)
            else:
                draw.line([px + 9, py, px + 26, py], fill=colour, width=3)


def draw_mounts(canvas, mounts):
    draw = ImageDraw.Draw(canvas)
    for i, m in enumerate(mounts):
        x, y = int(m["x"]), int(m["y"])
        colour = (60, 200, 255, 255) if i < VANILLA_MOUNTS else (255, 60, 255, 255)
        draw.ellipse([x - 4, y - 4, x + 4, y + 4], outline=colour, width=2)
        draw.text((x + 6, y - 6), "%d%s" % (i + 1, m["slide"][0]), fill=colour)


def preview(dat, made, out):
    """The vanilla ship and the new one side by side, with their rooms, doors, systems and mounts."""
    vanilla = made.vanilla
    layout = Layout(dat.text("data/%s.txt" % vanilla.get("layout")))
    origin, _, mounts = layout_xml_parts(dat.text("data/%s.xml" % vanilla.get("layout")))
    old = Image.new("RGBA", hull_image(dat, vanilla.get("img")).size, (40, 40, 60, 255))
    old.alpha_composite(hull_image(dat, vanilla.get("img")))
    draw_rooms(old, layout, origin, list(vanilla.find("systemList")))
    draw_mounts(old, mounts[:VANILLA_MOUNTS])

    new = Image.new("RGBA", made.hull.size, (40, 40, 60, 255))
    new.alpha_composite(made.hull)
    new.alpha_composite(made.floor, made.floor_offset)
    for elem in made.systems:
        image = elem.get("img")
        if image is None:
            continue
        x, y, _, _ = made.layout.rooms[int(elem.get("room"))]
        picture = made.interiors.get(image) or dat.image("img/ship/interior/%s.png" % image)
        new.alpha_composite(picture, (made.origin[0] + x * ROOM, made.origin[1] + y * ROOM))
    draw_rooms(new, made.layout, made.origin, made.systems)
    draw_mounts(new, made.mounts)

    sheet = Image.new("RGBA", (old.width + new.width + 10, max(old.height, new.height)), (0, 0, 0, 255))
    sheet.paste(old, (0, (sheet.height - old.height) // 2))
    sheet.paste(new, (old.width + 10, 0))
    sheet.save(out / ("%s.png" % made.ship["img"]))


def main():
    dat = Dat(sys.argv[1])
    blueprints = vanilla_blueprints(dat)
    cat = Catalogue(dat, blueprints)
    made = []
    for ship in SHIPS:
        m = make_ship(dat, blueprints, cat, ship)
        m.dat = dat
        made.append(m)
        print("Made %s (%s, %dx%d)" % (ship["title"], ship["name"], m.hull.width, m.hull.height))
    check_names(dat, made)

    if len(sys.argv) > 3 and sys.argv[2] == "--preview":
        out = Path(sys.argv[3])
        out.mkdir(parents=True, exist_ok=True)
        for m in made:
            preview(dat, m, out)
        print("Previews in", out)
        return

    for m in made:
        write(m)
    write_blueprints([m.blueprint for m in made])


if __name__ == "__main__":
    main()

def slot_of(elem, cells):
    """A system's console (or bed) cell and direction, or None: its own, or the game's default."""
    slot = elem.find("slot")
    number = slot.findtext("number") if slot is not None else None
    direction = slot.findtext("direction") if slot is not None else None
    default = DEFAULT_SLOTS.get(elem.tag)
    if number is None and default is not None:
        number = default[0] if default[0] < cells else 0
    if direction is None and default is not None:
        direction = default[1]
    if number is None:
        return None
    return int(str(number).strip()), (direction.strip() if direction else None)


def set_slot(elem, slot):
    for old in elem.findall("slot"):
        elem.remove(old)
    if slot is None:
        return
    number, direction = slot
    new = ET.SubElement(elem, "slot")
    if direction:
        ET.SubElement(new, "direction").text = direction
    ET.SubElement(new, "number").text = str(number)


def interior_name(elem):
    """A system's interior image, as the game picks it for a player ship (see ShipBlueprint.ParsedSystem)."""
    if elem.get("img"):
        return elem.get("img")
    if elem.tag in NO_DEFAULT_IMAGE:
        return None
    return "room_" + elem.tag


class Catalogue:
    def __init__(self, dat, blueprints):
        self.dat = dat
        self.rooms = {}
        names = [ship["vanilla"] for ship in SHIPS]
        names += sorted(n for n in blueprints if n.startswith("PLAYER_SHIP_") and n not in names)
        for name in names:
            bp = blueprints[name]
            layout_file = "data/%s.txt" % bp.get("layout")
            if not dat.has(layout_file):
                continue
            layout = Layout(dat.text(layout_file))
            for elem in bp.find("systemList"):
                room = layout.rooms.get(int(elem.get("room")))
                if room is None:
                    continue
                image = interior_name(elem)
                if image is not None and not dat.has("img/ship/interior/%s.png" % image):
                    continue
                key = (elem.tag, room[2], room[3])
                self.rooms.setdefault(key, []).append((image, slot_of(elem, room[2] * room[3])))

    def find(self, system, w, h):
        """The interior and console for a new room: (image name, slot, generated image or None)."""
        if (system, w, h) in self.rooms:
            image, slot = self.rooms[(system, w, h)][0]
            return image, slot, None
        if system in NO_DEFAULT_IMAGE:
            return None, None, None
        assert system not in ("weapons", "engines", "shields", "pilot", "sensors", "doors"), \
            "No vanilla %s room is %dx%d, to copy its console from" % (system, w, h)
        # Any vanilla interior of the right size, for a system without a console
        images = sorted(n for n in self.dat.files if re.fullmatch(r"img/ship/interior/room_%s(_\d+)?\.png" % system, n))
        for name in images:
            if self.dat.image(name).size == (w * ROOM, h * ROOM):
                return Path(name).stem, None, None
        # Or the biggest one, with its corners moved apart (and no cell
        # taken up by the medbay's bed)
        source = max(images, key=lambda n: self.dat.image(n).size[0] * self.dat.image(n).size[1])
        slot = (-2, None) if system in ("medbay", "clonebay") else None
        return None, slot, spread(self.dat.image(source), (w * ROOM, h * ROOM))


def spread(image, size):
    """The image with its corners moved apart, to fit a bigger room (see chonkestrel_art.ROOMS)."""
    w, h = image.size
    cx, cy = w // 2, h // 2
    out = Image.new("RGBA", size)
    for box in [(0, 0, cx, cy), (cx, 0, w, cy), (0, cy, cx, h), (cx, cy, w, h)]:
        x = box[0] if box[0] == 0 else size[0] - (w - box[0])
        y = box[1] if box[1] == 0 else size[1] - (h - box[1])
        out.paste(image.crop(box), (x, y))
    return out


def clean_row(hull, split, source, black=(BLACK_LEVEL, BLACK_SHARE, BLACK_SEARCH_ROOMS)):
    """
    The row of pixels to repeat when the hull's stretched at split: the one
    at source, but where that's black (an edge line, a gap between panels
    or dark machinery, which repeated would make a black block), each run
    of black pixels is taken from the row near the split (up to
    BLACK_SEARCH_ROOMS rooms above or below it) with the least black there, as long as it's solid where the
    row at source is. So the stretched hull looks closed, as the rest is.
    """
    pixels = np.asarray(hull).astype(np.int32)
    h, w = pixels.shape[:2]
    row = pixels[source].copy()
    # (black for this hull: darker than most of it, so a dark ship's own
    # dark panels aren't taken for gaps)
    solid_pixels = pixels[pixels[..., 3] > 200][:, :3].max(axis=1)
    black_level, black_share, search_rooms = black
    level = min(black_level, black_share * float(np.median(solid_pixels)))

    def black(line):
        return (line[:, 3] > 200) & (line[:, :3].max(axis=1) < level)

    solid = row[:, 3] > 200
    dark = black(row)
    reach = search_rooms * ROOM
    candidates = [r for r in range(split - reach, split + reach) if 0 <= r < h and r != source]
    x = 0
    while x < w:
        if not dark[x]:
            x += 1
            continue
        end = x
        # (a run of black, bridging gaps of a pixel or two)
        while end < w and (dark[end] or dark[end:end + 3].any()):
            end += 1
        best = None
        for r in candidates:
            line = pixels[r, x:end]
            if ((line[:, 3] > 200) != solid[x:end]).sum() > (end - x) // 10:
                continue
            key = (int(black(line).sum()), abs(r - source))
            if best is None or key < best[0]:
                best = (key, r)
        if best is not None and best[0][0] < dark[x:end].sum():
            row[x:end] = pixels[best[1], x:end]
        x = end
    return Image.fromarray(row[np.newaxis].astype(np.uint8))


def insert_row(image, split, add, line):
    """The image with `add` copies of the row of pixels `line` put in at row split."""
    w, h = image.size
    out = Image.new("RGBA", (w, h + add))
    out.paste(image.crop((0, 0, w, split)), (0, 0))
    for i in range(add):
        out.paste(line, (0, split + i))
    out.paste(image.crop((0, split, w, h)), (0, split + add))
    return out


def open_up(image, at, add):
    """The image with `add` clear rows put in at row `at`, as a room's interior when the room gets taller."""
    w, h = image.size
    out = Image.new("RGBA", (w, h + add))
    out.paste(image.crop((0, 0, w, at)), (0, 0))
    out.paste(image.crop((0, at, w, h)), (0, at + add))
    return out


def layout_text(layout, offsets):
    lines = ["X_OFFSET", str(offsets[0]), "Y_OFFSET", str(offsets[1]), "VERTICAL", "0"]
    return "\n".join(lines) + "\n" + layout.text()


def check_layout(name, layout, start_room):
    """Rooms don't overlap, every door's between its rooms, and every room can be reached."""
    cells = layout.cells()
    for x, y, a, b, vertical in layout.doors:
        sides = {cells.get((x - 1, y) if vertical else (x, y - 1), -1), cells.get((x, y), -1)}
        assert sides == {a, b}, "%s: the door at %d,%d isn't between rooms %d and %d" % (name, x, y, a, b)
        assert a != b, "%s: the door at %d,%d goes from room %d to itself" % (name, x, y, a)
    parts = layout.parts()
    assert len(parts) == 1, "%s: not every room can be reached from the piloting room: %s" % (
        name, [sorted(p) for p in parts if start_room not in p])
    assert min(c[0] for c in cells) >= 0 and min(c[1] for c in cells) >= 0, "%s: rooms off the grid" % name



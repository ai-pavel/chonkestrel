class Made:
    """A ship, made: its layout, images, blueprint and so on."""


def make_ship(dat, blueprints, cat, ship):
    vanilla = blueprints[ship["vanilla"]]
    vanilla_layout = vanilla.get("layout")
    img = ship["img"]
    layout = Layout(dat.text("data/%s.txt" % vanilla_layout))
    origin, cloak_offset, vanilla_mounts = layout_xml_parts(dat.text("data/%s.xml" % vanilla_layout))
    hull = hull_image(dat, vanilla.get("img"))
    cloak_name = (vanilla.findtext("cloakImage") or vanilla.get("img")).strip()
    cloak = dat.image("img/ship/%s_cloak.png" % cloak_name)
    mounts = [dict(m) for m in vanilla_mounts[:VANILLA_MOUNTS]]
    # (and the artillery's, which don't slide out, after them)
    artillery_mounts = [dict(m) for m in vanilla_mounts[VANILLA_MOUNTS:] if m.get("slide") == "no"]

    # The systems, from the vanilla ship's (each with where its console is,
    # as rooms that get taller move it)
    systems = []
    for elem in vanilla.find("systemList"):
        elem = ET.fromstring(ET.tostring(elem))
        if elem.tag in ship.get("drop", []):
            continue
        if elem.tag in ship.get("enable", {}):
            elem.set("start", "true")
            elem.set("power", str(ship["enable"][elem.tag]))
        room = layout.rooms[int(elem.get("room"))]
        systems.append({"elem": elem, "slot": slot_of(elem, room[2] * room[3]), "image": interior_name(elem),
                        "picture": None})

    # New systems in the vanilla ship's empty rooms
    for rid, spec in ship.get("systems", {}).items():
        x, y, w, h = layout.rooms[rid]
        elem = system_element(spec, rid)
        image, slot, picture = cat.find(elem.tag, w, h)
        systems.append({"elem": elem, "slot": slot, "image": image, "picture": picture})

    # Each cut, in turn: the rooms it goes through get taller (and so do
    # their interiors), and the rest move down
    added = 0
    new_rooms = []
    for cut in ship["cuts"]:
        line = cut["line"] + added
        add = cut["add"]
        grown = layout.crossing("y", line)
        for system in systems:
            rid = int(system["elem"].get("room"))
            if rid not in grown:
                continue
            x, y, w, h = layout.rooms[rid]
            at = line - y
            if system["slot"] is not None and system["slot"][0] >= 0:
                number, direction = system["slot"]
                cx, cy = number % w, number // w
                if cy >= at:
                    cy += add
                system["slot"] = (cy * w + cx, direction)
            picture = system["picture"]
            if picture is None and system["image"] is not None:
                picture = dat.image("img/ship/interior/%s.png" % system["image"])
            if picture is not None:
                system["picture"] = open_up(picture, at * ROOM, add * ROOM)
        first = max(layout.rooms) + 1
        rooms = [r[:4] + (None,) for r in cut["rooms"]]
        layout = stretch_layout(layout, "y", line, add, rooms)
        for i, (_, _, w, h, spec) in enumerate(cut["rooms"]):
            new_rooms.append((first + i, w, h, spec))

        split = origin[1] + line * ROOM + cut.get("shift", 0)
        source = split + cut.get("source", -1)
        black = ship.get("black", (BLACK_LEVEL, BLACK_SHARE, BLACK_SEARCH_ROOMS))
        hull = insert_row(hull, split, add * ROOM, clean_row(hull, split, source, black))
        cloak = insert(cloak, "y", split - cloak_offset[1], add * ROOM, source - cloak_offset[1])
        for m in mounts + artillery_mounts:
            if int(m["y"]) >= split:
                m["y"] = str(int(m["y"]) + add * ROOM)
        added += add

    # The new rooms' systems
    for rid, w, h, spec in new_rooms:
        if spec is None:
            continue
        elem = system_element(spec, rid)
        image, slot, picture = cat.find(elem.tag, w, h)
        systems.append({"elem": elem, "slot": slot, "image": image, "picture": picture})

    # Too tall for the screen: rows out of the hull above and below its rooms
    rooms_top = origin[1] + min(r[1] for r in layout.rooms.values()) * ROOM
    rooms_bottom = origin[1] + max(r[1] + r[3] for r in layout.rooms.values()) * ROOM
    rows = trim(hull, rooms_top - TRIM_MARGIN, rooms_bottom + TRIM_MARGIN, MAX_HEIGHT)
    if len(rows) < hull.height:
        print("  Note: %s is made %d pixels shorter, above and below its rooms" % (img, hull.height - len(rows)))
        hull = keep_rows(hull, rows)
        cloak = keep_rows(cloak, rows, cloak_offset[1])
        for m in mounts + artillery_mounts:
            m["y"] = str(moved_row(rows, int(m["y"])))
        origin = (origin[0], moved_row(rows, origin[1]))

    cells = layout.cells()
    grid_w = (max(c[0] for c in cells) + 1) * ROOM
    grid_h = (max(c[1] for c in cells) + 1) * ROOM
    rooms_box = (origin[0], origin[1], origin[0] + grid_w, origin[1] + grid_h)
    slots = ship.get("weapon_slots", WEAPON_SLOTS)
    mounts += more_mounts(hull, mounts, slots - len(mounts), rooms_box)
    # The artillery systems' mounts come straight after the weapon slots'
    # (see Artillery.hardpoint)
    artillery = len([s for s in systems if s["elem"].tag == "artillery"])
    mounts += nose_mounts(hull, artillery_mounts, artillery)

    made = Made()
    made.ship = ship
    made.vanilla = vanilla
    made.layout = layout
    made.hull = hull
    made.cloak = cloak
    made.origin = origin
    made.cloak_offset = cloak_offset
    made.floor = floor_image(layout)
    made.floor_offset = (origin[0] - FLOOR_PADDING, origin[1] - FLOOR_PADDING)
    made.mounts = mounts
    made.offsets = (round((CENTRE[0] + origin[0] - hull.width / 2) / ROOM),
                    round((CENTRE[1] + origin[1] - hull.height / 2) / ROOM))
    made.ellipse = layout.ellipse

    # The interiors: the generated ones get files of their own
    made.interiors = {}
    for system in systems:
        elem = system["elem"]
        set_slot(elem, system["slot"])
        if system["picture"] is not None:
            name = "%s_room%s_%s" % (img, elem.get("room"), elem.tag)
            made.interiors[name] = system["picture"]
            elem.set("img", name)
        elif system["image"] is not None:
            elem.set("img", system["image"])
        else:
            elem.attrib.pop("img", None)
    made.systems = [s["elem"] for s in systems]
    made.blueprint = blueprint_xml(made)
    check(made)
    return made


# The systems the crew can man, at their consoles
MANNED_SYSTEMS = {"pilot", "engines", "shields", "weapons", "sensors", "doors", "drones", "hacking", "mind",
                  "oxygen", "artillery"}


def crew_entries(ship):
    """Each of its crew lists (race, system, which of those systems, how many): one at a console, or (with a
    fourth element) as many as that waiting on a teleporter pad, when it has more crew than consoles."""
    return [entry if len(entry) == 4 else entry + (1,) for entry in ship["crew"]]


def system_rooms(made, name):
    return [int(e.get("room")) for e in made.systems if e.tag == name]


def blueprint_xml(made):
    ship = made.ship
    vanilla = made.vanilla
    bp = ET.Element("shipBlueprint", {"name": ship["name"], "layout": ship["img"], "img": ship["img"]})
    ET.SubElement(bp, "class").text = ship["class"]
    ET.SubElement(bp, "name").text = ship["title"]
    ET.SubElement(bp, "desc").text = ship["desc"]
    slots = ship.get("weapon_slots", WEAPON_SLOTS)
    ET.SubElement(bp, "weaponSlots").text = str(slots)
    ET.SubElement(bp, "droneSlots").text = str(ship["drone_slots"])

    # The weapons systems listed in order (the vanilla ship's first), so each
    # controls its share of the slots, in order (see Ship.assignWeaponHardpoints)
    system_list = ET.SubElement(bp, "systemList")
    for elem in made.systems:
        system_list.append(elem)

    main = [e for e in made.systems if e.tag not in SUBSYSTEMS]
    medbay_rooms = {e.get("room") for e in main if e.tag == "medbay"}
    count = len([e for e in main if not (e.tag == "clonebay" and e.get("room") in medbay_rooms)])
    shields = len(system_rooms(made, "shields"))
    ET.SubElement(bp, "maxCrew").text = str(MAX_CREW_MANY_SHIELDS if shields >= 3 else MAX_CREW)
    ET.SubElement(bp, "maxSystems").text = str(count)

    weapons_systems = len(system_rooms(made, "weapons"))
    assert weapons_systems == len(ship["weapons"]), "%s: weapons for %d systems, but it has %d" % (
        ship["img"], len(ship["weapons"]), weapons_systems)
    per_system = slots // weapons_systems
    weapon_list = ET.SubElement(bp, "weaponList", {"count": str(sum(map(len, ship["weapons"]))),
                                                   "missiles": str(ship["missiles"])})
    for i, names in enumerate(ship["weapons"]):
        for j, name in enumerate(names):
            attrs = {"name": name}
            if j == 0 and i > 0:
                attrs["slot"] = str(i * per_system + 1)
            ET.SubElement(weapon_list, "weapon", attrs)
    drone_list = ET.SubElement(bp, "droneList", {"count": str(len(ship["drones"])),
                                                 "drones": str(ship["drone_parts"])})
    for name in ship["drones"]:
        ET.SubElement(drone_list, "drone", {"name": name})

    ET.SubElement(bp, "health", {"amount": str(ship.get("health", int(vanilla.find("health").get("amount"))))})
    # Enough power for every system it starts with at once
    power = sum(int(e.get("power")) for e in main if e.get("start") != "false" and e.tag != "clonebay")
    ET.SubElement(bp, "maxPower", {"amount": str(power)})

    for race, system, which, amount in crew_entries(ship):
        rooms = system_rooms(made, system)
        ET.SubElement(bp, "crewCount", {"amount": str(amount), "class": race, "room": str(rooms[which])})
    for aug in ship["augments"]:
        ET.SubElement(bp, "aug", {"name": aug})
    for tag, text in (("maxCargo", MAX_CARGO), ("maxAugments", MAX_AUGMENTS), ("shipSize", 2),
                      ("opponentShips", OPPONENT_SHIPS), ("opponentShipsAtStart", OPPONENT_SHIPS_AT_START)):
        ET.SubElement(bp, tag).text = str(text)
    # The vanilla ship it's made from, which the hangar's Normal and Chonky
    # buttons switch between it and
    ET.SubElement(bp, "xftlVanillaShip").text = ship["vanilla"]
    ET.indent(bp, "    ")
    return ET.tostring(bp, encoding="unicode")


def check(made):
    """Check the ship's layout, its systems' and crew's rooms, and that its rooms and mounts are on its hull."""
    name = made.ship["img"]
    layout = made.layout
    pilot = system_rooms(made, "pilot")[0]
    check_layout(name, layout, pilot)
    # Its crew start at the consoles of the systems it starts with, one to each (but any it has no consoles
    # for, on a teleporter pad), so none stand about doing nothing
    taken = set()
    for race, system, which, amount in crew_entries(made.ship):
        elems = [e for e in made.systems if e.tag == system]
        assert which < len(elems), "%s: no %s system number %d for its crew" % (name, system, which + 1)
        elem = elems[which]
        assert elem.get("start") != "false", "%s: its %s's console is for a system it doesn't start with" % (
            name, system)
        if system == "teleporter":
            continue
        assert system in MANNED_SYSTEMS and amount == 1, "%s: %s %s crew at its %s, which has no console" % (
            name, amount, race, system)
        assert elem.get("room") not in taken, "%s: two crew at the console in room %s" % (name, elem.get("room"))
        taken.add(elem.get("room"))
    for elem in made.systems:
        assert int(elem.get("room")) in layout.rooms, "%s: no room %s for its %s" % (name, elem.get("room"), elem.tag)
        room = layout.rooms[int(elem.get("room"))]
        slot = elem.find("slot")
        if slot is not None and int(slot.findtext("number")) >= 0:
            assert int(slot.findtext("number")) < room[2] * room[3], "%s: %s's console is outside its room" % (
                name, elem.tag)
    alpha = np.asarray(made.hull)[..., 3]
    for rid, (x, y, w, h) in layout.rooms.items():
        for cx in range(x, x + w):
            for cy in range(y, y + h):
                px = made.origin[0] + cx * ROOM + ROOM // 2
                py = made.origin[1] + cy * ROOM + ROOM // 2
                inside = 0 <= px < made.hull.width and 0 <= py < made.hull.height and alpha[py, px] > 200
                assert inside, "%s: room %d is off the hull at %d,%d" % (name, rid, cx, cy)
    for m in made.mounts:
        x, y = int(m["x"]), int(m["y"])
        near = alpha[max(0, y - 4):y + 5, max(0, x - 4):x + 5]
        assert (near > 200).any(), "%s: the mount at %d,%d is off the hull" % (name, x, y)
    ET.fromstring(made.blueprint)


def check_names(dat, blueprints_made):
    """The weapons, drones and augments the ships start with all exist."""
    text = "".join(dat.text(n) for n in ("data/blueprints.xml", "data/dlcBlueprints.xml") if dat.has(n))
    base = dat.text("data/blueprints.xml")
    for made in blueprints_made:
        ship = made.ship
        for kind, names in (("weapon", sum(ship["weapons"], [])), ("drone", ship["drones"]),
                            ("aug", ship["augments"])):
            for name in names:
                single = re.sub(r"^XFTL_X[23]_", "", name)
                assert re.search(r'<%sBlueprint name="%s"' % (kind, single), text), \
                    "%s: no %s %s" % (ship["img"], kind, name)
                if single != name:
                    # (the twins and triples are only made of the base game's weapons and drones)
                    assert re.search(r'<%sBlueprint name="%s"' % (kind, single), base), \
                        "%s: %s isn't a base game %s, so there's no %s" % (ship["img"], single, kind, name)


def write(made):
    ship_dir = MOD / "img" / "ship"
    (ship_dir / "interior").mkdir(parents=True, exist_ok=True)
    (MOD / "img" / "customizeUI").mkdir(parents=True, exist_ok=True)
    img = made.ship["img"]
    made.hull.save(ship_dir / ("%s_base.png" % img))
    made.cloak.save(ship_dir / ("%s_cloak.png" % img))
    made.floor.save(ship_dir / ("%s_floor.png" % img))
    for i, (piece, _, _) in enumerate(gibs(made.hull)):
        piece.save(ship_dir / ("%s_gib%d.png" % (img, i + 1)))
    # (the vanilla ship's own shield, or the one it borrows, as the Red-Tail does the Kestrel's)
    vanilla_shield = (made.vanilla.findtext("shieldImage") or made.vanilla.get("img")).strip()
    rx, ry = made.ellipse[0], made.ellipse[1]
    shield = made.dat.image("img/ship/%s_shields1.png" % vanilla_shield)
    shield.resize((2 * rx, 2 * ry), Image.BICUBIC).save(ship_dir / ("%s_shields1.png" % img))
    miniature(made.hull).save(MOD / "img" / "customizeUI" / ("miniship_%s.png" % img))
    for name, picture in made.interiors.items():
        picture.save(ship_dir / "interior" / ("%s.png" % name))
    (MOD / "data" / ("%s.txt" % img)).write_text(layout_text(made.layout, made.offsets))
    (MOD / "data" / ("%s.xml" % img)).write_text(
        layout_xml(made.ship, made.vanilla.get("layout"), made.hull, made.origin, made.floor_offset,
                   made.cloak_offset, made.mounts))


def write_blueprints(entries):
    # (their classes and names as keys, with the English in text_blueprints.xml.append)
    entries = mod_text.keyed_blueprints(entries, "tools/race_ships.py")
    text = BLUEPRINTS_FILE.read_text() if BLUEPRINTS_FILE.exists() else ""
    if BEGIN_MARK in text:
        # (the blank lines either side of it kept to one gap, so they don't pile up)
        text = text[:text.index(BEGIN_MARK)].rstrip() + "\n\n" + text[text.index(END_MARK) + len(END_MARK):].lstrip()
    block = "\n".join([
        BEGIN_MARK,
        "<!--",
        "    The race ships: each race's Type A ship, made twice as big as the",
        "    Chonkestrel is (see doc/game/race-ships.md). Don't edit these by hand:",
        "    change tools/race_ships.py and run it again.",
        "-->",
    ] + entries + [END_MARK])
    BLUEPRINTS_FILE.write_text(text.rstrip() + "\n\n" + block + "\n")



def trim(hull, top, bottom, height):
    """
    The rows of the hull to keep for it to be at most `height` tall: half
    of the rows taken out below `bottom` and half above `top`, each the one
    most like the row next to it (see ship_variants.tail_rows).
    """
    excess = hull.height - height
    if excess <= 0:
        return list(range(hull.height))
    below = excess // 2
    above = excess - below
    kept_below = set(tail_rows(hull, bottom, hull.height - below))
    flipped = hull.transpose(Image.FLIP_TOP_BOTTOM)
    kept_above = {hull.height - 1 - y for y in tail_rows(flipped, hull.height - top, hull.height - above)}
    return sorted(kept_below & kept_above)


def floor_image(layout):
    """The floor under the rooms: grey, reaching a little past them, with a black edge."""
    cells = layout.cells()
    w = (max(c[0] for c in cells) + 1) * ROOM + 2 * FLOOR_PADDING
    h = (max(c[1] for c in cells) + 1) * ROOM + 2 * FLOOR_PADDING
    inside = np.zeros((h, w), dtype=bool)
    for x, y in cells:
        inside[FLOOR_PADDING + y * ROOM:FLOOR_PADDING + (y + 1) * ROOM,
               FLOOR_PADDING + x * ROOM:FLOOR_PADDING + (x + 1) * ROOM] = True

    def grow(mask, n):
        out = mask.copy()
        for _ in range(n):
            step = out.copy()
            step[1:] |= out[:-1]
            step[:-1] |= out[1:]
            step[:, 1:] |= out[:, :-1]
            step[:, :-1] |= out[:, 1:]
            out = step
        return out

    floor = grow(inside, FLOOR_MARGIN)
    inner = grow(inside, FLOOR_MARGIN - FLOOR_EDGE)
    pixels = np.zeros((h, w, 4), dtype=np.uint8)
    pixels[floor] = (0, 0, 0, 255)
    pixels[inner] = FLOOR_COLOUR
    return Image.fromarray(pixels)


def edges(alpha, x):
    """The top and bottom solid pixels of a column of the hull, or None."""
    solid = np.nonzero(alpha[:, x])[0]
    return (int(solid[0]), int(solid[-1])) if len(solid) else None


def more_mounts(hull, mounts, count, rooms_box):
    """
    The new weapon mounts: half along the top of the hull, sliding up, and
    half along the bottom, sliding down, each as far from the others on its
    side as it can be, over the rooms (rather than out on the hull's fins),
    where the hull's edge is outside the rooms and thick enough to hold it. Each is as far into the hull as the vanilla mounts on
    that side are.
    """
    alpha = np.asarray(hull)[..., 3] > 200
    w, h = hull.size
    result = []
    for side, n in (("up", (count + 1) // 2), ("down", count // 2)):
        on_side = [m for m in mounts if (int(m["y"]) < h // 2) == (side == "up")]
        insets = []
        for m in on_side:
            e = edges(alpha, int(m["x"]))
            if e:
                insets.append(int(m["y"]) - e[0] if side == "up" else e[1] - int(m["y"]))
        inset = max(0, min(MAX_MOUNT_INSET, round(sum(insets) / len(insets)))) if insets else MOUNT_INSET
        options = []
        for x in range(rooms_box[0], rooms_box[2]):
            e = edges(alpha, x)
            if not e:
                continue
            edge = e[0] if side == "up" else e[1]
            # (outside the rooms, on solid hull at least a few pixels thick)
            if side == "up" and edge >= rooms_box[1] or side == "down" and edge <= rooms_box[3]:
                continue
            step = 1 if side == "up" else -1
            if not all(alpha[edge + step * i, x] for i in range(min(12, h)) if 0 <= edge + step * i < h):
                continue
            options.append((x, edge + inset if side == "up" else edge - inset))
        taken = [int(m["x"]) for m in on_side]
        for _ in range(n):
            # (spread out, but not too far out from the rooms, on a fin)
            x, y = max(options, key=lambda o: min([abs(o[0] - t) for t in taken] or [w])
                       - MOUNT_REACH_COST * abs(o[1] - (rooms_box[1] if side == "up" else rooms_box[3])))
            taken.append(x)
            result.append({"x": str(x), "y": str(y), "rotate": "true", "mirror": "true" if side == "up" else "false",
                           "slide": side})
    return result


def nose_mounts(hull, vanilla, count):
    """
    The artillery systems' mounts: the vanilla ship's (on its nose), and if
    there are more artillery systems than it has mounts for, all of them
    spread out above and below where its mount was (ARTILLERY_SPACING apart),
    each as far in from the edge of the nose as the vanilla one.
    """
    if count <= len(vanilla):
        return vanilla[:count]
    assert vanilla, "No vanilla artillery mount to copy for %d artillery systems" % count
    alpha = np.asarray(hull)[..., 3] > 200
    template = vanilla[0]
    x, y = int(template["x"]), int(template["y"])

    def right_edge(row):
        solid = np.nonzero(alpha[row])[0]
        return int(solid[-1])

    inset = right_edge(y) - x
    result = []
    for i in range(count):
        row = y + round((i - (count - 1) / 2) * ARTILLERY_SPACING)
        m = dict(template)
        m["y"] = str(row)
        m["x"] = str(right_edge(row) - inset)
        result.append(m)
    return result


def layout_xml(ship, vanilla_layout, hull, origin, floor_offset, cloak_offset, mounts):
    w, h = hull.size
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!--",
        "    %s's layout, made by tools/race_ships.py from the vanilla" % ship["title"],
        "    %s.xml (copyright (c) 2012 by Subset Games). Don't edit it by hand." % vanilla_layout,
        "-->",
        "<FTL>",
        '<img x="-%d" y="-%d" w="%d" h="%d"/>' % (origin[0], origin[1], w, h),
        "<offsets>",
        '\t<floor x="%d" y="%d"/>' % floor_offset,
        '\t<cloak x="%d" y="%d"/>' % cloak_offset,
        "</offsets>",
        "<weaponMounts>",
    ]
    for m in mounts:
        x, y = int(m["x"]), int(m["y"])
        gib = 1 + (1 if x >= w // 2 else 0) + (2 if y >= h // 2 else 0)
        lines.append('\t<mount x="%d" y="%d" rotate="%s" mirror="%s" gib="%d" slide="%s"/>' % (
            x, y, m.get("rotate", "true"), m.get("mirror", "false"), gib, m["slide"]))
    lines += ["</weaponMounts>", "<explosion>"]
    for i, (_, x, y) in enumerate(gibs(hull)):
        low, high = GIB_DIRECTIONS[i]
        lines += [
            "\t<gib%d>" % (i + 1),
            '\t\t<velocity min="0.2" max="0.8"/>',
            '\t\t<direction min="%d" max="%d"/>' % (low, high),
            '\t\t<angular min="-0.6" max="0.6"/>',
            "\t\t<x>%d</x>" % x,
            "\t\t<y>%d</y>" % y,
            "\t</gib%d>" % (i + 1),
        ]
    lines += ["</explosion>", "</FTL>", ""]
    return "\n".join(lines)



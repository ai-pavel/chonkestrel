def insert(image, axis, split, add, source):
    """Put `add` copies of the row (or column) of pixels at `source` in at `split`."""
    w, h = image.size
    if axis == "y":
        out = Image.new("RGBA", (w, h + add))
        out.paste(image.crop((0, 0, w, split)), (0, 0))
        line = image.crop((0, source, w, source + 1))
        for i in range(add):
            out.paste(line, (0, split + i))
        out.paste(image.crop((0, split, w, h)), (0, split + add))
    else:
        out = Image.new("RGBA", (w + add, h))
        out.paste(image.crop((0, 0, split, h)), (0, 0))
        line = image.crop((source, 0, source + 1, h))
        for i in range(add):
            out.paste(line, (split + i, 0))
        out.paste(image.crop((split, 0, w, h)), (split + add, 0))
    return out



def hull_edges(hull, axis, line):
    """
    The first and last solid pixels of the hull along a row (for a long
    ship) or column (for a wide one) of the image.
    """
    w, h = hull.size
    alpha = hull.getchannel("A")
    if axis == "y":
        solid = [x for x in range(w) if alpha.getpixel((x, line)) > 200]
    else:
        solid = [y for y in range(h) if alpha.getpixel((line, y)) > 200]
    return (solid[0], solid[-1]) if solid else None


def extra_mounts(hull, axis, split, add_px, mounts, count):
    """
    The weapon mounts to put on the part of the hull that was put in: down
    its sides on a long ship, and along its top on a wide one. Each is as far
    from the edge of the hull as one of the vanilla ship's mounts on that side
    is from the edge where it is (so it sits on the hull the same way), and
    slides out the same way.
    """
    if count <= 0:
        return []
    w, h = hull.size
    centre = w // 2
    band = hull_edges(hull, axis, split + add_px // 2)
    result = []
    if axis == "y":
        # Down the sides, left first, spread out along the new rows
        sides = ["left", "right"]
        per_side = [(count + 1) // 2, count // 2]
        for side, n in zip(sides, per_side):
            # A mount on that side, sliding out sideways, to copy; ships whose
            # mounts all slide up (or down) get theirs a little way in from
            # the edge
            on_side = [m for m in mounts if (int(m["x"]) < centre) == (side == "left")]
            template = next((m for m in on_side if m.get("slide") == side), None)
            if template is not None:
                edges = hull_edges(hull, "y", int(template["y"]))
                inset = int(template["x"]) - edges[0] if side == "left" else edges[1] - int(template["x"])
                # (on the edge, even where the hull there is narrower)
                inset = max(0, min(inset, MAX_SIDE_MOUNT_INSET))
            else:
                template = on_side[0] if on_side else mounts[0]
                inset = SIDE_MOUNT_INSET
            for i in range(n):
                m = dict(template)
                m["y"] = str(split + add_px * (i + 1) // (n + 1))
                m["x"] = str(band[0] + inset if side == "left" else band[1] - inset)
                m["mirror"] = "true" if side == "left" else "false"
                m["slide"] = side
                result.append(m)
    else:
        # Along the top, spread out along the new columns, sliding up (or the
        # way the topmost vanilla mount does)
        template = min(mounts, key=lambda m: int(m["y"]))
        edges = hull_edges(hull, "x", int(template["x"]))
        inset = int(template["y"]) - edges[0]
        for i in range(count):
            m = dict(template)
            x = split + add_px * (i + 1) // (count + 1)
            m["x"] = str(x)
            m["y"] = str(band[0] + inset)
            m["mirror"] = "true" if x < centre else "false"
            if m.get("slide") in ("left", "right"):
                m["slide"] = "left" if x < centre else "right"
            result.append(m)
    return result



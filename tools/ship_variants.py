def auto_config_for(hull, vanilla, layout_name, layout, origin, shape, config):
    """
    The full set-up for a version made automatically (with "auto" set to its
    faction in SHIPS): the cut is the grid line in the middle half of the
    ship whose row (or column) of pixels changes least along it (unless it's
    given), and the new rows (or columns) get rooms wherever the hull is
    solid across them, which get the faction's systems, cloaking and (on a
    wide ship, if it has one) a second oxygen system.
    """
    axis = "y" if shape == "long" else "x"
    a = 1 if axis == "y" else 0
    b = 1 - a
    add = config.get("add", 4)
    cells = layout.cells()
    faction_systems = config.get("systems") or FACTION_SYSTEMS[config["auto"]]

    lo = min(c[a] for c in cells)
    hi = max(c[a] for c in cells) + 1
    across = [c[b] for c in cells]
    alpha = hull.getchannel("A")
    w, h = hull.size

    def free_places(cut, shift):
        """
        The places along the cut that the rooms it goes through (which get
        bigger) don't cover, where the hull is solid.
        """
        source = origin[a] + cut * ROOM + shift + config.get("source", -1)

        def solid(pos):
            start = origin[b] + pos * ROOM
            points = [(start + i, source) if axis == "y" else (source, start + i) for i in range(ROOM)]
            inside = [p for p in points if 0 <= p[0] < w and 0 <= p[1] < h and alpha.getpixel(p) > 200]
            return len(inside) >= ROOM * 0.9

        covered = set()
        for rid in layout.crossing(axis, cut):
            r = layout.rooms[rid]
            covered.update(range(r[b], r[b] + r[b + 2]))
        return covered, [pos for pos in range(min(across), max(across) + 1) if pos not in covered and solid(pos)]

    # Where to cut: a line without bits of hull that would hang off the ship,
    # with room for new rooms, whose pixels change least along it, nearest
    # the middle
    shift = config.get("shift", 0)
    if "cut" in config:
        cut = config["cut"]
    elif config.get("middle"):
        # Down the middle of the image, for a symmetric ship
        centre = hull.size[a] // 2
        cut = min(range(lo + 1, hi), key=lambda line: abs(origin[a] + line * ROOM - centre))
        shift = centre - (origin[a] + cut * ROOM)
    else:
        span = hi - lo
        lines = [line for line in range(lo + 1, hi) if lo + span / 4 <= line <= hi - span / 4]
        # (a hybrid can be cut further from its middle, to find a clean line)
        if config.get("avoid_dark"):
            lines = list(range(lo + 1, hi))
        lines = lines or [(lo + hi) // 2]
        cut = min(lines, key=lambda line: (bool(fragments(hull, axis, origin[a] + line * ROOM - 1)),
                                           len(free_places(line, 0)[1]) < 2,
                                           # (ships with a big teleporter want the most room)
                                           -len(free_places(line, 0)[1]) if config.get("roomy") else 0,
                                           # (a hybrid's lines through dark parts of its hull, or near its
                                           # join, would leave dark stripes when they're repeated)
                                           bad_line(hull, axis, origin[a] + line * ROOM - 1, config),
                                           streaks(hull, layout, origin, axis, origin[a] + line * ROOM - 1),
                                           abs(line - (lo + hi) / 2)))
    covered, places = free_places(cut, shift)

    middle = (min(across) + max(across) + 1) / 2
    big = config.get("teleporter")
    vanilla_systems = {e.tag for e in vanilla.find("systemList")}
    # The rooms a big teleporter has to leave: for cloaking, a second oxygen
    # system on a wide ship, and one more
    needed = 1 + ("cloaking" not in vanilla_systems) + (shape == "wide" and "oxygen" in vanilla_systems)
    wanted = len(faction_systems) + needed - 1

    def make_rooms(places):
        """
        Rooms two wide (or one, at the end of an odd run) and two long,
        split in half lengthways if there aren't enough of them (but never
        into rooms of one cell), apart from any that can't be reached; or
        None if the ship's split in two. With "teleporter" set to (pieces,
        length), the pieces nearest the middle are joined into one room for
        a big teleporter, which is returned as well.
        """
        runs = []
        for pos in places:
            if runs and runs[-1][-1] == pos - 1:
                runs[-1].append(pos)
            else:
                runs.append([pos])
        pieces = []
        for run in runs:
            pieces.append([(run[i], len(run[i:i + 2])) for i in range(0, len(run), 2)])
        count = sum(len(run) for run in pieces)
        length = 2
        if count * (add // length) < AUTO_ROOMS[shape]:
            length = 1

        def split(taken, tele_length, length):
            """The rooms for the rest of the pieces."""
            rooms = []
            for run in pieces:
                for start, size in run:
                    first_along = tele_length if (start, size) in taken else 0
                    # (a piece one wide isn't split into rooms of one cell)
                    step = length if size > 1 else 2
                    for along in range(first_along, add, step):
                        room = [0, 0, 0, 0]
                        room[b], room[b + 2] = start, size
                        room[a], room[a + 2] = along, min(step, add - along)
                        rooms.append(room)
            return rooms

        rooms = split(set(), 0, length)

        # The teleporter: the window of pieces nearest the middle, as big as
        # it can be (up to the size asked for) while leaving rooms for the
        # systems every version has, and about as many as there are systems
        # (or none, if there isn't room for one, so the ship keeps its own)
        teleporter = None
        if big and count:
            options = []
            for width in range(1, big[0] + 1):
                for tele_length in range(2, big[1] + 1, 2):
                    for ri, run in enumerate(pieces):
                        for i in range(len(run) - width + 1):
                            chosen = run[i:i + width]
                            start = chosen[0][0]
                            size = chosen[-1][0] + chosen[-1][1] - start
                            for rest_length in (2, 1):
                                rest = split(set(chosen), tele_length, rest_length)
                                if len(rest) >= needed:
                                    options.append((size * tele_length, -abs(len(rest) - wanted),
                                                    -abs(start + size / 2 - middle), chosen, tele_length, rest))
            if options:
                _, _, _, chosen, tele_length, rooms = max(options, key=lambda o: o[:3])
                teleporter = [0, 0, 0, 0]
                teleporter[b] = chosen[0][0]
                teleporter[b + 2] = chosen[-1][0] + chosen[-1][1] - chosen[0][0]
                teleporter[a], teleporter[a + 2] = 0, tele_length
                rooms = [teleporter] + rooms

        while True:
            new = stretch_layout(layout, axis, cut, add, [tuple(r) + (None,) for r in rooms])
            first = max(layout.rooms) + 1
            parts = new.parts()
            if len([p for p in parts if min(p) < first]) > len(layout.parts()):
                return None
            cut_off = [i for i in range(len(rooms)) if any(first + i in p and min(p) >= first for p in parts)]
            if not cut_off:
                return rooms, (teleporter if teleporter in rooms else None)
            rooms = [r for i, r in enumerate(rooms) if i not in cut_off]

    # If the two halves aren't joined up, there are rooms wherever a door
    # went across the cut too, even where the hull isn't solid
    made = make_rooms(places)
    if made is None:
        doors = {d[b] for d in layout.doors if d[a] == cut and d[4] == (0 if axis == "y" else 1)}
        made = make_rooms(sorted(set(places) | (doors - covered)))
    assert made is not None, "%s %s: cut at %d splits the ship" % (layout_name, shape, cut)
    rooms, teleporter = made

    # The systems, the most wanted in the rooms nearest the middle
    systems = list(faction_systems)
    vanilla_systems = {e.tag for e in vanilla.find("systemList")}
    extra = []
    if "cloaking" not in vanilla_systems:
        extra.append("cloaking")
    if shape == "wide" and "oxygen" in vanilla_systems:
        extra.append("oxygen")
    systems[2:2] = extra
    named = [None] * len(rooms)
    out = dict(config)
    if teleporter:
        # The ship's teleporter moves into its big room
        named[rooms.index(teleporter)] = "teleporter"
        if "teleporter" in vanilla_systems:
            out["drop"] = list(config.get("drop", [])) + ["teleporter"]
    order = sorted((i for i in range(len(rooms)) if named[i] is None),
                   key=lambda i: abs(rooms[i][b] + rooms[i][b + 2] / 2 - middle))
    # Without rooms for them all, cloaking and the second oxygen system come
    # first (after the faction's favourite)
    if len(order) < len(systems):
        faction = [system for system in systems if system not in extra]
        keep = max(1, len(order) - len(extra))
        systems = faction[:keep] + extra
    for i, system in zip(order, systems):
        named[i] = system
    # Cloaking always gets a room, even when there aren't many
    if "cloaking" in extra and "cloaking" not in named and order:
        named[order[min(len(order), len(systems)) - 1]] = "cloaking"

    out.update(cut=cut, add=add, shift=shift, rooms=[tuple(r) + (named[i],) for i, r in enumerate(rooms)])
    # A hybrid repeats the cleanest row (or column) of pixels near its cut
    # (see clean_source), rather than the one just before it
    if config.get("avoid_dark") and "source" not in config:
        out["source"] = clean_source(hull, axis, origin[a] + cut * ROOM + shift, config)
    return out


# The empty hold each bigger ship gets (see with_hold), a square this many
# cells each way: for the enemies' bulwarks (a twin on a long ship, a
# triple on a wide one), which only stand in rooms without a system
HOLD = {"long": 2, "wide": 3}


def with_hold(config, shape):
    """
    The config with an empty hold put in after its new rooms: HOLD[shape]
    more rows (or columns), with an empty square room of that size in them,
    as near the middle of the new rooms as it fits, and the rest of those
    rows filled with empty rooms (one or two cells wide), wherever the new
    rooms were (so where the hull's solid). The enemies' bulwarks stand in
    it (see doc/game/drone-sizes.md). If there's no run of cells that wide,
    it's a size smaller (a twin's), down to 2; and unchanged if there's no
    room even for that.
    """
    for size in range(HOLD[shape], 1, -1):
        held = hold_of_size(config, shape, size)
        if held is not None:
            return held
    return config


def hold_of_size(config, shape, size):
    """with_hold, for a hold of [size], or None if there's no run of cells that wide."""
    a = 1 if shape == "long" else 0  # The coordinate across the cut, in the new rows
    b = 1 - a  # Along the cut
    rooms = list(config["rooms"])
    along = sorted({pos for r in rooms for pos in range(r[b], r[b] + r[b + 2])})
    runs = []
    for pos in along:
        if runs and runs[-1][-1] == pos - 1:
            runs[-1].append(pos)
        else:
            runs.append([pos])
    middle = (along[0] + along[-1] + 1) / 2 if along else 0
    fitting = [run for run in runs if len(run) >= size]
    if not fitting:
        return None
    best = min(fitting, key=lambda run: abs((run[0] + run[-1] + 1) / 2 - middle))
    start = min(max(round((best[0] + best[-1] + 1) / 2 - size / 2), best[0]), best[-1] + 1 - size)

    # Right after the furthest the new rooms reach (which is past "add" when
    # the cut keeps the rooms it goes through as they are, as the new rooms
    # go next to them), with "add" that much bigger, so the rest of the ship
    # moves along to meet it
    after = max([config["add"]] + [r[a] + r[a + 2] for r in rooms])

    def room(at, length):
        r = [0, 0, 0, 0, None]
        r[b], r[a] = at, after
        r[b + 2], r[a + 2] = length, size
        return tuple(r)

    new = [room(start, size)]
    for run in runs:
        rest = [pos for pos in run if not start <= pos < start + size]
        while rest:
            piece = [rest[0]] + ([rest[1]] if len(rest) > 1 and rest[1] == rest[0] + 1 else [])
            new.append(room(piece[0], len(piece)))
            rest = rest[len(piece):]
    return dict(config, add=config["add"] + size, rooms=rooms + new)


def is_hold(room):
    """Whether a layout room (x, y, w, h) is big enough to be a hold (see with_hold)."""
    return room[2] >= min(HOLD.values()) and room[3] >= min(HOLD.values())


class TooTall(AssertionError):
    """A long ship that would be too tall for its window, even with its tail shortened."""


def make_version(dat, blueprints, classes, layout_name, shape, config, write=True, hold=True):
    layout = Layout(dat.text("data/%s.txt" % layout_name))
    origin, cloak_offset, mounts = layout_xml_parts(dat.text("data/%s.xml" % layout_name))
    if "auto" in config:
        config = auto_config(dat, blueprints, layout_name, layout, origin, shape, config)
    if hold:
        config = with_hold(config, shape)
    axis = "y" if shape == "long" else "x"
    a = 1 if axis == "y" else 0
    cut, add = config["cut"], config["add"]
    crossing = layout.crossing(axis, cut)
    if crossing:
        what = "which stay as they are" if config.get("crossing") == "keep" else "which get bigger"
        print("  Note: %s %s's cut goes through rooms %s, %s" % (layout_name, shape, crossing, what))
    new = stretch_layout(layout, axis, cut, add, config["rooms"], config.get("crossing") == "keep",
                         config.get("grow", ()))
    # A second cut further along (in the vanilla ship's grid), for ships
    # that widen cleanly on both sides of their middle but not down it
    second = config.get("second")
    if second:
        assert second["cut"] > cut, "%s %s: the second cut has to come after the first" % (layout_name, shape)
        new = stretch_layout(new, axis, second["cut"] + add, second["add"], second["rooms"])
        config = dict(config, rooms=list(config["rooms"]) + list(second["rooms"]))
    new.cells()
    # (Some crewless ships' rooms aren't joined up anyway)
    assert len(new.parts()) <= len(layout.parts()), "%s %s: not every room can be reached" % (layout_name, shape)

    # The image is cut at the cut line, or `shift` pixels from it (such as
    # down the middle of a ship whose middle isn't on a line of the grid),
    # and the row (or column) of pixels repeated is the one just before
    # that, or `source` pixels from it
    split = origin[a] + cut * ROOM + config.get("shift", 0)
    source = split + config.get("source", -1)
    add_px = add * ROOM
    new_name = "%s_%s" % (layout_name, shape)

    # Vanilla ships only use their first four mounts (the Rebel Fighter's
    # other four are nearly on top of them)
    if second:
        split2 = origin[a] + second["cut"] * ROOM + second.get("shift", 0)
        source2 = split2 + second.get("source", -1)
        add2_px = second["add"] * ROOM
    new_mounts = []
    for m in mounts[:VANILLA_MOUNTS]:
        m = dict(m)
        key = "y" if axis == "y" else "x"
        moved = int(m[key])
        if second and int(m[key]) >= split2:
            moved += add2_px
        if int(m[key]) >= split:
            moved += add_px
        m[key] = str(moved)
        new_mounts.append(m)

    def stretch(image, offset=0):
        """The image with the rows (or columns) put in at each cut."""
        out = insert(image, axis, split - offset, add_px, source - offset)
        if second:
            out = insert(out, axis, split2 + add_px - offset, add2_px, source2 + add_px - offset)
        return out

    def more_mounts(hull):
        """The new mounts, shared between the cuts."""
        count = config.get("mounts", MOUNTS[shape]) - len(new_mounts)
        if not second:
            return extra_mounts(hull, axis, split, add_px, new_mounts, count)
        first = extra_mounts(hull, axis, split, add_px, new_mounts, (count + 1) // 2)
        return first + extra_mounts(hull, axis, split2 + add_px, add2_px, new_mounts, count // 2)

    names = sorted(families(blueprints)[layout_name])
    images = {}
    rows = None
    for name in names:
        bp = blueprints[name]
        img = bp.get("img")
        if img not in images:
            hull = stretch(hull_image(dat, img))
            cloak_name = (bp.findtext("cloakImage") or img).strip()
            cloak = stretch(dat.image("img/ship/%s_cloak.png" % cloak_name), cloak_offset[a])
            # A long ship too tall for its window has its tail shortened
            # (the same rows taken out of every colour of it)
            if axis == "y":
                if rows is None:
                    rooms_end = origin[1] + max(r[1] + r[3] for r in new.rooms.values()) * ROOM
                    rooms_start = origin[1] + min(r[1] for r in new.rooms.values()) * ROOM
                    rows = tail_rows(hull, rooms_end + TAIL_MARGIN, MAX_LONG_HEIGHT, rooms_start - TAIL_MARGIN)
                hull = keep_rows(hull, rows)
                cloak = keep_rows(cloak, rows, cloak_offset[a])
            images[img] = (hull, cloak, cloak_name)
    if rows is not None:
        for m in new_mounts:
            m["y"] = str(moved_row(rows, int(m["y"])))
        # (the rooms move up with the rows taken out of the nose)
        origin = (origin[0], moved_row(rows, origin[1]))

    if not write:
        hull = next(iter(images.values()))[0]
        mounts_out = new_mounts + more_mounts(hull)
        return new, images, origin, mounts_out

    ship_dir = MOD / "img" / "ship"
    ship_dir.mkdir(parents=True, exist_ok=True)
    for img, (hull, cloak, cloak_name) in images.items():
        hull.save(ship_dir / ("%s_%s_base.png" % (img, shape)))
        cloak.save(ship_dir / ("%s_%s_cloak.png" % (cloak_name, shape)))
        for i, (piece, _, _) in enumerate(gibs(hull)):
            piece.save(ship_dir / ("%s_%s_gib%d.png" % (img, shape, i + 1)))

    first_hull = next(iter(images.values()))[0]
    new_mounts += more_mounts(first_hull)
    note = "%d %s %s." % (add, "rows longer" if axis == "y" else "columns wider", "at row %d" % cut if axis == "y" else "at column %d" % cut)
    (MOD / "data" / ("%s.txt" % new_name)).write_text(new.text())
    (MOD / "data" / ("%s.xml" % new_name)).write_text(
        layout_xml(layout_name, first_hull, origin, cloak_offset, new_mounts, note))

    # A blueprint for each ship using this layout, except the DLC copies,
    # which are named in their ship's xftlVariantOf
    result = []
    first_room = max(layout.rooms) + 1
    for name in names:
        if name.endswith("_DLC"):
            continue
        bp = blueprints[name]
        partners = [n for n in names if n == name or n == name + "_DLC"]
        img = bp.get("img")
        cloak_name = images[img][2]
        class_id = bp.find("class").get("id") if bp.find("class") is not None else None
        result.append(blueprint_xml(bp, partners, shape, new_name, "%s_%s" % (img, shape),
                                    "%s_%s" % (cloak_name, shape), config, first_room,
                                    classes.get(class_id)))
    print("Made %s (%s), for %s" % (new_name, "x".join(map(str, first_hull.size)), ", ".join(n for n in names if not n.endswith("_DLC"))))
    return result


def write_blueprints(entries):
    text = BLUEPRINTS_FILE.read_text() if BLUEPRINTS_FILE.exists() else ""
    if BEGIN_MARK in text:
        text = text[:text.index(BEGIN_MARK)] + text[text.index(END_MARK) + len(END_MARK):]
    block = "\n".join([
        BEGIN_MARK,
        "<!--",
        "    The bigger versions of the vanilla ships (see doc/game/ship-shapes.md). Don't",
        "    edit these by hand: change tools/ship_variants.py and run it again.",
        "-->",
    ] + entries + [END_MARK])
    BLUEPRINTS_FILE.write_text(text.rstrip() + "\n\n" + block + "\n")


def analyse(dat, layout_name):
    layout = Layout(dat.text("data/%s.txt" % layout_name))
    origin, _, _ = layout_xml_parts(dat.text("data/%s.xml" % layout_name))
    blueprints = vanilla_blueprints(dat)
    img = blueprints[sorted(families(blueprints)[layout_name])[0]].get("img")
    hull = hull_image(dat, img)
    cells = layout.cells()
    xs = [c[0] for c in cells]
    ys = [c[1] for c in cells]
    print("%s: %d rooms, grid %d-%d x %d-%d, hull %s" % (layout_name, len(layout.rooms), min(xs), max(xs), min(ys), max(ys), hull.size))
    for rid in sorted(layout.rooms):
        print("  room %d: %s" % (rid, layout.rooms[rid]))
    for axis in ("y", "x"):
        a = 1 if axis == "y" else 0
        lo, hi = (min(ys), max(ys)) if axis == "y" else (min(xs), max(xs))
        for line in range(lo + 1, hi + 1):
            px = origin[a] + line * ROOM
            print("  %s cut %d: through rooms %s, streaks %d" % (
                "long" if axis == "y" else "wide", line, layout.crossing(axis, line),
                streaks(hull, layout, origin, axis, px - 1)))


def preview(dat, out_dir):
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    blueprints = vanilla_blueprints(dat)
    classes = class_names(dat)
    for layout_name, versions in SHIPS.items():
        for shape, config in versions.items():
            new, images, origin, mounts = make_version(dat, blueprints, classes, layout_name, shape, config, write=False)
            for img, (hull, _, _) in images.items():
                bg = Image.new("RGBA", hull.size, (40, 40, 60, 255))
                bg.alpha_composite(hull)
                plain = bg.copy()
                draw = ImageDraw.Draw(bg)
                for rid, (x, y, w, h) in new.rooms.items():
                    box = [origin[0] + x * ROOM, origin[1] + y * ROOM,
                           origin[0] + (x + w) * ROOM - 1, origin[1] + (y + h) * ROOM - 1]
                    draw.rectangle(box, fill=(225, 225, 225, 255), outline=(60, 60, 60, 255))
                    draw.text((box[0] + 3, box[1] + 2), str(rid), fill=(0, 0, 0, 255))
                for i, m in enumerate(mounts):
                    x, y = int(m["x"]), int(m["y"])
                    colour = (255, 60, 60, 255) if i >= VANILLA_MOUNTS else (60, 200, 255, 255)
                    for d in (draw, ImageDraw.Draw(plain)):
                        d.ellipse([x - 4, y - 4, x + 4, y + 4], outline=colour, width=2)
                        d.text((x + 6, y - 6), "%d%s" % (i, (m.get("slide") or "-")[0]), fill=colour)
                sheet = Image.new("RGBA", (hull.size[0] * 2 + 10, hull.size[1]), (0, 0, 0, 255))
                sheet.paste(plain, (0, 0))
                sheet.paste(bg, (hull.size[0] + 10, 0))
                sheet.resize((sheet.width * 2, sheet.height * 2), Image.NEAREST).save(out / ("%s_%s.png" % (img, shape)))
    print("Previews in", out)


def explore(dat, layout_name, out_dir):
    """Draw the hull stretched at every line of the grid (and half way between), to pick a cut."""
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    layout = Layout(dat.text("data/%s.txt" % layout_name))
    origin, _, _ = layout_xml_parts(dat.text("data/%s.xml" % layout_name))
    blueprints = vanilla_blueprints(dat)
    img = blueprints[sorted(families(blueprints)[layout_name])[0]].get("img")
    hull = hull_image(dat, img)
    cells = layout.cells()
    for axis in ("y", "x"):
        a = 1 if axis == "y" else 0
        lo = min(c[a] for c in cells)
        hi = max(c[a] for c in cells) + 1
        tiles = []
        for line in range(lo, hi + 1):
            for half in (0, ROOM // 2):
                split = origin[a] + line * ROOM + half
                if split >= hull.size[a]:
                    continue
                tile = Image.new("RGBA", hull.size, (40, 40, 60, 255))
                tile = insert(tile, axis, split, 2 * ROOM, split - 1)
                tile.alpha_composite(insert(hull, axis, split, 2 * ROOM, split - 1))
                ImageDraw.Draw(tile).text((4, 4), "%s %d%s" % (axis, line, "+half" if half else ""), fill=(255, 255, 0, 255))
                tiles.append(tile)
        w = sum(t.width for t in tiles) + 8 * len(tiles)
        h = max(t.height for t in tiles)
        sheet = Image.new("RGBA", (w, h), (0, 0, 0, 255))
        x = 0
        for t in tiles:
            sheet.paste(t, (x, 0))
            x += t.width + 8
        sheet.save(out / ("%s_%s.png" % (layout_name, "long" if axis == "y" else "wide")))
    print("Explored", layout_name)


def main():
    dat = Dat(sys.argv[1])
    if len(sys.argv) > 4 and sys.argv[2] == "--explore":
        explore(dat, sys.argv[3], sys.argv[4])
        return
    if len(sys.argv) > 3 and sys.argv[2] == "--analyse":
        analyse(dat, sys.argv[3])
        return
    if len(sys.argv) > 3 and sys.argv[2] == "--preview":
        preview(dat, sys.argv[3])
        return

    blueprints = vanilla_blueprints(dat)
    classes = class_names(dat)
    entries = []
    without_hold = []
    for layout_name, versions in SHIPS.items():
        for shape, config in versions.items():
            # (a long ship that its hold would make too tall for its window
            # goes without one, see with_hold)
            try:
                entries += make_version(dat, blueprints, classes, layout_name, shape, config)
            except TooTall:
                without_hold.append("%s %s" % (layout_name, shape))
                entries += make_version(dat, blueprints, classes, layout_name, shape, config, hold=False)
    write_blueprints(entries)
    if without_hold:
        print("Without a hold, as they'd be too tall: %s" % ", ".join(without_hold))


if __name__ == "__main__":
    main()

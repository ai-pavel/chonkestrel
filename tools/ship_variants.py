def tail_rows(hull, first, max_height, nose_end=0):
    """
    The rows of the hull to keep for it to be at most max_height tall, taking
    rows out from first down (below the rooms) one at a time, each the one
    most like the row under it, so the tail's just shorter where it's
    straight. All of them, if it isn't too tall. Once the tail's as short as
    it goes, the nose is shortened the same way, above nose_end (above the
    rooms): which moves the rooms up, see moved_row.
    """
    import numpy as np
    rows = list(range(hull.height))
    excess = hull.height - max_height
    if excess <= 0:
        return rows
    pixels = np.asarray(hull, dtype=np.int32)
    nose = nose_end
    for _ in range(excess):
        kept = pixels[rows]
        differences = np.abs(kept[first:-1] - kept[first + 1:]).sum(axis=(1, 2))
        if len(differences):
            del rows[first + int(np.argmin(differences))]
            continue
        if nose < 2:
            raise TooTall("the tail and nose are too short to take %d rows out of" % excess)
        differences = np.abs(kept[:nose - 1] - kept[1:nose]).sum(axis=(1, 2))
        del rows[int(np.argmin(differences))]
        nose -= 1
        first -= 1
    return rows


def keep_rows(image, rows, offset=0):
    """The image with only the rows of the hull in rows (see tail_rows), for
    an image offset rows above the hull (such as its cloak)."""
    import numpy as np
    removed = set(range(max(rows) + 1)) - set(rows)
    keep = [y for y in range(image.height) if y + offset not in removed]
    return Image.fromarray(np.ascontiguousarray(np.asarray(image)[keep]), "RGBA")


def moved_row(rows, y):
    """Where row y of the hull goes once only the rows in rows are kept."""
    return sum(1 for row in rows if row < y)


def gibs(hull):
    w, h = hull.size
    cx, cy = w // 2, h // 2
    result = []
    for box in [(0, 0, cx, cy), (cx, 0, w, cy), (0, cy, cx, h), (cx, cy, w, h)]:
        piece = hull.crop(box)
        # (a quarter with no hull in it gets a single clear pixel)
        bbox = piece.getbbox() or (0, 0, 1, 1)
        result.append((piece.crop(bbox), box[0] + bbox[0], box[1] + bbox[1]))
    return result


def streaks(hull, layout, origin, axis, line_px):
    """How much the row (or column) at line_px changes along it, outside the rooms."""
    covered = set()
    for x, y, w, h in layout.rooms.values():
        if axis == "y":
            covered.update(range(origin[0] + x * ROOM, origin[0] + (x + w) * ROOM))
        else:
            covered.update(range(origin[1] + y * ROOM, origin[1] + (y + h) * ROOM))
    w, h = hull.size
    total = 0
    length = w if axis == "y" else h
    prev = None
    for i in range(length):
        if i in covered:
            prev = None
            continue
        p = hull.getpixel((i, line_px) if axis == "y" else (line_px, i))
        if prev is not None and p[3] > 128 and prev[3] > 128:
            total += sum(abs(p[c] - prev[c]) for c in range(3))
        prev = p
    return total


# A line (row or column) of a hybrid's hull is too dark to repeat (see
# bad_line) if more than this much of the hull along it is nearly black
DARK_LIMIT = 0.15
DARK_LEVEL = 50


def dark_fraction(hull, axis, line_px):
    """How much of the hull along a row (or column) is nearly black."""
    w, h = hull.size
    if axis == "y":
        pixels = [hull.getpixel((x, line_px)) for x in range(w)]
    else:
        pixels = [hull.getpixel((line_px, y)) for y in range(h)]
    solid = [p for p in pixels if p[3] > 200]
    if not solid:
        return 0
    return sum(1 for p in solid if max(p[:3]) < DARK_LEVEL) / len(solid)


def bad_line(hull, axis, line_px, config):
    """
    How bad a line of a hybrid's hull is to repeat (0 for every line of a
    vanilla ship): 2 if it's near the join (`avoid_rows`, where the halves'
    edges and outline change), 1 if it's dark (DARK_LIMIT), or else 0.
    """
    if not config.get("avoid_dark"):
        return 0
    lo, hi = config.get("avoid_rows", (0, -1)) if axis == "y" else (0, -1)
    if lo <= line_px <= hi:
        return 2
    return 1 if dark_fraction(hull, axis, line_px) > DARK_LIMIT else 0


def clean_source(hull, axis, split, config):
    """
    The row (or column) of a hybrid's hull to repeat when it's stretched at
    split, as an offset from it: the one up to a room before it that isn't
    near the join or dark (see bad_line) and whose hull is closest to as wide
    as at the split itself, so the stretched part has no dark stripes and
    meets the rest without a step.
    """
    def edges(line):
        alpha = hull.getchannel("A")
        n = hull.size[0] if axis == "y" else hull.size[1]
        solid = [i for i in range(n) if alpha.getpixel((i, line) if axis == "y" else (line, i)) > 200]
        return (solid[0], solid[-1]) if solid else None

    target = edges(split - 1)
    best = None
    for offset in range(-1, -ROOM, -1):
        line = split + offset
        if line < 0:
            break
        own = edges(line)
        if own is None or target is None:
            continue
        mismatch = abs(own[0] - target[0]) + abs(own[1] - target[1])
        if fragments(hull, axis, line):
            continue
        key = (bad_line(hull, axis, line, config), mismatch > 4, dark_fraction(hull, axis, line), mismatch)
        if best is None or key < best[0]:
            best = (key, offset)
    return best[1] if best else -1


def fragments(hull, axis, line_px):
    """
    The short bits of hull, apart from the rest, along the row (or column) at
    line_px: repeated, they'd make lines hanging off the ship.
    """
    alpha = hull.getchannel("A")
    w, h = hull.size
    runs = []
    start = None
    for i in range(w if axis == "y" else h):
        solid = alpha.getpixel((i, line_px) if axis == "y" else (line_px, i)) > 128
        if solid and start is None:
            start = i
        elif not solid and start is not None:
            runs.append(i - start)
            start = None
    return [run for run in runs if run < 8]



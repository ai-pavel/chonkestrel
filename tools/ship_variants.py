class Dat:
    def __init__(self, path):
        self.data = Path(path).read_bytes()
        header, entry, count, names_size = struct.unpack(">HHII", self.data[4:16])
        table = self.data[header + count * entry:header + count * entry + names_size]
        self.files = {}
        for i in range(count):
            e = self.data[header + i * entry:header + (i + 1) * entry]
            name_offset = int.from_bytes(e[5:8], "big")
            offset, _, size = struct.unpack(">III", e[8:20])
            self.files[table[name_offset:table.index(b"\0", name_offset)].decode()] = (offset, size)

    def read(self, name):
        offset, size = self.files[name]
        return self.data[offset:offset + size]

    def text(self, name):
        return self.read(name).decode("utf-8", "replace")

    def image(self, name):
        return Image.open(io.BytesIO(self.read(name))).convert("RGBA")

    def has(self, name):
        return name in self.files


# --- Layouts ---------------------------------------------------------------

class Layout:
    def __init__(self, txt):
        words = txt.split()
        self.ellipse = None
        self.rooms = {}
        self.doors = []
        i = 0
        while i < len(words):
            word = words[i]
            if word == "ROOM":
                rid, x, y, w, h = map(int, words[i + 1:i + 6])
                self.rooms[rid] = [x, y, w, h]
                i += 6
            elif word == "DOOR":
                self.doors.append(list(map(int, words[i + 1:i + 6])))
                i += 6
            elif word == "ELLIPSE":
                self.ellipse = list(map(int, words[i + 1:i + 5]))
                i += 5
            elif word in ("X_OFFSET", "Y_OFFSET", "VERTICAL", "HORIZONTAL"):
                i += 2
            else:
                i += 1

    def text(self):
        lines = ["ELLIPSE"] + [str(v) for v in self.ellipse]
        for rid in sorted(self.rooms):
            lines += ["ROOM", str(rid)] + [str(v) for v in self.rooms[rid]]
        for door in self.doors:
            lines += ["DOOR"] + [str(v) for v in door]
        return "\n".join(lines) + "\n"

    def cells(self):
        cells = {}
        for rid, (x, y, w, h) in self.rooms.items():
            for cx in range(x, x + w):
                for cy in range(y, y + h):
                    assert (cx, cy) not in cells, "rooms %s and %s overlap" % (cells[(cx, cy)], rid)
                    cells[(cx, cy)] = rid
        return cells

    def crossing(self, axis, line):
        """The rooms the line between rows (or columns) line-1 and line goes through."""
        lo = 1 if axis == "y" else 0
        return [rid for rid, r in self.rooms.items() if r[lo] < line < r[lo] + r[lo + 2]]

    def parts(self, starts=None):
        """The groups of rooms that can be reached from each other."""
        neighbours = {rid: set() for rid in self.rooms}
        for x, y, a, b, _ in self.doors:
            if a >= 0 and b >= 0:
                neighbours[a].add(b)
                neighbours[b].add(a)
        groups = []
        left = set(self.rooms)
        while left:
            start = min(left)
            seen = {start}
            queue = deque([start])
            while queue:
                for n in neighbours[queue.popleft()]:
                    if n not in seen:
                        seen.add(n)
                        queue.append(n)
            groups.append(seen)
            left -= seen
        return groups

    def connected(self):
        return len(self.parts()) == 1


def stretch_layout(layout, axis, cut, add, new_rooms, keep_crossing=False, grow=()):
    """
    The layout with `add` rows (or columns) put in at the cut, and the new
    rooms. A room the cut goes through gets bigger, or with keep_crossing,
    stays as it is (and the new rooms go next to it).
    """
    out = Layout("")
    out.ellipse = list(layout.ellipse)
    a = 1 if axis == "y" else 0  # The coordinate across the cut
    out.ellipse[a] += add * ROOM // 2

    kept = set()
    for rid, r in layout.rooms.items():
        r = list(r)
        if r[a] >= cut:
            r[a] += add
        elif r[a] + r[a + 2] > cut:
            if keep_crossing and rid not in grow:
                kept.add(rid)
            else:
                r[a + 2] += add
        out.rooms[rid] = r

    first_new = max(layout.rooms) + 1
    for i, (x, y, w, h, _) in enumerate(new_rooms):
        r = [x, y, w, h]
        r[a] += cut
        out.rooms[first_new + i] = r

    # The doors move with their rooms, apart from the ones on the cut
    # between the rows (or columns) either side of it, which go, and those
    # of a room that stays as it is
    for door in layout.doors:
        x, y, ra, rb, vertical = door
        pos = [x, y]
        across = (vertical == 0) if axis == "y" else (vertical == 1)
        if pos[a] == cut and across:
            continue
        in_kept = any(rid in kept and out.rooms[rid][a] <= pos[a] < out.rooms[rid][a] + out.rooms[rid][a + 2]
                      for rid in (ra, rb))
        if not in_kept and (pos[a] > cut or (pos[a] == cut and not across)):
            pos[a] += add
        out.doors.append([pos[0], pos[1], ra, rb, vertical])

    # Take out any door that isn't between its rooms any more
    cells = out.cells()

    def door_ok(door):
        x, y, ra, rb, vertical = door
        sides = {cells.get((x - 1, y) if vertical else (x, y - 1), -1), cells.get((x, y), -1)}
        return sides == {ra, rb}

    for door in [d for d in out.doors if not door_ok(d)]:
        print("  Note: taking out the door at %d,%d between rooms %d and %d" % tuple(door[:4]))
        out.doors.remove(door)

    # The new rooms get a door to each room next to them
    for rid in range(first_new, first_new + len(new_rooms)):
        x, y, w, h = out.rooms[rid]
        done = set()
        edges = []
        for cx in range(x, x + w):
            edges += [((cx, y - 1), (cx, y, 0)), ((cx, y + h), (cx, y + h, 0))]
        for cy in range(y, y + h):
            edges += [((x - 1, cy), (x, cy, 1)), ((x + w, cy), (x + w, cy, 1))]
        for cell, (dx, dy, vertical) in edges:
            other = cells.get(cell)
            if other is None or other == rid or other in done:
                continue
            if other >= first_new and other < rid:
                continue  # That room already made this door
            done.add(other)
            first, second = (other, rid) if (cell[0] < x or cell[1] < y) else (rid, other)
            out.doors.append([dx, dy, first, second, vertical])
    return out



#!/usr/bin/env python3
"""
Move the Chonkestrel mod's English text out of its data and into its English
text files, so it can be translated (see doc/tools/translations.md):

    python3 tools/extract_mod_text.py           # move any text it finds
    python3 tools/extract_mod_text.py --check   # only list it (exit 1 if any)

Every text the game shows that's written into the mod's data as it is, such
as an event's `<text>Some words.</text>` or a blueprint's `<title>Some
Words</title>`, becomes a key (`<text id="event_XFTL_X_c1_text"/>`, `<title
id="aug_XFTL_X_title"/>`), and its English goes into the English text file
for it, in a section for the file it came from:

- events (events*.xml.append, newEvents.xml.append, dlcEvents*.xml.append
  and so on): text_events.xml.append;
- blueprints (blueprints.xml.append, dlcBlueprints.xml.append):
  text_blueprints.xml.append;
- achievements (achievements.xml.append): text_achievements.xml.append.

So events can go on being written with their text in them, and this moves
it out afterwards. Text already in the text files stays as it is (it can be
edited there), and running this again changes nothing.

The keys are named as vanilla's are, by where they are:

- an event's text: `event_<EVENT>_text`, its choices' `event_<EVENT>_c1_choice`,
  `_c2_choice`..., and the events they lead to `event_<EVENT>_c1_text`, and
  so on down (`event_<EVENT>_c1_c2_choice`);
- the events in an eventList: `event_<LIST>_1_text`, `event_<LIST>_2_text`...;
- a textList's texts: `text_<LIST>_1`, `text_<LIST>_2`...;
- a ship's events: `ship_<SHIP>_destroyed_text`, `ship_<SHIP>_deadCrew_c1_choice`...;
- anything else in an event (such as removeCrew's clone text):
  `event_<EVENT>_<element>_text`;
- a blueprint's fields: `ship_<NAME>_class`, `aug_<NAME>_title`,
  `weapon_<NAME>_desc`... (see mod_text.BLUEPRINT_FIELDS);
- an achievement's: `<ID>_name` and `<ID>_desc`.

If the event's (or list's, ship's or blueprint's) name isn't the mod's own
(XFTL_...), the key gets `xftl_` in front, so it can't be one of vanilla's
(see mod_text.owned_key). If a key's already taken by another text, the new
one gets a number after it (`_2`).

The generated blocks (between `BEGIN generated by` and `END generated by`
markers) are left alone: their scripts write keys themselves (see
mod_text.keyed_blueprints, and tools/hybrid_sectors.py).
"""
import re
import sys
import xml.parsers.expat

import mod_text
from mod_text import DATA, owned_key, text_entry

# The vanilla file each kind of data file's English goes in
TARGETS = {"event": mod_text.TEXT_EVENTS, "blueprint": mod_text.TEXT_BLUEPRINTS,
           "achievement": mod_text.TEXT_ACHIEVEMENTS}

# The wrapper the data files are parsed in, as they're fragments with several
# elements at the top level, and Slipstream's namespaces
WRAP_START = b'<wrap xmlns:mod="mod" xmlns:mod-append="mod-append" xmlns:mod-overwrite="mod-overwrite">'
WRAP_END = b"</wrap>"

GENERATED = re.compile(rb"<!-- BEGIN generated by (\S+) -->.*?<!-- END generated by \1 -->", re.S)


class Node:
    def __init__(self, tag, attrs, start, parent):
        self.tag = tag
        self.attrs = attrs
        self.start = start        # where its start tag starts
        self.open_end = None      # just after its start tag
        self.end = None           # where its end tag starts (open_end for <x/>)
        self.close_end = None     # just after its end tag
        self.children = []
        self.parent = parent

    def descendants(self):
        for child in self.children:
            yield child
            yield from child.descendants()


def parse(data):
    """The elements in [data] (a data file's bytes), with where each one is in it."""
    source = WRAP_START + data + WRAP_END
    offset = len(WRAP_START)
    root = Node("wrap", {}, 0, None)
    stack = [root]
    parser = xml.parsers.expat.ParserCreate()

    def tag_end(position):
        # (the end of the tag starting at [position], skipping quoted values)
        quote = None
        while True:
            c = source[position:position + 1]
            if quote:
                if c == quote:
                    quote = None
            elif c in (b'"', b"'"):
                quote = c
            elif c == b">":
                return position + 1
            position += 1

    def start(tag, attrs):
        node = Node(tag, attrs, parser.CurrentByteIndex, stack[-1])
        node.open_end = tag_end(node.start)
        stack[-1].children.append(node)
        stack.append(node)

    def end(tag):
        node = stack.pop()
        if source[node.open_end - 2:node.open_end] == b"/>":
            node.end = node.close_end = node.open_end
        else:
            node.end = parser.CurrentByteIndex
            node.close_end = tag_end(node.end)

    parser.StartElementHandler = start
    parser.EndElementHandler = end
    parser.Parse(source, True)

    # The wrapper, with the positions back to those in [data]
    wrap = root.children[0]
    for node in wrap.descendants():
        for name in ("start", "open_end", "end", "close_end"):
            setattr(node, name, getattr(node, name) - offset)
    return wrap


class Extractor:
    def __init__(self, name, data, english):
        self.name = name
        self.data = data
        self.english = english        # every English key and text so far
        self.generated = [m.span() for m in GENERATED.finditer(data)]
        self.found = []               # (node, key, text, kind)
        self.unplaced = []            # text it doesn't know how to name

    def inline_text(self, node):
        """The text written into [node] (as it is in the file, escaped), or None."""
        if node.children or node.end == node.open_end or "id" in node.attrs or "load" in node.attrs:
            return None
        text = self.data[node.open_end:node.end].decode("utf-8").strip()
        if not text:
            return None
        assert "<" not in text, "%s: unexpected markup in %s" % (self.name, text)
        return text

    def in_generated(self, node):
        return any(start <= node.start < end for start, end in self.generated)

    def add(self, node, key, kind):
        text = self.inline_text(node)
        if text is not None and not self.in_generated(node):
            self.found.append((node, key, text, kind))

    def event(self, node, base):
        """An event (or something like one, such as a ship's <destroyed>), with keys starting [base]."""
        choice = 0
        for child in node.children:
            if child.tag == "text":
                self.add(child, base + "_text", "event")
            elif child.tag == "choice":
                choice += 1
                for part in child.children:
                    if part.tag == "text":
                        self.add(part, "%s_c%d_choice" % (base, choice), "event")
                    elif part.tag == "event":
                        self.event(part, "%s_c%d" % (base, choice))
            elif any(self.inline_text(n) is not None for n in child.descendants()) or self.inline_text(child):
                self.event(child, "%s_%s" % (base, child.tag))

    def run(self):
        root = parse(self.data)
        for node in root.children:
            name = node.attrs.get("name") or node.attrs.get("id") or ""
            if node.tag == "event":
                self.event(node, owned_key(name, "event_" + name))
            elif node.tag == "eventList":
                for i, child in enumerate(node.children, 1):
                    self.event(child, owned_key(name, "event_%s_%d" % (name, i)))
            elif node.tag == "textList":
                for i, child in enumerate(node.children, 1):
                    self.add(child, owned_key(name, "text_%s_%d" % (name, i)), "event")
            elif node.tag == "ship":
                for child in node.children:
                    self.event(child, owned_key(name, "ship_%s_%s" % (name, child.tag)))
            elif node.tag in mod_text.BLUEPRINT_FIELDS:
                for child in node.children:
                    if child.tag in mod_text.BLUEPRINT_FIELDS[node.tag]:
                        key = "%s_%s_%s" % (mod_text.BLUEPRINT_KEYS[node.tag], name, child.tag)
                        self.add(child, owned_key(name, key), "blueprint")
            elif node.tag == "achievement":
                for child in node.children:
                    if child.tag in ("name", "desc"):
                        self.add(child, owned_key(name, "%s_%s" % (name, child.tag)), "achievement")
            self.check_placed(node)
        return self.found

    def check_placed(self, top):
        # Any other text in an event (such as in a mod:findName patching
        # one) would be missed, so it's an error
        placed = {id(node) for node, _, _, _ in self.found}
        for node in [top] + list(top.descendants()):
            if node.tag == "text" and id(node) not in placed and self.inline_text(node) is not None \
                    and not self.in_generated(node):
                self.unplaced.append(node)

    def key_for(self, key, text):
        """
        [key], or the first free one after it (key_2...) if it's taken by
        other text, and whether it's new (rather than already with this text).
        """
        candidate, n = key, 1
        while candidate in self.english and self.english[candidate] != text:
            n += 1
            candidate = "%s_%d" % (key, n)
        if candidate != key:
            print("  %s: %s is taken by other text, using %s" % (self.name, key, candidate))
        new = candidate not in self.english
        self.english[candidate] = text
        return candidate, new


def rewrite(data, found):
    """[data] with each of [found]'s elements a key instead of text."""
    out = data
    for node, key, _, _ in sorted(found, key=lambda f: -f[0].start):
        start_tag = data[node.start:node.open_end].decode("utf-8")
        new = re.sub(r"\s*/?>$", "", start_tag) + ' id="%s"/>' % key
        out = out[:node.start] + new.encode("utf-8") + out[node.close_end:]
    return out


def add_entries(path, source, entries):
    """Add [entries] (text lines) to [path], at the end of [source]'s section."""
    begin = "<!-- BEGIN text of %s (see tools/extract_mod_text.py) -->" % source
    end = "<!-- END text of %s -->" % source
    text = path.read_text(encoding="utf-8") if path.exists() else mod_text.HEADER % path.name.replace(".append", "")
    if begin not in text:
        text = text.rstrip() + "\n\n" + begin + "\n" + end + "\n"
    at = text.index(end, text.index(begin))
    text = text[:at] + "".join(line + "\n" for line in entries) + text[at:]
    path.write_text(text, encoding="utf-8")


def sources():
    """The mod's data files that can have text in them (not the text files themselves)."""
    return sorted(p for p in DATA.glob("*.xml.append") if not p.name.startswith(("text_", "text-")))


def main():
    check = "--check" in sys.argv[1:]
    english = mod_text.english()
    total = 0
    problems = 0
    for path in sources():
        data = path.read_bytes()
        extractor = Extractor(path.name, data, english)
        found = extractor.run()
        for node in extractor.unplaced:
            line = data[:node.start].count(b"\n") + 1
            print("%s:%d: text that isn't in an event or blueprint it knows: %s" % (path.name, line, node.tag))
            problems += 1
        if not found:
            continue
        total += len(found)
        print("%s: %d texts" % (path.name, len(found)))
        if check:
            for node, key, text, _ in found:
                print("  %d: %s: %s" % (data[:node.start].count(b"\n") + 1, key, text[:60]))
            continue

        # Keys first (each text's own, or the next free one), then the
        # data file, then the English
        keyed = []
        by_target = {}
        for node, key, text, kind in found:
            key, new = extractor.key_for(key, text)
            keyed.append((node, key, text, kind))
            if new:
                by_target.setdefault(TARGETS[kind], []).append(text_entry(key, text))
        path.write_bytes(rewrite(data, keyed))
        for target, entries in by_target.items():
            add_entries(target, path.name, entries)

    if check:
        print("%d texts to move" % total if total else "No text to move")
        sys.exit(1 if total or problems else 0)
    print("Moved %d texts" % total if total else "No text to move")
    sys.exit(1 if problems else 0)


if __name__ == "__main__":
    main()

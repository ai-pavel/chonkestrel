"""
The Chonkestrel mod's text, for the scripts that write the mod's data (see
doc/tools/translations.md).

The mod's data refers to its text by key, as vanilla's does (`<text
id="..."/>` in events, `<class id="..."/>` in blueprints), and the English
for each key is in the mod's English text files, which append to vanilla's
(text_events.xml.append and so on). The translations are in
text-<lang>.xml.append, appending to vanilla's text-<lang>.xml.

The keys are named like vanilla's (`event_<NAME>_c1_choice`,
`ship_<NAME>_class`, see tools/extract_mod_text.py), from the name of the
event or blueprint they belong to. If that name is the mod's own (starting
with XFTL_), it can't be vanilla's, so neither can the key; otherwise the
key gets `xftl_` in front (see owned_key).

The generators (tools/ship_variants.py and so on) write the English for
their blueprints' classes and names into a block of their own in
text_blueprints.xml.append (see keyed_blueprints), like their blueprints'
block in autoBlueprints.xml.append.
"""
import re
from pathlib import Path

MOD = Path(__file__).resolve().parent.parent / "mods" / "chonkestrel"
DATA = MOD / "data"

# The mod's English text files, and the vanilla file each appends to
TEXT_EVENTS = DATA / "text_events.xml.append"
TEXT_BLUEPRINTS = DATA / "text_blueprints.xml.append"
TEXT_ACHIEVEMENTS = DATA / "text_achievements.xml.append"
ENGLISH_FILES = [TEXT_EVENTS, TEXT_BLUEPRINTS, TEXT_ACHIEVEMENTS,
                 DATA / "text_misc.xml.append", DATA / "text_sectorname.xml.append"]

# A new English text file's header
HEADER = """<!--
    The Chonkestrel mod's English text, appended to vanilla's
    %s: the text its data refers to by key (<text id="..."/> and
    so on). The translations are in text-<lang>.xml.append (see
    doc/tools/translations.md).
-->
"""

# The blueprint fields that are shown (the rest are numbers and names)
BLUEPRINT_FIELDS = {
    "shipBlueprint": ("class", "name", "desc"),
    "weaponBlueprint": ("title", "short", "desc", "tooltip", "flavorType"),
    "droneBlueprint": ("title", "short", "desc", "tooltip"),
    "augBlueprint": ("title", "desc"),
    "crewBlueprint": ("title", "short", "desc"),
    "systemBlueprint": ("title", "desc"),
}

# The first part of a blueprint's keys, as vanilla's (such as aug_X_title)
BLUEPRINT_KEYS = {
    "shipBlueprint": "ship",
    "weaponBlueprint": "weapon",
    "droneBlueprint": "drone",
    "augBlueprint": "aug",
    "crewBlueprint": "crew",
    "systemBlueprint": "system",
}


def owned_key(owner, key):
    """
    The key [key] for the text of an event or blueprint called [owner]: as
    it is if the owner's the mod's own (XFTL_...), or with xftl_ in front,
    so it can't be one of vanilla's keys.
    """
    return key if owner.startswith("XFTL_") else "xftl_" + key


def text_entry(key, text):
    """An English text file's line for [key], with [text] as it's written in the XML (escaped)."""
    return '<text name="%s">%s</text>' % (key, text.strip())


def read_texts(path):
    """The keys [path] has text for, and their text as it's written (escaped)."""
    if not path.exists():
        return {}
    text = path.read_text(encoding="utf-8")
    result = dict(re.findall(r'<text name="([^"]+)"\s*>(.*?)</text>', text, re.S))
    for key, value in re.findall(r'<mod:findName type="text" name="([^"]+)"\s*>\s*'
                                 r'<mod:setValue>(.*?)</mod:setValue>', text, re.S):
        result[key] = value
    return {k: v.strip() for k, v in result.items()}


def english():
    """Every key the mod has English text for, in all its English text files."""
    result = {}
    for path in ENGLISH_FILES:
        result.update(read_texts(path))
    return result


def write_generated_block(path, tool, entries, about):
    """
    Put [entries] (lines of text) in [path], in [tool]'s block: in place of
    the one that's there, so the blocks keep their order, or at the end.
    """
    begin = "<!-- BEGIN generated by %s -->" % tool
    end = "<!-- END generated by %s -->" % tool
    block = "\n".join([begin, "<!-- %s Don't edit these by hand: change %s and run it again. -->" % (about, tool)]
                      + entries + [end])
    text = path.read_text(encoding="utf-8") if path.exists() else HEADER % path.name.replace(".append", "")
    if begin in text:
        text = text[:text.index(begin)] + block + text[text.index(end) + len(end):]
    else:
        text = text.rstrip() + "\n\n" + block + "\n"
    path.write_text(text, encoding="utf-8")


def keyed_blueprints(entries, tool):
    """
    The generated blueprints [entries] (XML text, one blueprint or list
    each), with their classes, names and descriptions as keys rather than
    English (`<class id="ship_X_class"/>`), whose English goes in [tool]'s
    block of text_blueprints.xml.append.
    """
    texts = []

    def keyed(blueprint):
        kind, name = blueprint.group(1), blueprint.group(2)

        def replace(field):
            key = owned_key(name, "%s_%s_%s" % (BLUEPRINT_KEYS[kind], name, field.group(1)))
            texts.append(text_entry(key, field.group(2)))
            return '<%s id="%s"/>' % (field.group(1), key)

        # (within a blueprint, these are only ever its own fields)
        fields = "|".join(BLUEPRINT_FIELDS[kind])
        return re.sub(r"<(%s)>([^<]+)</\1>" % fields, replace, blueprint.group(0))

    kinds = "|".join(BLUEPRINT_FIELDS)
    result = [re.sub(r'<(%s) name="([^"]+)".*?</\1>' % kinds, keyed, entry, flags=re.S) for entry in entries]
    write_generated_block(TEXT_BLUEPRINTS, tool, texts, "The classes and names of the blueprints it makes.")
    return result

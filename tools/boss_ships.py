def preview(name, boss, ship, placed, out):
    """The boss, plain and with its rooms, systems and mounts, side by side."""
    hull = ship.hull
    bg = Image.new("RGBA", hull.size, (40, 40, 60, 255))
    bg.alpha_composite(hull)
    plain = bg.copy()
    draw = ImageDraw.Draw(bg)
    systems = {room: system for system, _, _, room in placed}
    ox, oy = ship.origin
    for rid, (x, y, w, h) in ship.layout.rooms.items():
        box = [ox + x * ROOM, oy + y * ROOM, ox + (x + w) * ROOM - 1, oy + (y + h) * ROOM - 1]
        draw.rectangle(box, fill=(225, 225, 225, 255), outline=(60, 60, 60, 255))
        draw.text((box[0] + 3, box[1] + 2), str(rid), fill=(0, 0, 0, 255))
        if rid in systems:
            draw.text((box[0] + 3, box[1] + 13), systems[rid][:6], fill=(160, 0, 0, 255))
    for x, y, a, b, vertical in ship.layout.doors:
        px, py = ox + x * ROOM, oy + y * ROOM
        if vertical:
            draw.line([px, py + 8, px, py + ROOM - 8], fill=(255, 160, 0, 255), width=3)
        else:
            draw.line([px + 8, py, px + ROOM - 8, py], fill=(255, 160, 0, 255), width=3)
    for i, m in enumerate(ship.mounts):
        x, y = int(m["x"]), int(m["y"])
        colour = (255, 60, 60, 255) if i >= VANILLA_MOUNTS else (60, 200, 255, 255)
        for d in (draw, ImageDraw.Draw(plain)):
            d.ellipse([x - 4, y - 4, x + 4, y + 4], outline=colour, width=2)
            d.text((x + 6, y - 6), "%d%s" % (i, (m.get("slide") or "-")[0]), fill=colour)
    sheet = Image.new("RGBA", (hull.width * 2 + 10, hull.height), (0, 0, 0, 255))
    sheet.paste(plain, (0, 0))
    sheet.paste(bg, (hull.width + 10, 0))
    sheet.save(out / ("%s.png" % name.lower()))



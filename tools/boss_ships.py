class Stretched:
    """A ship's layout, images and mounts, as it's stretched one way and then the other."""

    def __init__(self, dat, vanilla, layout_name):
        self.vanilla = vanilla
        self.layout = Layout(dat.text("data/%s.txt" % layout_name))
        self.origin, self.cloak_offset, mounts = layout_xml_parts(dat.text("data/%s.xml" % layout_name))
        self.mounts = [dict(m) for m in mounts[:VANILLA_MOUNTS]]
        self.hull = hull_image(dat, vanilla.get("img"))
        cloak_name = (vanilla.findtext("cloakImage") or vanilla.get("img")).strip()
        self.cloak = dat.image("img/ship/%s_cloak.png" % cloak_name)
        self.new_rooms = []
        # The rows and columns put in, as (axis, first, count), where axis is
        # 0 for columns and 1 for rows
        self.bands = []

    def stretch(self, shape, config, mount_count):
        """
        Put config["add"] rows (long) or columns (wide) in at config["cut"]
        (a line of the grid), and mount_count new weapon mounts on them. The
        vanilla rooms stay as they are, even one the cut goes through: the new
        rows (or columns) get rooms of their own later (see fill_new_parts).
        """
        axis = "y" if shape == "long" else "x"
        a = 1 if axis == "y" else 0
        cut, add = config["cut"], config["add"]
        self.layout = stretch_layout(self.layout, axis, cut, add, [], keep_crossing=True)
        self.bands.append((a, cut, add))

        split = self.origin[a] + cut * ROOM + config.get("shift", 0)
        source = split + config.get("source", -1)
        add_px = add * ROOM
        self.hull = insert(self.hull, axis, split, add_px, source)
        offset = self.cloak_offset[a]
        self.cloak = insert(self.cloak, axis, split - offset, add_px, source - offset)

        key = "y" if axis == "y" else "x"
        for m in self.mounts:
            if int(m[key]) >= split:
                m[key] = str(int(m[key]) + add_px)
        self.mounts += extra_mounts(self.hull, axis, split, add_px, self.mounts, mount_count)
        return "%d %s at %s %d" % (add, "rows" if axis == "y" else "columns", "row" if axis == "y" else "column", cut)

    def shorten(self):
        """Shorten the tail, if it's too tall for its window."""
        if self.hull.height <= MAX_HEIGHT:
            return
        rooms_end = self.origin[1] + max(r[1] + r[3] for r in self.layout.rooms.values()) * ROOM
        rows = tail_rows(self.hull, rooms_end + TAIL_MARGIN, MAX_HEIGHT)
        self.hull = keep_rows(self.hull, rows)
        self.cloak = keep_rows(self.cloak, rows, self.cloak_offset[1])
        for m in self.mounts:
            m["y"] = str(moved_row(rows, int(m["y"])))


# The sizes of the new rooms, biggest first: each part put in is filled with
# the biggest that fit, and 2x2s only where nothing bigger does
ROOM_SIZES = [(4, 4), (4, 3), (3, 4), (3, 3), (3, 2), (2, 3), (2, 2)]


def solid_cells(ship):
    """The cells of the grid the hull covers (90% of their pixels), in the rows and columns put in."""
    alpha = ship.hull.getchannel("A")
    w, h = ship.hull.size
    ox, oy = ship.origin
    covered = ship.layout.cells()
    max_x = (w - ox) // ROOM
    max_y = (h - oy) // ROOM
    result = set()
    # (the game doesn't allow rooms left of or above the grid's origin)
    for cx in range(0, max_x):
        for cy in range(0, max_y):
            if (cx, cy) in covered:
                continue
            if not any(first <= (cx, cy)[axis] < first + count for axis, first, count in ship.bands):
                continue
            px, py = ox + cx * ROOM, oy + cy * ROOM
            if px < 0 or py < 0 or px + ROOM > w or py + ROOM > h:
                continue
            solid = sum(1 for i in range(0, ROOM, 5) for j in range(0, ROOM, 5)
                        if alpha.getpixel((px + i, py + j)) > 200)
            if solid >= 0.9 * (ROOM // 5) ** 2:
                result.add((cx, cy))
    return result


def shared_wall(a, b):
    """A door between rooms a and b, as (x, y, vertical), or None if they aren't next to each other."""
    ax, ay, aw, ah = a
    bx, by, bw, bh = b
    if bx == ax + aw or ax == bx + bw:
        lo, hi = max(ay, by), min(ay + ah, by + bh)
        if lo < hi:
            return (max(ax, bx), (lo + hi - 1) // 2, 1)
    if by == ay + ah or ay == by + bh:
        lo, hi = max(ax, bx), min(ax + aw, bx + bw)
        if lo < hi:
            return ((lo + hi - 1) // 2, max(ay, by), 0)
    return None


def tile(free, connected, limit=300000):
    """
    The rooms to split the free cells into, as [x, y, w, h]: a search over
    every way of covering them with ROOM_SIZES (each step takes the first
    free cell, in rows from the top, and puts a room with its top left corner
    there, or leaves it empty), for the one that covers the most cells, with
    the fewest rooms and 2x2s, and joins every room up (connected). It stops
    after `limit` steps, with the best it's found.
    """
    order = sorted(free, key=lambda c: (c[1], c[0]))
    best = [None, None]
    steps = [0]

    def score(rooms):
        covered = sum(w * h for _, _, w, h in rooms)
        return covered, -len(rooms), -sum(1 for r in rooms if r[2] * r[3] == 4)

    def search(i, left, rooms, covered):
        steps[0] += 1
        if steps[0] > limit:
            return
        while i < len(order) and order[i] not in left:
            i += 1
        if best[0] is not None and covered + len(left) < best[0][0]:
            return
        if i == len(order):
            s = score(rooms)
            if (best[0] is None or s > best[0]) and connected(rooms):
                best[0], best[1] = s, list(rooms)
            return
        x, y = order[i]
        for w, h in ROOM_SIZES:
            cells = [(x + a, y + b) for a in range(w) for b in range(h)]
            if all(c in left for c in cells):
                rooms.append([x, y, w, h])
                search(i + 1, left - set(cells), rooms, covered + w * h)
                rooms.pop()
        search(i + 1, left - {order[i]}, rooms, covered)

    search(0, frozenset(free), [], 0)
    assert best[1] is not None, "the new parts can't be split into rooms that join the ship up"
    return best[1]


def add_rooms(layout, rooms):
    """Add the rooms to the layout, with a door to every room next to each. Returns their numbers."""
    first = max(layout.rooms) + 1
    new = list(range(first, first + len(rooms)))
    for rid, room in zip(new, rooms):
        layout.rooms[rid] = list(room)
    for a in new:
        for b in sorted(layout.rooms):
            if b == a or (b in new and b < a):
                continue
            wall = shared_wall(layout.rooms[a], layout.rooms[b])
            if wall is None:
                continue
            x, y, vertical = wall
            # (the door's first room is the one above it, or to its left)
            k = 0 if vertical else 1
            before, after = (b, a) if layout.rooms[b][k] < layout.rooms[a][k] else (a, b)
            layout.doors.append([x, y, before, after, vertical])
    return new


def fill_new_parts(ship):
    """
    Split the solid parts of the rows and columns put in into big rooms
    (see tile), each with a door to every room next to it, so that every
    room can be reached, including the vanilla ones the cuts parted.
    """
    free = solid_cells(ship)

    def connected(rooms):
        trial = Layout("")
        trial.rooms = {rid: list(r) for rid, r in ship.layout.rooms.items()}
        trial.doors = [list(d) for d in ship.layout.doors]
        add_rooms(trial, rooms)
        return trial.connected()

    ship.new_rooms = add_rooms(ship.layout, tile(free, connected))
    ship.layout.cells()
    assert ship.layout.connected(), "not every room can be reached"


def place_systems(stretched, boss):
    """
    Where each of the boss's systems goes, as a list of (system, power, most,
    room): in a vanilla room that had one like it, or else the biggest rooms
    left, new ones first.
    """
    vanilla_rooms = {}
    for elem in stretched.vanilla.find("systemList"):
        vanilla_rooms.setdefault(elem.tag, []).append(int(elem.get("room")))
    used = set()
    placed = []
    left = []
    for system, power, most in boss["systems"]:
        # (a teleporter sends as many boarders as its room holds, so it
        # always goes in one of the biggest new rooms)
        rooms = [r for r in vanilla_rooms.get(system, []) if r not in used and system not in FIRST_SYSTEMS]
        if rooms:
            used.add(rooms[0])
            placed.append((system, power, most, rooms[0]))
        else:
            left.append((system, power, most))

    def area(rid):
        _, _, w, h = stretched.layout.rooms[rid]
        return w * h

    free = [rid for rid in stretched.layout.rooms if rid not in used]

    # One new room's kept empty, as a hold for its bulwarks (see
    # doc/game/drone-sizes.md): the smallest that's at least 3x3 (or else
    # 2x2), if there are enough rooms for its systems without it
    for size in (3, 2):
        holds = [rid for rid in free if rid in stretched.new_rooms
                 and min(stretched.layout.rooms[rid][2:]) >= size]
        if holds and len(free) - 1 >= len(left):
            free.remove(min(holds, key=area))
            break
    free.sort(key=lambda rid: (-area(rid), rid not in stretched.new_rooms, rid))
    # (or, for a boss full of bulwarks, the smallest, keeping the big ones
    # for them and its crew)
    if boss.get("small_rooms_first"):
        free.sort(key=lambda rid: (area(rid), rid))
    left.sort(key=lambda s: (s[0] not in FIRST_SYSTEMS, s[0] not in BIG_SYSTEMS))
    assert len(free) >= len(left), "%s: %d rooms for %d systems" % (boss["kind"], len(free), len(left))
    for (system, power, most), rid in zip(left, free):
        placed.append((system, power, most, rid))
    return placed


def blueprint_xml(name, boss, img, placed, max_systems):
    """The boss's blueprint."""
    lines = [
        '<shipBlueprint name="%s" layout="%s" img="%s">' % (name, img, img),
        "\t<class>%s</class>" % boss["class"],
        "\t<name>%s</name>" % boss["title"],
        "\t<shipSize>%d</shipSize>" % boss.get("size", 3),
        "\t<xftlShape>%s</xftlShape>" % boss.get("shape", "colossal"),
        "\t<xftlBoss>%s</xftlBoss>" % boss["kind"],
        "\t<maxSystems>%d</maxSystems>" % max_systems,
        # (vanilla ships have three augments at most)
        "\t<maxAugments>%d</maxAugments>" % max(3, len(boss["augments"])),
        "\t<systemList>",
    ]
    for system, power, most, room in placed:
        lines.append('\t\t<%s power="%d" max="%d" room="%d" />' % (system, power, most, room))
    lines.append("\t</systemList>")
    lines.append('\t<weaponList count="%d" missiles="%d">' % (len(boss["weapons"]), boss["missiles"]))
    lines += ['\t\t<weapon name="%s" />' % w for w in boss["weapons"]]
    lines.append("\t</weaponList>")
    lines.append('\t<droneList count="%d" drones="%d">' % (len(boss["drones"]), boss["drone_parts"]))
    lines += ['\t\t<drone name="%s" />' % d for d in boss["drones"]]
    lines.append("\t</droneList>")
    lines.append('\t<health amount="%d" />' % boss["health"])
    # (the Mainframe's is all its systems need)
    power = boss.get("power") or sum(power for _, power, _ in boss["systems"])
    lines.append('\t<maxPower amount="%d" />' % power)
    for count, race in boss["crew"]:
        lines.append('\t<crewCount amount="%d" max="%d" class="%s" />' % (count, count, race))
    lines.append("\t<boardingAI>sabotage</boardingAI>")
    lines.append("\t<cloakImage>%s</cloakImage>" % img)
    lines += ['\t<aug name="%s" />' % aug for aug in boss["augments"]]
    lines.append("</shipBlueprint>")
    return "\n".join(lines)


# --- The Firewall: glued side by side -------------------------------------
#
# hybrid_ships.glue joins the front of one ship (above a grid line) to the
# back of another (below one). The Firewall's parts go side by side, so each
# is transposed (x and y swapped: its left becomes its top), glued, and the
# result transposed back.

# A weapon mount's slide, transposed
TRANSPOSED_SLIDE = {"up": "left", "left": "up", "down": "right", "right": "down"}


def transpose_layout(layout):
    out = Layout("")
    out.rooms = {rid: [y, x, h, w] for rid, (x, y, w, h) in layout.rooms.items()}
    # (a door in the left wall of a cell is in its top wall, transposed)
    out.doors = [[y, x, a, b, 1 - vertical] for x, y, a, b, vertical in layout.doors]
    e = layout.ellipse
    out.ellipse = [e[1], e[0], e[3], e[2]]
    return out


def transpose_mounts(mounts):
    out = []
    for m in mounts:
        t = dict(m, x=m["y"], y=m["x"])
        if m.get("slide") in TRANSPOSED_SLIDE:
            t["slide"] = TRANSPOSED_SLIDE[m["slide"]]
        out.append(t)
    return out


def transposed(race, layout, hull, cloak, origin, cloak_offset, mounts):
    """A part for hybrid_ships.glue, with x and y swapped."""
    return SimpleNamespace(
        race=race, layout=transpose_layout(layout), hull=hull.transpose(Image.Transpose.TRANSPOSE),
        cloak=cloak.transpose(Image.Transpose.TRANSPOSE), origin=(origin[1], origin[0]),
        cloak_offset=(cloak_offset[1], cloak_offset[0]), mounts=transpose_mounts(mounts))


def vanilla_part(dat, bp, race):
    """A vanilla ship's layout, images and mounts, transposed."""
    name = bp.get("layout")
    layout = Layout(dat.text("data/%s.txt" % name))
    origin, cloak_offset, mounts = layout_xml_parts(dat.text("data/%s.xml" % name))
    hull = hull_image(dat, bp.get("img"))
    cloak_name = (bp.findtext("cloakImage") or bp.get("img")).strip()
    cloak = dat.image("img/ship/%s_cloak.png" % cloak_name)
    return transposed(race, layout, hull, cloak, origin, cloak_offset, mounts)


def flagship_blueprint(dat):
    text = dat.text("data/bosses.xml")
    match = re.search(r'<shipBlueprint name="%s".*?</shipBlueprint>' % FLAGSHIP, text, re.S)
    return ET.fromstring(re.sub(r"<!--.*?-->", "", match.group(0), flags=re.S))


def middle_cuts(layout):
    """
    The grid lines (between rows, as the ship's transposed: between columns)
    to cut a half off it at, best first: nearest its middle, cutting
    through the fewest rooms.
    """
    rows = [c[1] for c in layout.cells()]
    lo, hi = min(rows), max(rows) + 1
    middle = (lo + hi) / 2
    return sorted(range(lo + 1, hi), key=lambda c: (abs(c - middle) + 2 * len(layout.crossing("y", c)), c))


def rows_middle(layout, rooms=None):
    """The middle of a (transposed) layout's columns, or of some of its rooms'."""
    xs = [(x, x + w) for rid, (x, y, w, h) in layout.rooms.items() if rooms is None or rid in rooms]
    return (min(a for a, _ in xs) + max(b for _, b in xs)) / 2


def glue_near(front, back, cuts_f, cuts_b, ideal, max_width=None):
    """
    hybrid_ships.glue, at the first of the cuts that works (cuts_f for the
    front, cuts_b for the back, best first), with the back moved along the
    join (in whole rows) as little from [ideal] as lets every room be
    reached.
    """
    for cut_f in cuts_f:
        for cut_b in cuts_b:
            for shift in sorted(range(round(ideal) - 8, round(ideal) + 9), key=lambda s: (abs(s - ideal), s)):
                try:
                    result = hybrid_ships.glue(front, back, cut_f, cut_b, shift)
                except AssertionError:
                    continue
                # (the hull's width, transposed, is how tall it is)
                if max_width is None or result[1].width <= max_width:
                    return result
    raise AssertionError("%s+%s: no way of gluing them" % (front.race, back.race))


def bridge(ship, cut, add, plate):
    """
    Put [add] columns in at grid line [cut], as ship.stretch does, as a
    plain plate of hull of colour [plate], wherever either side of the cut
    has hull (row by row), so the new section joins both sides up: with a
    dark edge where it ends, and a darker seam along each row of the grid.
    """
    import numpy as np
    split = ship.origin[0] + cut * ROOM
    # (the columns put in before, right of the cut, move along with it)
    ship.bands = [(axis, first + add if axis == 0 and first >= cut else first, count)
                  for axis, first, count in ship.bands]
    note = ship.stretch("wide", {"cut": cut, "add": add}, 0)
    add_px = add * ROOM
    for image, offset in ((ship.hull, 0), (ship.cloak, ship.cloak_offset[0])):
        pixels = np.asarray(image).copy()
        x = split - offset
        if not (0 < x and x + add_px < pixels.shape[1]):
            continue
        solid = (pixels[:, x - 1, 3] > 200) | (pixels[:, x + add_px, 3] > 200)
        colour = np.array(plate if image is ship.hull else cloak_colour(image), dtype=np.float32)
        band = np.zeros((pixels.shape[0], add_px, 4), dtype=np.float32)
        band[solid] = list(colour) + [255]
        rows = np.arange(pixels.shape[0])
        # (the seams between the panels, on the grid's rows, and the edges)
        seam = ((rows - ship.origin[1] + offset) % ROOM == 0) & solid
        edge = solid & ~(np.roll(solid, 1) & np.roll(solid, -1))
        band[seam, :, :3] *= PLATE_SEAM_SHADE
        band[edge, :, :3] *= PLATE_EDGE_SHADE
        pixels[:, x:x + add_px] = band.clip(0, 255).astype(np.uint8)
        image.paste(Image.fromarray(pixels, "RGBA"))
    return note


def cloak_colour(image):
    """The usual colour of a cloak image's solid pixels."""
    import numpy as np
    pixels = np.asarray(image)
    solid = pixels[..., 3] > 200
    return np.median(pixels[solid][:, :3], axis=0) if solid.any() else (80, 80, 110)


def plate_colour(hull):
    """The usual colour of a hull's solid pixels, a little darker, for its plain plate."""
    import numpy as np
    pixels = np.asarray(hull)
    solid = pixels[..., 3] > 200
    return np.median(pixels[solid][:, :3], axis=0) * PLATE_SHADE


def on_hull(hull, mount):
    """Whether a weapon mount is on the hull: there's hull right by it."""
    alpha = hull.getchannel("A")
    x, y = int(mount["x"]), int(mount["y"])
    return any(0 <= x + dx < hull.width and 0 <= y + dy < hull.height and alpha.getpixel((x + dx, y + dy)) > 200
               for dx in range(-MOUNT_REACH, MOUNT_REACH + 1, 2) for dy in range(-MOUNT_REACH, MOUNT_REACH + 1, 2))


def glue_firewall(dat, blueprints, boss):
    """
    The Firewall's hull: the left half of the first race's bomber, the
    flagship, and the right half of the second's, side by side, lined up
    on their middles. Returns it as a Stretched would be, with the
    vanilla systems of each part in the rooms they ended up as.
    """
    left_race, right_race = boss["glue"]
    bombers = hybrid_ships.CLASSES["BOMBERS"][0]
    left_bp, right_bp = blueprints[bombers[left_race]], blueprints[bombers[right_race]]
    flagship_bp = flagship_blueprint(dat)
    left = vanilla_part(dat, left_bp, left_race)
    middle = vanilla_part(dat, flagship_bp, "FLAGSHIP")
    # Two of the flagship's artillery rooms can't be reached from the rest
    # of it (vanilla's crew never went there): they're left out, and their
    # wings are just hull
    main = next(part for part in middle.layout.parts() if 0 in part)
    middle.layout.rooms = {rid: r for rid, r in middle.layout.rooms.items() if rid in main}
    middle.layout.doors = [d for d in middle.layout.doors
                           if (d[2] < 0 or d[2] in main) and (d[3] < 0 or d[3] in main)]
    right = vanilla_part(dat, right_bp, right_race)

    # (glue's limits are for hybrids: a hybrid's height, which here is the
    # Firewall's width, and its mounts)
    saved = hybrid_ships.MAX_HEIGHT, hybrid_ships.MAX_MOUNTS
    hybrid_ships.MAX_HEIGHT, hybrid_ships.MAX_MOUNTS = 100000, 100
    try:
        # The bomber's left half, and all of the flagship
        flag_first = min(y for _, y, _, _ in middle.layout.rooms.values())
        ideal = rows_middle(left.layout) - rows_middle(middle.layout)
        layout, hull, cloak, origin, offset, mounts, ids_left, ids_middle = glue_near(
            left, middle, middle_cuts(left.layout), [flag_first], ideal, MAX_HEIGHT)
        both = SimpleNamespace(race=left_race + "+FLAGSHIP", layout=layout, hull=hull, cloak=cloak,
                               origin=origin, cloak_offset=offset, mounts=mounts)

        # Then the other bomber's right half
        last = max(y + h for _, y, _, h in layout.rooms.values())
        flag_middle = rows_middle(layout, set(ids_middle.values()))
        ideal = flag_middle - rows_middle(right.layout)
        layout, hull, cloak, origin, offset, mounts, ids_both, ids_right = glue_near(
            both, right, [last], middle_cuts(right.layout), ideal, MAX_HEIGHT)
    finally:
        hybrid_ships.MAX_HEIGHT, hybrid_ships.MAX_MOUNTS = saved

    # The vanilla systems' rooms, where they ended up (the flagship's
    # first, then the bombers'; its artillery rooms are weapons rooms)
    systems = ET.Element("shipBlueprint")
    system_list = ET.SubElement(systems, "systemList")
    for bp, ids in ((flagship_bp, {k: ids_both[v] for k, v in ids_middle.items() if v in ids_both}),
                    (left_bp, {k: ids_both[v] for k, v in ids_left.items() if v in ids_both}),
                    (right_bp, ids_right)):
        for elem in bp.find("systemList"):
            room = int(elem.get("room"))
            if room in ids:
                tag = ARTILLERY_ROOMS if elem.tag == "artillery" else elem.tag
                ET.SubElement(system_list, tag, room=str(ids[room]))

    # The flagship's mounts first, as it's what's in the middle
    back = transpose_mounts(mounts)
    width = hull.height
    back.sort(key=lambda m: abs(int(m["x"]) - width / 2))

    # (a Stretched, so it can be widened, see below)
    ship = Stretched.__new__(Stretched)
    ship.layout = transpose_layout(layout)
    ship.hull = hull.transpose(Image.Transpose.TRANSPOSE)
    ship.cloak = cloak.transpose(Image.Transpose.TRANSPOSE)
    ship.origin = (origin[1], origin[0])
    ship.cloak_offset = (offset[1], offset[0])
    ship.mounts = back
    ship.vanilla = systems
    ship.new_rooms = []
    ship.bands = []
    ship.notes = ["glued from the left half of the %s bomber, the Rebel flagship, and the right half of the %s "
                  "bomber" % (left_race.title(), right_race.title())]

    # Then, as wide as it can be, with a plain section between the flagship
    # and each side (its hull's edge repeated), split into big rooms, for its
    # crew and bulwarks: the right one first, so the left's cut stays put
    flagship_rooms = [ship.layout.rooms[ids_both[v]] for v in ids_middle.values() if v in ids_both]
    left_seam = min(x for x, _, _, _ in flagship_rooms)
    right_seam = max(x + w for x, _, w, _ in flagship_rooms)
    add = min((MAX_WIDTH_TITAN - ship.hull.width) // ROOM, 2 * MAX_CONNECTOR)
    right_add = min(add // 2, MAX_CONNECTOR)
    left_add = min(add - right_add, MAX_CONNECTOR)
    plate = plate_colour(middle.hull)
    if right_add > 0:
        ship.notes.append(bridge(ship, right_seam, right_add, plate))
    if left_add > 0:
        ship.notes.append(bridge(ship, left_seam, left_add, plate))
    fill_new_parts(ship)

    # Its mounts: the flagship's (nearest the middle) that are still on the hull
    ship.mounts = [m for m in ship.mounts if on_hull(ship.hull, m)][:len(boss["weapons"])]
    return ship



def make_boss(dat, blueprints, name, boss):
    """Stretch the boss's vanilla ship (or glue it, see glue_firewall), and its layout, images and blueprint."""
    if "glue" in boss:
        ship = glue_firewall(dat, blueprints, boss)
        max_width = MAX_WIDTH_TITAN if boss.get("shape") == "titan" else MAX_WIDTH
        assert ship.hull.width <= max_width, "%s is %dpx wide" % (name, ship.hull.width)
        assert ship.hull.height <= MAX_HEIGHT, "%s is %dpx tall" % (name, ship.hull.height)
        assert len(ship.mounts) == len(boss["weapons"]), "%s has %d mounts" % (name, len(ship.mounts))
        placed = place_systems(ship, boss)
        cells = len(ship.layout.cells())
        crew = sum(count for count, _ in boss["crew"])
        assert cells >= crew * 3 // 2, "%s: %d cells for %d crew" % (name, cells, crew)
        return ship, placed

    base = boss["base"]
    vanilla = first_vanilla(blueprints, base)
    ship = Stretched(dat, vanilla, base)
    extra = len(boss["weapons"]) - len(ship.mounts)
    notes = [ship.stretch("wide", boss["wide"], (extra + 1) // 2)]
    notes.append(ship.stretch("long", boss["long"], extra // 2))
    ship.notes = notes
    fill_new_parts(ship)
    for rid, (x, y, _, _) in ship.layout.rooms.items():
        assert x >= 0 and y >= 0, "%s: room %d is at %d,%d, outside the grid" % (name, rid, x, y)
    ship.shorten()
    max_width = MAX_WIDTH_TITAN if boss.get("shape") == "titan" else MAX_WIDTH
    assert ship.hull.width <= max_width, "%s is %dpx wide" % (name, ship.hull.width)
    assert ship.hull.height <= MAX_HEIGHT, "%s is %dpx tall" % (name, ship.hull.height)
    assert len(ship.mounts) == len(boss["weapons"]), "%s has %d mounts" % (name, len(ship.mounts))

    placed = place_systems(ship, boss)
    cells = len(ship.layout.cells())
    crew = sum(count for count, _ in boss["crew"])
    assert cells >= crew * 3 // 2, "%s: %d cells for %d crew" % (name, cells, crew)
    return ship, placed


def write_boss(name, boss, ship, placed):
    img = boss.get("img") or "xftl_boss_%s" % boss["kind"].lower()
    ship_dir = MOD / "img" / "ship"
    ship_dir.mkdir(parents=True, exist_ok=True)
    ship.hull.save(ship_dir / ("%s_base.png" % img))
    ship.cloak.save(ship_dir / ("%s_cloak.png" % img))
    for i, (piece, _, _) in enumerate(gibs(ship.hull)):
        piece.save(ship_dir / ("%s_gib%d.png" % (img, i + 1)))

    (MOD / "data" / ("%s.txt" % img)).write_text(ship.layout.text())
    how = "Glued" if "glue" in boss else "Stretched"
    note = "%s into a size %d boss: %s." % (how, boss.get("size", 3), ", then ".join(ship.notes))
    xml = layout_xml(boss["base"], ship.hull, ship.origin, ship.cloak_offset, ship.mounts, note)
    (MOD / "data" / ("%s.xml" % img)).write_text(xml.replace("tools/ship_variants.py", "tools/boss_ships.py"))

    max_systems = len(placed)
    print("Made %s (%s): %d rooms, %d cells, %d mounts" % (
        name, "x".join(map(str, ship.hull.size)), len(ship.layout.rooms), len(ship.layout.cells()),
        len(ship.mounts)))
    return blueprint_xml(name, boss, img, placed, max_systems)



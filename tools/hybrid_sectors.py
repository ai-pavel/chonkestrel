#!/usr/bin/env python3
"""
Make the hybrid sectors for the Chonkestrel mod (see doc/game/sectors.md): the
hostile sectors of act 2, one for every pair of the eight races with hybrid
ships (all but the Federation), such as the Rock-Zoltan Controlled Sector,
where the enemy ships are that pair's hybrids (see doc/game/hybrid-ships.md).

    python3 tools/hybrid_sectors.py ftl.dat

Each one has the hybrid sectors' own events (`XFTL_HYBRIDSEC_*`, in
events.xml.append): its own start event, about its two races under the hum
(see START), CONCORD's joined ships to fight, life under the hum, and a pool
for each of its two races, with only a few of the two races' vanilla
events (see VANILLA). It has both races' music, and the crew of both in
its stores. The first race is the more
hostile one (see RACES), so it's the Rock-Zoltan sector, not Zoltan-Rock.
They're all only in act 2 (`xftlAct`), and `xftlHybrids` names the pair,
whose hybrids take the place of the enemy ships that can be hybrids (see
ShipGenerator.hybridFor). Together they're about as likely as the sectors
they replace (`xftlWeight`, see WEIGHT).

The sectors go between their own markers in the mod's
sector_data.xml.append, with their names in text_sectorname.xml.append, their
start events at the end of events.xml.append, and
a table of them, with every hybrid ship in each, in doc/game/sectors.md.
"""
import itertools
import re
import sys
import xml.etree.ElementTree as ET

from ship_variants import MOD, Dat

BEGIN_MARK = "<!-- BEGIN generated by tools/hybrid_sectors.py -->"
END_MARK = "<!-- END generated by tools/hybrid_sectors.py -->"

SECTOR_DATA = MOD / "data" / "sector_data.xml.append"
SECTOR_NAMES = MOD / "data" / "text_sectorname.xml.append"
EVENTS = MOD / "data" / "events.xml.append"
HYBRID_SHIPS = MOD / "data" / "autoBlueprints.xml.append"
DOC = MOD.parent.parent / "doc" / "game" / "sectors.md"

# Each race, from the most hostile: its name (as in the hybrids' names and
# their classes), and its vanilla sector, whose events and music it brings
RACES = [
    ("REBEL", "Rebel", "REBEL_SECTOR"),
    ("MANTIS", "Mantis", "MANTIS_SECTOR"),
    ("ROCK", "Rock", "ROCK_SECTOR"),
    ("SLUG", "Slug", "SLUG_SECTOR"),
    ("LANIUS", "Lanius", "LANIUS_SECTOR"),
    ("CRYSTAL", "Crystal", "CRYSTAL_HOME"),
    ("ENGI", "Engi", "ENGI_SECTOR"),
    ("ZOLTAN", "Zoltan", "ZOLTAN_SECTOR"),
]

# What each race's space looks like under the hum, for the start events: a
# sentence each (see the race's pool in events.xml.append, and doc/game/lore.md)
START = {
    "REBEL": "Rebel checkpoints still guard the border, but their guns point at nothing now, and their crews wave every ship through, smiling.",
    "MANTIS": "Mantis hunting packs drift between the stars, perfectly still, claws folded, waiting for nothing at all.",
    "ROCK": "Rock cathedral-ships sing the hum from orbit, so slowly that each verse takes an hour.",
    "SLUG": "Slug relays whisper on every channel, very pleased that they heard the hum first, and said yes first.",
    "LANIUS": "Lanius hulks drift among the old wrecks, slowly eating them, and sharing every bite with whoever they're joined to.",
    "CRYSTAL": "Crystal ships glint among the stars, every one of them cracked with thin white lines where the hum went in.",
    "ENGI": "Engi networks run the sector's traffic on every frequency, with perfect, cheerful efficiency, and no arguments at all.",
    "ZOLTAN": "Zoltan colonies glow and dim in time with the hum, like one heartbeat spread across a dozen worlds.",
}

# How the start events end, taking turns, with the two races' names
START_ENDINGS = [
    "Between them fly the joined ships, half {a} and half {b}, welded together and humming as one. CONCORD holds this sector now.",
    "Whatever {a} and {b} crews once fought over, they don't any more. Their ships fly joined together now, and every channel carries the same calm hum.",
    "Your sensors can't find a single ship here that's only {a} or only {b}. CONCORD has made them one people, and it would like to make you one too.",
]

# The crew races in the stores' rarity lists (the rest are weapons)
CREW = {"human", "engi", "mantis", "energy", "slug", "rock", "crystal", "anaerobic"}

# The race augments each race's stores have more of (the rarity: lower is
# commoner, they're 5 elsewhere), matching the vanilla race sectors' in
# mods/chonkestrel/data/sector_data.xml.append
RACE_AUGMENTS = {
    "ENGI": {"NANO_MEDBAY": 2, "DRONE_SPEED": 3},
    "MANTIS": {"CREW_STIMS": 2},
    "SLUG": {"SLUG_GEL": 2},
    "ZOLTAN": {"ENERGY_SHIELD": 3},
    "ROCK": {"ROCK_ARMOR": 2, "CRYSTAL_SHARDS": 4},
    "CRYSTAL": {"CRYSTAL_SHARDS": 2, "ROCK_ARMOR": 4},
}

# Of the two races' vanilla sectors' events, the ones a hybrid sector keeps,
# now and then (0 or 1 of each): the first whose name has each of these
VANILLA = ("HOSTILE", "NEUTRAL")

# How likely each hybrid sector is, next to a vanilla sector: together, the
# 28 are about as likely as the four act 2 hostile sectors (twice as likely
# as a vanilla one each) and the five vanilla hostile sectors they replace
WEIGHT = 0.5


def start_event(index, first, second):
    """
    The sector's start event: the sector's name, what each race's space
    looks like under the hum, and the joined ships between them, with no
    choices or hazards (the start beacon's calm, see GameMap.calmStart).
    """
    (key_a, name_a, _), (key_b, name_b, _) = first, second
    ending = START_ENDINGS[index % len(START_ENDINGS)].format(a=name_a, b=name_b)
    text = "You enter the %s-%s Controlled Sector. %s %s %s" % (name_a, name_b, START[key_a], START[key_b], ending)
    return '<event name="XFTL_HYBRIDSEC_START_%s_%s">\n\t<text>%s</text>\n</event>' % (key_a, key_b, text)


def sector(dat_sectors, first, second):
    (key_a, name_a, vanilla_a), (key_b, name_b, vanilla_b) = first, second
    a, b = dat_sectors[vanilla_a], dat_sectors[vanilla_b]
    name = "XFTL_HYBRID_%s_%s" % (key_a, key_b)

    lines = ['<sectorDescription name="%s" minSector="0" unique="false" xftlAct="2" '
             'xftlWeight="%s" xftlHybrids="%s %s">' % (name, WEIGHT, key_a, key_b),
             '\t<nameList>',
             '\t\t<name id="sectorname_%s" short="sectorname_short_%s"/>' % (name, name),
             '\t</nameList>',
             '\t<trackList>']
    tracks = []
    for source in (a, b):
        for track in source.find("trackList"):
            if track.text not in tracks:
                tracks.append(track.text)
    lines += ['\t\t<track>%s</track>' % t for t in tracks]
    lines.append('\t</trackList>')

    # The crew of both in the stores: each race as common as it is in
    # whichever sector has more of it (the lower rarity, but 0 is never)
    rarities = {}
    for source in (a, b):
        for bp in source.findall("rarityList/blueprint"):
            if bp.get("name") not in CREW:
                continue
            rarity = int(bp.get("rarity"))
            old = rarities.get(bp.get("name"))
            if old is None or (rarity != 0 and (old == 0 or rarity < old)):
                rarities[bp.get("name")] = rarity
    # And both races' augments, each as common as in either's sectors
    for key in (key_a, key_b):
        for augment, rarity in RACE_AUGMENTS.get(key, {}).items():
            rarities[augment] = min(rarity, rarities.get(augment, rarity))
    if rarities:
        lines.append('\t<rarityList>')
        lines += ['\t\t<blueprint name="%s" rarity="%d"/>' % (name, r) for name, r in rarities.items()]
        lines.append('\t</rarityList>')

    # The hybrid sectors' own events, and each race's pool
    lines += ['\t<startEvent>XFTL_HYBRIDSEC_START_%s_%s</startEvent>' % (key_a, key_b),
              '\t<event name="XFTL_HYBRIDSEC_HOSTILE" min="5" max="7"/>',
              '\t<event name="XFTL_HYBRIDSEC_COMMON" min="3" max="4"/>',
              '\t<event name="XFTL_HYBRIDSEC_%s" min="2" max="3"/>' % key_a,
              '\t<event name="XFTL_HYBRIDSEC_%s" min="2" max="3"/>' % key_b,
              '\t<event name="XFTL_HYBRIDSEC_NOTHING" min="2" max="3"/>',
              '\t<event name="STORE" min="1" max="2"/>',
              '\t<event name="ITEMS" min="0" max="1"/>']

    # Now and then, the two races' vanilla events (see VANILLA), and the
    # mod's new events for their vanilla sectors
    for source, key in ((a, key_a), (b, key_b)):
        names = [e.get("name") for e in source.findall("event")]
        for kind in VANILLA:
            vanilla = next((n for n in names if kind in n), None)
            if vanilla:
                lines.append('\t<event name="%s" min="0" max="1"/>' % vanilla)
        lines.append('\t<event name="XFTL_MORE_%s" min="0" max="1"/>' % key)

    # The events for big ships, and one of CONCORD's (as the vanilla sectors
    # get in act 2)
    lines.append('\t<event name="XFTL_BIG_HOSTILE" min="1" max="2" xftlMinShipSize="2"/>')
    lines.append('\t<event name="XFTL_CHORUS" min="1" max="1"/>')
    lines.append('</sectorDescription>')

    title = "%s-%s Controlled" % (name_a, name_b)
    names = ['<text name="sectorname_%s">%s Sector</text>' % (name, title),
             '<text name="sectorname_short_%s">%s</text>' % (name, title)]
    return name, "\n".join(lines), names, (title + " Sector", (key_a, key_b), tracks)


def hybrid_classes():
    """The hybrid ships' classes, such as "Rock-Zoltan Hybrid Scout", by name."""
    text = HYBRID_SHIPS.read_text()
    return dict(re.findall(r'<shipBlueprint name="(XFTL_HYBRID_[A-Z_]+)"[^>]*>\s*<class>([^<]*)</class>', text))


def doc_table(classes, rows):
    """
    The table of the hybrid sectors for doc/game/sectors.md: each sector's
    scouts and bombers (each way round), with their long and wide versions,
    and its music.
    """
    lines = ["| Sector | Scouts | Bombers | Music |", "|--------|--------|---------|-------|"]
    for title, (key_a, key_b), tracks in rows:
        cells = []
        for prefix in ("XFTL_HYBRID_", "XFTL_HYBRID_BOMBER_"):
            ships = []
            for name in (prefix + key_a + "_" + key_b, prefix + key_b + "_" + key_a):
                if name not in classes:
                    continue
                shapes = [shape for shape in ("LONG", "WIDE") if name + "_" + shape in classes]
                ships.append(classes[name] + (" (%s)" % ", ".join(s.lower() for s in shapes) if shapes else ""))
            cells.append(", ".join(ships) or "none")
        lines.append("| %s | %s | %s | %s |" % (title, cells[0], cells[1], ", ".join(tracks)))
    return "\n".join(lines)


def replace_between_marks(path, block):
    """Put [block] between the markers already in [path]."""
    text = path.read_text()
    start = text.index(BEGIN_MARK) + len(BEGIN_MARK)
    path.write_text(text[:start] + "\n" + block + "\n" + text[text.index(END_MARK):])


def replace_block(path, block):
    text = path.read_text()
    if BEGIN_MARK in text:
        text = text[:text.index(BEGIN_MARK)] + text[text.index(END_MARK) + len(END_MARK):]
    path.write_text(text.rstrip() + "\n\n" + block + "\n")


def main():
    dat = Dat(sys.argv[1])
    # (without its declaration and comments, in a root of its own, as it
    # has several at the top level)
    text = dat.read("data/sector_data.xml").decode("utf-8", "replace")
    text = re.sub(r"<!--.*?-->", "", text.split("?>", 1)[-1], flags=re.S)
    root = ET.fromstring("<root>" + text + "</root>")
    dat_sectors = {s.get("name"): s for s in root.iter("sectorDescription")}

    names = []
    sectors = []
    texts = []
    rows = []
    starts = []
    for index, (first, second) in enumerate(itertools.combinations(RACES, 2)):
        starts.append(start_event(index, first, second))
        name, xml, text, row = sector(dat_sectors, first, second)
        names.append(name)
        sectors.append(xml)
        texts += text
        rows.append(row)

    header = [BEGIN_MARK,
              "<!--",
              "    The hybrid sectors of act 2 (see doc/game/sectors.md). Don't edit these by",
              "    hand: change tools/hybrid_sectors.py and run it again.",
              "-->"]
    lists = []
    for sector_type in ("HOSTILE", "OVERRIDE_HOSTILE"):
        lists.append('<mod:findName type="sectorType" name="%s">' % sector_type)
        lists += ['\t<mod-append:sector>%s</mod-append:sector>' % n for n in names]
        lists.append('</mod:findName>')
    replace_block(SECTOR_DATA, "\n".join(header + sectors + lists + [END_MARK]))
    replace_block(SECTOR_NAMES, "\n".join([BEGIN_MARK] + texts + [END_MARK]))
    replace_block(EVENTS, "\n".join([BEGIN_MARK, "<!-- The hybrid sectors' start events (see doc/game/sectors.md) -->"] +
                                    starts + [END_MARK]))
    replace_between_marks(DOC, doc_table(hybrid_classes(), rows))
    print("Made %d hybrid sectors" % len(names))


if __name__ == "__main__":
    main()

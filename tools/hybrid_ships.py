def spans(solid, rows):
    """The leftmost and rightmost solid pixels in any of these rows."""
    xs = np.nonzero(solid[rows].any(axis=0))[0]
    return (int(xs[0]), int(xs[-1])) if len(xs) else None


def solid_span(alpha, rows):
    """The leftmost and rightmost solid pixel over these rows, or None."""
    xs = np.nonzero((alpha[rows] > 128).any(axis=0))[0]
    return (int(xs[0]), int(xs[-1])) if len(xs) else None


def fit_join(hull, cloak, cloak_offset, seam):
    """
    Make the halves' sides meet at the join (above it the front, below it the
    back), where they miss each other by a little (up to FIT_MAX pixels): as
    the halves are lined up by whole rooms, their hulls' sides only meet by
    chance, leaving a step or a gap. The narrower half's rows near the join
    are stretched out from their middle, more the nearer the join, so its
    side bends out to meet the wider one's there; the cloak the same way.
    """
    pixels = np.asarray(hull).copy()
    cloak_pixels = np.asarray(cloak).copy()
    alpha = pixels[..., 3]
    height, width = alpha.shape
    ox, oy = cloak_offset
    above = solid_span(alpha, slice(max(0, seam - 3), seam))
    below = solid_span(alpha, slice(seam, min(height, seam + 3)))
    if above is None or below is None:
        return hull, cloak

    # How far each row's left and right sides move out (negative to the left)
    moves = {}
    for side, outward in ((0, -1), (1, 1)):
        miss = below[side] - above[side]
        if not 1 <= abs(miss) <= FIT_MAX:
            continue
        # The narrower half on this side, and where its side should get to
        narrow_below = miss * outward < 0
        target = above[side] if narrow_below else below[side]
        start = below[side] if narrow_below else above[side]
        rows = range(seam, min(height, seam + FIT_ROWS)) if narrow_below else \
            range(seam - 1, max(-1, seam - 1 - FIT_ROWS), -1)
        for i, y in enumerate(rows):
            t = 1 - i / FIT_ROWS
            weight = t * t * (3 - 2 * t)  # (smoothstep: no kink where it ends)
            move = round((target - start) * weight)
            if move:
                moves.setdefault(y, [0, 0])[side] = move

    for y, (left_move, right_move) in moves.items():
        span = solid_span(alpha, slice(y, y + 1))
        if span is None:
            continue
        left, right = span
        middle = (left + right) // 2
        # Where each pixel of the new row comes from in the old one
        xs = np.arange(width, dtype=np.float64)
        source = xs.copy()
        if left_move and middle > left:
            scale = (middle - left) / (middle - left - left_move)
            part = xs <= middle
            source[part] = middle - (middle - xs[part]) * scale
        if right_move and right > middle:
            scale = (right - middle) / (right - middle + right_move)
            part = xs > middle
            source[part] = middle + (xs[part] - middle) * scale
        source = np.round(source).astype(int)
        inside = (source >= 0) & (source < width)
        row = np.zeros_like(pixels[y])
        row[inside] = pixels[y, source[inside]]
        pixels[y] = row
        cy = y - oy
        if 0 <= cy < cloak_pixels.shape[0]:
            cxs = np.arange(cloak_pixels.shape[1])
            csource = source[np.clip(cxs + ox, 0, width - 1)] - ox
            ok = (cxs + ox >= 0) & (cxs + ox < width) & (csource >= 0) & (csource < cloak_pixels.shape[1])
            crow = np.zeros_like(cloak_pixels[cy])
            crow[ok] = cloak_pixels[cy, csource[ok]]
            # (the cloak's wider than the hull: what's past it stays as it was)
            outside = (cxs + ox < 0) | (cxs + ox >= width)
            crow[outside] = cloak_pixels[cy, outside]
            cloak_pixels[cy] = crow
    return Image.fromarray(pixels, "RGBA"), Image.fromarray(cloak_pixels, "RGBA")


def close_cloak_lines(cloak, seam, hull, cloak_offset):
    """
    Close the cloak's lines that stop at the join (at row seam), as the
    halves' lines rarely meet: each line coming down to it is joined to
    the nearest one going on from it below (within CLOAK_LINK pixels) along
    the join, and one with no other end is taken along the join to the
    nearest line (within CLOAK_REACH), if there is one. Near the join, the
    faint fill inside the hull (hull, cloak_offset from the cloak) and the
    glow round the lines are made again, as each half's fade out towards
    where it was cut.
    """
    pixels = np.asarray(cloak).copy()
    height, width = pixels.shape[:2]
    if not 3 <= seam < height - 3:
        return cloak
    line = pixels[..., 3] > CLOAK_LINE_ALPHA

    def ends(rows_in, rows_out):
        """The middles of the runs of columns with a line in rows_in that stops before rows_out."""
        found = []
        for x in range(1, width - 1):
            if line[rows_in, x].all() and not line[rows_out, x - 1:x + 2].any():
                if found and found[-1][-1] == x - 1:
                    found[-1].append(x)
                else:
                    found.append([x])
        return [run[len(run) // 2] for run in found]

    up = ends(slice(seam - 3, seam), slice(seam, seam + 2))
    down = ends(slice(seam, seam + 3), slice(seam - 2, seam))

    def draw(y, x0, x1, colour):
        lo, hi = sorted((x0, x1))
        for x in range(lo, hi + 1):
            if pixels[y, x, 3] < colour[3]:
                pixels[y, x] = colour

    # Pair up the ends above and below, nearest first
    pairs = sorted((abs(a - b), a, b) for a in up for b in down if abs(a - b) <= CLOAK_LINK)
    used_up, used_down = set(), set()
    for _, a, b in pairs:
        if a in used_up or b in used_down:
            continue
        used_up.add(a)
        used_down.add(b)
        draw(seam - 1, a, b, pixels[seam - 1, a].copy())

    # The rest, along the join to the nearest line there
    for xs, y, used in ((up, seam - 1, used_up), (down, seam, used_down)):
        for x in xs:
            if x in used:
                continue
            colour = pixels[y, x].copy()
            near = [x2 for x2 in range(max(0, x - CLOAK_REACH), min(width, x + CLOAK_REACH + 1))
                    if abs(x2 - x) > 2 and line[y - 1:y + 2, x2].any() and (line[y - 3:y, x2].all() or line[y:y + 3, x2].all())]
            if near:
                draw(y, x, min(near, key=lambda x2: abs(x2 - x)), colour)

    # The faint fill inside the hull: each half's fades out towards where it
    # was cut, leaving a dark band with straight edges at the join (which a
    # long version, repeating a row near it, can stretch), so near it, each
    # column's fill goes smoothly from what it is above to what it is below
    line = pixels[..., 3] > CLOAK_LINE_ALPHA
    ox, oy = cloak_offset
    hull_alpha = np.asarray(hull.getchannel("A"))
    inside = np.zeros((height, width), dtype=bool)
    hy0, hx0 = max(0, oy), max(0, ox)
    hy1, hx1 = min(hull_alpha.shape[0], height + oy), min(hull_alpha.shape[1], width + ox)
    inside[hy0 - oy:hy1 - oy, hx0 - ox:hx1 - ox] = hull_alpha[hy0:hy1, hx0:hx1] > 128
    top, bottom = max(0, seam - GLOW_BAND), min(height - 1, seam + GLOW_BAND)

    def fill_at(y):
        """The fill's colour and alpha along row y (none on a line or outside the hull)."""
        ok = inside[y] & ~line[y]
        return np.where(ok[:, None], pixels[y].astype(np.float32), 0)

    def smoothed(row):
        """A row's fill evened out along it, so the columns between don't streak."""
        weight = ndimage.gaussian_filter1d((row[:, 3] > 0).astype(np.float32), CLOAK_FILL_SMOOTH)
        out = np.stack([ndimage.gaussian_filter1d(row[:, c], CLOAK_FILL_SMOOTH) for c in range(4)], axis=1)
        out[:, :3] /= np.maximum(weight, 1e-3)[:, None]
        return out

    above, below = smoothed(fill_at(top)), smoothed(fill_at(bottom))
    for y in range(top + 1, bottom):
        t = (y - top) / (bottom - top)
        want = above * (1 - t) + below * t
        mask = inside[y] & ~line[y]
        # (the colour of whichever end has any fill, where only one has)
        colour = np.where((above[:, 3:] > 0) & (below[:, 3:] > 0), want[:, :3],
                          np.where(above[:, 3:] > 0, above[:, :3], below[:, :3]))
        pixels[y, mask, :3] = colour[mask].astype(np.uint8)
        pixels[y, mask, 3] = want[mask, 3].astype(np.uint8)
    weight = np.clip(1 - np.abs(np.arange(height) - seam) / GLOW_BAND, 0, 1)[:, None]

    # The glow round the lines likewise, made again from the lines, fading
    # into what's there
    faint = (pixels[..., 3] > 10) & ~line & ~inside
    if faint.any() and line.any():
        glow_colour = np.median(pixels[faint][:, :3], axis=0)
        strongest = np.percentile(pixels[faint][:, 3], 90)
        halo = ndimage.gaussian_filter(line.astype(np.float32), CLOAK_GLOW)
        halo = np.clip(halo / max(halo.max(), 1e-6) * 2, 0, 1) * strongest
        alpha = pixels[..., 3].astype(np.float32)
        new_alpha = np.maximum(alpha, halo * weight)
        glow = ~line & (new_alpha > alpha)
        pixels[glow, :3] = glow_colour
        pixels[glow, 3] = new_alpha[glow].astype(np.uint8)
    return Image.fromarray(pixels, "RGBA")


def blend(hull, cloak, cloak_offset, seam, protected):
    """
    Finish off the join between the halves of a hybrid's hull (the front
    above the seam, the back below it), so where one half is wider than the
    other, the part sticking out doesn't look cut off in midair:

    - its cut edge gets a dark outline (as every vanilla hull's edges have),
      and the hull's glow past it, so it looks like the end of the plating;
    - bits of hull left on their own near the join, with no rooms on them,
      are taken out.
    """
    pixels = np.asarray(hull).astype(np.float32)
    cloak_pixels = np.asarray(cloak).copy()
    height, width = pixels.shape[:2]
    alpha = pixels[..., 3]
    solid = alpha > 200
    ox, oy = cloak_offset

    # The colour of the hull's glow: its faint pixels
    faint = (alpha > 20) & (alpha < 100)
    glow_colour = np.median(pixels[faint][:, :3], axis=0) if faint.any() else np.array([100.0, 80.0, 130.0])

    def finish(edge_rows, open_row, outward):
        """
        Outline the hull in edge_rows where open_row (the other half's row
        next to the join) has no hull, and put glow beyond it, going outward.
        """
        if not (0 <= open_row < height):
            return
        exposed = ~solid[open_row]
        for y in edge_rows:
            if 0 <= y < height:
                mask = exposed & solid[y]
                pixels[y, mask, :3] *= OUTLINE_SHADE
        first = edge_rows[0]
        if not 0 <= first < height:
            return
        source = exposed & solid[first]
        for d in range(1, BLEND_GLOW + 1):
            y = first + outward * d
            if not 0 <= y < height:
                break
            strength = GLOW_ALPHA * (1 - d / (BLEND_GLOW + 1))
            mask = source & ~solid[y] & (alpha[y] < strength)
            pixels[y, mask, :3] = glow_colour
            pixels[y, mask, 3] = strength

    # The front's bottom edge where the back's narrower, and the back's top
    # edge where the front's narrower
    finish([seam - 1, seam - 2], seam, +1)
    finish([seam, seam + 1], seam - 1, -1)

    # Each half's glow stops in a straight line at the join, so near it, the
    # glow's made again round the whole hull
    band = slice(max(0, seam - GLOW_BAND), min(height, seam + GLOW_BAND))
    halo = ndimage.gaussian_filter(solid.astype(np.float32), BLEND_GLOW / 2) * 2 * GLOW_ALPHA
    region = np.zeros((height, width), dtype=bool)
    region[band] = True
    clear = region & (pixels[..., 3] < GLOW_CUTOFF) & ~solid
    # (fading into the glow that's there away from the join)
    weight = 1 - np.abs(np.arange(height) - seam) / GLOW_BAND
    weight = np.clip(weight, 0, 1)[:, None] * np.ones((1, width))
    new_alpha = halo * weight + pixels[..., 3] * (1 - weight)
    pixels[clear, :3] = glow_colour
    pixels[clear, 3] = np.minimum(new_alpha[clear], GLOW_ALPHA)

    # Bits of hull near the join left on their own, without rooms
    keep = np.zeros((height, width), dtype=bool)
    for x0, y0, x1, y1 in protected:
        keep[max(0, y0):y1, max(0, x0):x1] = True
    labels, count = ndimage.label(solid, structure=np.ones((3, 3)))
    band = slice(max(0, seam - ISLAND_BAND), min(height, seam + ISLAND_BAND))
    for label in range(1, count + 1):
        part = labels == label
        if (part & keep).any() or not part[band].any() or part.sum() >= ISLAND_SIZE:
            continue
        gone = ndimage.binary_dilation(part, iterations=BLEND_GLOW) & ~(solid & ~part)
        pixels[gone] = 0
        ys, xs = np.nonzero(gone)
        cy, cx = ys - oy, xs - ox
        ok = (cy >= 0) & (cy < cloak_pixels.shape[0]) & (cx >= 0) & (cx < cloak_pixels.shape[1])
        cloak_pixels[cy[ok], cx[ok]] = 0

    return Image.fromarray(pixels.clip(0, 255).astype(np.uint8), "RGBA"), Image.fromarray(cloak_pixels, "RGBA")


def merge_small_rooms(rooms, id_maps, hull, origin):
    """
    The rooms with none of one cell (from the vanilla ships, or cut down at
    the join), which hybrids don't have: each is joined to a room next to it
    that's one cell wide along that side (so it's still a rectangle), or
    else grows into the cell next to it, if the hull's solid there. The rooms
    are numbered from 0 again, and id_maps (old ids to new) are updated.
    """
    rooms = {rid: list(r) for rid, r in rooms.items()}
    alpha = np.asarray(hull.getchannel("A"))
    merged = {}

    def solid(cx, cy):
        x0, y0 = origin[0] + cx * ROOM, origin[1] + cy * ROOM
        if x0 < 0 or y0 < 0 or x0 + ROOM > alpha.shape[1] or y0 + ROOM > alpha.shape[0]:
            return False
        return (alpha[y0:y0 + ROOM, x0:x0 + ROOM] > 200).mean() > 0.9

    while True:
        small = [rid for rid, (x, y, w, h) in rooms.items() if w * h == 1]
        if not small:
            break
        rid = small[0]
        x, y, _, _ = rooms[rid]
        target = None
        for other, (ox, oy, ow, oh) in rooms.items():
            if other == rid:
                continue
            if ow == 1 and ox == x and (oy + oh == y or oy == y + 1):
                target = other
                rooms[other] = [ox, min(oy, y), 1, oh + 1]
                break
            if oh == 1 and oy == y and (ox + ow == x or ox == x + 1):
                target = other
                rooms[other] = [min(ox, x), oy, ow + 1, 1]
                break
        if target is not None:
            del rooms[rid]
            merged[rid] = target
            continue
        cells = {(cx, cy) for (rx, ry, rw, rh) in rooms.values()
                 for cx in range(rx, rx + rw) for cy in range(ry, ry + rh)}
        for nx, ny in ((x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)):
            if (nx, ny) not in cells and solid(nx, ny):
                rooms[rid] = [min(x, nx), min(y, ny), 1 + abs(nx - x), 1 + abs(ny - y)]
                break
        else:
            raise AssertionError("room %d is one cell, with nowhere to grow" % rid)

    def final(rid):
        while rid in merged:
            rid = merged[rid]
        return rid

    order = sorted(rooms)
    new_ids = {old: i for i, old in enumerate(order)}
    for ids in id_maps:
        for old in ids:
            ids[old] = new_ids[final(ids[old])]
    return {new_ids[old]: rooms[old] for old in order}


def glue(front, back, cut_f, cut_b, shift):
    """
    The hybrid's layout, hull and cloak images, origin, cloak offset, mounts,
    and where each half's rooms went (old room id to new).
    """
    split_f = front.origin[1] + cut_f * ROOM
    split_b = back.origin[1] + cut_b * ROOM
    dx = front.origin[0] - back.origin[0] + shift * ROOM
    dy = split_f - split_b

    # The rooms: the front's above its cut, the back's below its, moved to
    # line up with the front's grid
    rooms = {}
    ids_f = {}
    ids_b = {}
    # (a room the cut goes through keeps its part on that side)
    for rid, (x, y, w, h) in sorted(front.layout.rooms.items()):
        if y < cut_f:
            ids_f[rid] = len(rooms)
            rooms[len(rooms)] = [x, y, w, min(h, cut_f - y)]
    for rid, (x, y, w, h) in sorted(back.layout.rooms.items()):
        if y + h > cut_b:
            top = max(y, cut_b)
            ids_b[rid] = len(rooms)
            rooms[len(rooms)] = [x + shift, top - cut_b + cut_f, w, y + h - top]

    # The images, on a canvas big enough for both
    x0 = min(0, dx)
    width = max(front.hull.width, back.hull.width + dx) - x0
    height = split_f + back.hull.height - split_b
    hull = Image.new("RGBA", (width, height))
    hull.alpha_composite(back.hull.crop((0, split_b, back.hull.width, back.hull.height)), (dx - x0, split_f))
    hull.alpha_composite(front.hull.crop((0, 0, front.hull.width, split_f)), (-x0, 0))

    # The cloak, the same way, with the front's offset from the hull
    off_f, off_b = front.cloak_offset, back.cloak_offset
    cloak = Image.new("RGBA", (width + 2 * off_f[0], height + 2 * off_f[1]))
    cloak_split_f = split_f - off_f[1]
    cloak_split_b = split_b - off_b[1]
    cloak.alpha_composite(back.cloak.crop((0, max(0, cloak_split_b), back.cloak.width, back.cloak.height)),
                          (max(0, off_b[0] + dx - x0 - off_f[0]), max(0, cloak_split_b + off_b[1] + dy - off_f[1])))
    cloak.alpha_composite(front.cloak.crop((0, 0, front.cloak.width, max(0, cloak_split_f))), (-x0, 0))

    # Smooth the join, so neither half sticks out past the other in midair
    protected = [(front.origin[0] - x0 + x * ROOM, front.origin[1] + y * ROOM,
                  front.origin[0] - x0 + (x + w) * ROOM, front.origin[1] + (y + h) * ROOM)
                 for x, y, w, h in rooms.values()]
    hull, cloak = fit_join(hull, cloak, off_f, split_f)
    hull, cloak = blend(hull, cloak, off_f, split_f, protected)
    cloak = close_cloak_lines(cloak, split_f - off_f[1], hull, off_f)

    hull, cloak, mounts_cut = shorten(hull, cloak, off_f, front.origin[1] + (max(r[1] + r[3] for r in rooms.values())) * ROOM)

    # (before the grid's origin is moved, as a room can grow past it)
    rooms = merge_small_rooms(rooms, [ids_f, ids_b], hull, (front.origin[0] - x0, front.origin[1]))

    # Keep the grid's origin where the rooms are
    min_x = min(r[0] for r in rooms.values())
    min_y = min(r[1] for r in rooms.values())
    for r in rooms.values():
        r[0] -= min_x
        r[1] -= min_y
    origin = (front.origin[0] - x0 + min_x * ROOM, front.origin[1] + min_y * ROOM)

    layout = Layout("")
    layout.rooms = rooms
    # The shield's as wide as the wider of the two, and stretched to the
    # new length
    ell_f, ell_b = front.layout.ellipse, back.layout.ellipse
    layout.ellipse = [max(ell_f[0], ell_b[0]), round(ell_f[1] * height / front.hull.height), ell_f[2], ell_f[3]]

    # The doors within each half, and between rooms either side of the cut
    cells = layout.cells()

    def keep_door(door, ids, dx_cells, dy_cells, lo, hi):
        x, y, a, b, vertical = door
        if (a >= 0 and a not in ids) or (b >= 0 and b not in ids):
            return None
        if not lo <= y < hi and not (vertical == 0 and y == hi):
            return None
        return [x + dx_cells - min_x, y + dy_cells - min_y, ids.get(a, -1), ids.get(b, -1), vertical]

    doors = []
    # (a door between two rooms that were merged goes)
    for door in front.layout.doors:
        kept = keep_door(door, ids_f, 0, 0, -99, cut_f)
        if kept and not (kept[4] == 0 and door[1] == cut_f) and not (kept[2] == kept[3] >= 0):
            doors.append(kept)
    for door in back.layout.doors:
        kept = keep_door(door, ids_b, shift, cut_f - cut_b, cut_b, 99)
        if kept and not (kept[4] == 0 and door[1] == cut_b) and not (kept[2] == kept[3] >= 0):
            doors.append(kept)
    seam = cut_f - min_y
    joined = set()
    for (x, y), rid in sorted(cells.items()):
        if y != seam - 1:
            continue
        below = cells.get((x, seam))
        if below is not None and (rid, below) not in joined:
            joined.add((rid, below))
            doors.append([x, seam, rid, below, 0])

    # A door to space has to be on the hull, so the ones left on the cut go
    def door_ok(door):
        x, y, a, b, vertical = door
        sides = {cells.get((x - 1, y) if vertical else (x, y - 1), -1), cells.get((x, y), -1)}
        return sides == {a, b}

    # (and one between two cells of the same room, from rooms that were
    # merged across the join, goes too)
    layout.doors = [d for d in doors if door_ok(d) and not (d[2] == d[3] >= 0)]

    # Join up any rooms that can't be reached (some vanilla ships have rooms
    # without doors), with a door to a room next to them
    while not layout.connected():
        parts = layout.parts()
        main = next(p for p in parts if 0 in p)
        door = None
        for (x, y), rid in sorted(cells.items()):
            if rid in main:
                continue
            for (nx, ny), vertical, pos in (((x - 1, y), 1, (x, y)), ((x + 1, y), 1, (x + 1, y)),
                                            ((x, y - 1), 0, (x, y)), ((x, y + 1), 0, (x, y + 1))):
                if cells.get((nx, ny)) in main:
                    door = [pos[0], pos[1], cells[(nx, ny)], rid, vertical]
                    break
            if door:
                break
        assert door, "%s+%s: rooms with no room next to them" % (front.race, back.race)
        layout.doors.append(door)
    assert layout.connected(), "%s+%s: not every room can be reached" % (front.race, back.race)

    # The mounts: each half's own, on its own half
    mounts = []
    for m in front.mounts[:4]:
        if int(m["y"]) < split_f:
            mounts.append(dict(m, x=str(int(m["x"]) - x0)))
    for m in back.mounts[:4]:
        if int(m["y"]) >= split_b:
            mounts.append(dict(m, x=str(int(m["x"]) + dx - x0), y=str(mounts_cut(int(m["y"]) + dy))))
    # The mounts left out (on the other half's side of the join) are put back
    # if it's short of them, on the edge of the hull just its side of the join
    seam = split_f
    stacked = {}
    dropped = [(m, front, int(m["y"]), -1) for m in front.mounts[:4] if int(m["y"]) >= split_f]
    dropped += [(m, back, int(m["y"]), +1) for m in back.mounts[:4] if int(m["y"]) < split_b]
    for m, part, y, direction in dropped:
        if len(mounts) >= MAX_MOUNTS:
            break
        left = int(m["x"]) < part.hull.width // 2
        key = (direction, left)
        stacked[key] = stacked.get(key, 0) + 1
        new_y = seam + direction * (JOIN_MOUNT_GAP * stacked[key])
        own = hull_edges(part.hull, y)
        inset = (int(m["x"]) - own[0] if left else own[1] - int(m["x"])) if own else 0
        inset = max(0, min(inset, JOIN_MOUNT_INSET))
        edges = hull_edges(hull, min(max(new_y, 0), hull.height - 1))
        if edges is None:
            continue
        new_x = edges[0] + inset if left else edges[1] - inset
        mounts.append(dict(m, x=str(new_x), y=str(new_y)))
    mounts = mounts[:MAX_MOUNTS]
    assert len(mounts) >= MIN_MOUNTS, "%s+%s: only %d weapon mounts" % (front.race, back.race, len(mounts))

    return layout, hull, cloak, origin, off_f, mounts, ids_f, ids_b


def blueprint(front, back, name, layout, ids_f, ids_b, mount_count):
    """The hybrid's blueprint, made from both ships'."""
    _, title_f, crew_f, _, _, aug_f = RACES[front.race]
    _, title_b, crew_b, _, _, aug_b = RACES[back.race]
    weapons_f, weapons_b, drones_f, drones_b = front.weapons, back.weapons, front.drones, back.drones
    bp = ET.fromstring(ET.tostring(front.bp))
    bp.set("name", name)
    bp.set("layout", name.lower())
    bp.set("img", name.lower())

    cls = bp.find("class")
    cls.attrib.clear()
    cls.text = "%s-%s Hybrid %s" % (title_f, title_b, front.kind)

    # Each half's systems, in its own rooms
    systems = bp.find("systemList")
    for elem in list(systems):
        systems.remove(elem)
    have = set()
    taken = set()
    for part, ids in ((front, ids_f), (back, ids_b)):
        for elem in part.bp.find("systemList"):
            room = int(elem.get("room"))
            # (two rooms that were merged only keep the first's system)
            if room not in ids or ids[room] in taken:
                continue
            tag, attrib = elem.tag, dict(elem.attrib)
            if tag in have:
                # The race's own system instead of a second copy, if it
                # hasn't got it yet
                signature = SIGNATURE.get(part.race)
                if signature and signature not in have:
                    power, most = DEFAULT_SYSTEMS[signature]
                    tag, attrib = signature, {"power": str(power), "max": str(most)}
                elif tag in SINGLE:
                    continue
            new = ET.SubElement(systems, tag, attrib)
            new.set("room", str(ids[room]))
            have.add(tag)
            taken.add(ids[room])
    # And the ones it needs, in the biggest rooms without a system
    used = {int(elem.get("room")) for elem in systems}
    free = sorted((rid for rid in layout.rooms if rid not in used),
                  key=lambda rid: -layout.rooms[rid][2] * layout.rooms[rid][3])
    for system in NEEDED:
        if system in have:
            continue
        if free:
            room = free.pop(0)
        else:
            # Without a free room, it takes the place of the least needed
            # system (or a second copy of a needed one)
            counts = {}
            for elem in systems:
                counts[elem.tag] = counts.get(elem.tag, 0) + 1
            spare = [elem for elem in systems if elem.tag not in NEEDED or counts[elem.tag] > 1]
            assert spare, "%s: no room for %s" % (name, system)
            replaced = min(spare, key=lambda elem: LEAST_NEEDED.index(elem.tag) if elem.tag in LEAST_NEEDED else 99)
            systems.remove(replaced)
            have.discard(replaced.tag) if counts[replaced.tag] == 1 else None
            room = int(replaced.get("room"))
        power, most = DEFAULT_SYSTEMS.get(system, (1, 3))
        ET.SubElement(systems, system, power=str(power), max=str(most), room=str(room))
        have.add(system)

    # A drones system, for the drones that quietly keep watch over it (see
    # control_drones): in a room without a system, or in place of the least
    # needed one
    if "drones" not in have:
        used = {int(elem.get("room")) for elem in systems}
        free = [rid for rid in layout.rooms if rid not in used]
        if free:
            room = max(free, key=lambda rid: layout.rooms[rid][2] * layout.rooms[rid][3])
        else:
            counts = {}
            for elem in systems:
                counts[elem.tag] = counts.get(elem.tag, 0) + 1
            spare = [elem for elem in systems if elem.tag not in NEEDED or counts[elem.tag] > 1]
            assert spare, "%s: no room for drones" % name
            replaced = min(spare, key=lambda elem: LEAST_NEEDED.index(elem.tag) if elem.tag in LEAST_NEEDED else 99)
            systems.remove(replaced)
            room = int(replaced.get("room"))
        power, most = DEFAULT_SYSTEMS["drones"]
        ET.SubElement(systems, "drones", power=str(power), max=str(most), room=str(room))
        have.add("drones")

    # Both races' weapons and drones
    weapons = bp.find("weaponList")
    weapons.set("load", "%s_WEAPONS" % name)
    lists = [blueprint_list("%s_WEAPONS" % name, [weapons_f, weapons_b])]
    drones = bp.find("droneList")
    if "drones" in have:
        if drones is None:
            drones = ET.SubElement(bp, "droneList")
        drones.set("load", "%s_DRONES" % name)
        drones.set("drones", str(max(4, int((drones.get("drones") or "0").strip()))))
        lists.append(blueprint_list("%s_DRONES" % name, [d for d in (drones_f, drones_b) if d] or [DEFAULT_DRONES]))
    elif drones is not None:
        bp.remove(drones)

    # The crew, half each, and the bigger of the two ships' hull and reactor
    crew = bp.find("crewCount")
    crew_back = back.bp.find("crewCount")
    other = ET.Element("crewCount")
    for attr in ("amount", "max"):
        total = max(2, int(crew.get(attr).strip()), int(crew_back.get(attr).strip()))
        crew.set(attr, str(total - total // 2))
        other.set(attr, str(total // 2))
    other.set("class", crew_b)
    bp.insert(list(bp).index(crew) + 1, other)
    for tag in ("health", "maxPower"):
        elem = bp.find(tag)
        elem.set("amount", str(max(int(elem.get("amount").strip()),
                                   int(back.bp.find(tag).get("amount").strip()))))

    for aug in (aug_f, aug_b):
        if aug and aug not in {a.get("name") for a in bp.findall("aug")}:
            ET.SubElement(bp, "aug").set("name", aug)

    drones = control_drones("normal", front.race, back.race)
    ensure_drones_systems(bp, layout.rooms, drones)
    ensure_doors_system(bp, layout.rooms)
    set_control_drones(bp, drones)

    cloak = bp.find("cloakImage")
    if cloak is None:
        cloak = ET.SubElement(bp, "cloakImage")
    cloak.text = name.lower()

    for tag, text in (("weaponSlots", str(mount_count)), ("maxSystems", str(len(systems)))):
        elem = ET.Element(tag)
        elem.text = text
        bp.insert(1, elem)

    ET.indent(bp, "\t")
    return [ET.tostring(bp, encoding="unicode")] + lists


def blueprint_list(name, items):
    lst = ET.Element("blueprintList", name=name)
    for item in items:
        ET.SubElement(lst, "name").text = item
    ET.indent(lst, "\t")
    return ET.tostring(lst, encoding="unicode")


# The bigger versions of the hybrids (see doc/game/ship-shapes.md): the shapes,
# and for each kind of hybrid, how many weapon mounts each shape has (as
# the vanilla ships of that size do, see ship_variants.SMALL and MEDIUM)
SHAPES = ("long", "wide")
SHAPE_MOUNTS = {"XFTL_HYBRID_": variants.SMALL, "XFTL_HYBRID_BOMBER_": variants.MEDIUM}
# How far (in pixels) from a hybrid's join its bigger versions aren't cut
SEAM_AVOID = 12
# What the front race's FACTION_EXTRAS a bigger hybrid doesn't get: the
# crew it has is already two races'
LEFT_OUT_EXTRAS = ("crew", "crew_mix")


def clean_band(hull, axis, start, size):
    """
    The hull with the glow in the rows (or columns) put in at start made
    again: repeating a row of glow (where the hybrid's halves meet, it's
    rarely the same either side) leaves a see-through box beside the hull,
    so in the band, everything that isn't hull is cleared, and the glow is
    made again round the hull there.
    """
    pixels = np.asarray(hull).astype(np.float32)
    height, width = pixels.shape[:2]
    band = np.zeros((height, width), dtype=bool)
    lo, hi = max(0, start - BLEND_GLOW), start + size + BLEND_GLOW
    if axis == "y":
        band[lo:hi] = True
    else:
        band[:, lo:hi] = True
    solid = pixels[..., 3] > GLOW_CUTOFF
    faint = (pixels[..., 3] > 20) & (pixels[..., 3] < 100)
    glow_colour = np.median(pixels[faint][:, :3], axis=0) if faint.any() else np.array([100.0, 80.0, 130.0])
    clear = band & ~solid
    halo = ndimage.gaussian_filter(solid.astype(np.float32), BLEND_GLOW / 2) * 2 * GLOW_ALPHA
    pixels[clear, :3] = glow_colour
    pixels[clear, 3] = np.minimum(halo[clear], GLOW_ALPHA)
    return Image.fromarray(pixels.clip(0, 255).astype(np.uint8), "RGBA")


def control_drones(shape, *races):
    """
    The drones a hybrid always has (see doc/game/hybrid-ships.md): anti-personnel
    and system repair drones, taking turns, one on a normal ship, two on a
    long one and three on a wide one, and one more if one of its races is
    known for its drones (CONTROL_DRONE_RACES).
    """
    count = CONTROL_DRONES[shape]
    if any(race in CONTROL_DRONE_RACES for race in races):
        count += CONTROL_DRONE_RACE_EXTRA[shape]
    count = min(count, MOST_CONTROL_DRONES)
    return [CONTROL_DRONE_TYPES[i % len(CONTROL_DRONE_TYPES)] for i in range(count)]


def ensure_drones_systems(bp, rooms, drones, long_ship=False):
    """
    Give a hybrid's blueprint enough drones systems for the drones it always
    has to have the power they need (DRONES_SYSTEM_POWER each): new ones go
    in rooms without a system (unless it's a long ship with all the systems
    it can show), or in place of the least needed systems.
    """
    systems = bp.find("systemList")
    needed = -(-sum(DRONE_POWER[d] for d in drones) // DRONES_SYSTEM_POWER)
    while len(systems.findall("drones")) < needed:
        used = {int(elem.get("room")) for elem in systems}
        free = [rid for rid in rooms if rid not in used]
        if free and not (long_ship and len(systems) >= variants.MAX_LONG_SYSTEMS):
            # (the biggest, but not a hold, if there's another: the bulwarks
            # stand in that, see variants.with_hold)
            room = max(free, key=lambda rid: (not variants.is_hold(rooms[rid]), rooms[rid][2] * rooms[rid][3]))
        else:
            counts = {}
            for elem in systems:
                counts[elem.tag] = counts.get(elem.tag, 0) + 1
            spare = [elem for elem in systems if elem.tag != "drones" and elem.tag in LEAST_NEEDED
                     and (elem.tag not in NEEDED or counts[elem.tag] > 1) and elem.tag not in ("cloaking", "teleporter")]
            if not spare:
                break
            replaced = min(spare, key=lambda elem: LEAST_NEEDED.index(elem.tag))
            systems.remove(replaced)
            room = int(replaced.get("room"))
        power, most = DEFAULT_SYSTEMS["drones"]
        ET.SubElement(systems, "drones", power=str(power), max=str(most), room=str(room))
    limit = bp.find("maxSystems")
    if limit is not None:
        limit.text = str(max(int(limit.text), len(systems)))


def ensure_doors_system(bp, rooms, long_ship=False):
    """
    Give a hybrid without a doors system a place for one, if it has a room
    without a system to spare (the smallest, and never its hold, see
    variants.with_hold), and on a long ship, if its window has room for the
    icon: it's optional (start="false"), and the later enemies always get
    it (see ShipGenerator.lateDoors), to keep the player's boarders out.
    """
    systems = bp.find("systemList")
    if systems.find("doors") is not None:
        return
    if long_ship and len(systems) >= variants.MAX_LONG_SYSTEMS:
        return
    used = {int(elem.get("room")) for elem in systems}
    free = [rid for rid in rooms if rid not in used and not variants.is_hold(rooms[rid])]
    if not free:
        return
    room = min(free, key=lambda rid: rooms[rid][2] * rooms[rid][3])
    power, most = DEFAULT_SYSTEMS.get("doors", (1, 3))
    ET.SubElement(systems, "doors", power=str(power), max=str(most), room=str(room), start="false")
    limit = bp.find("maxSystems")
    if limit is not None:
        limit.text = str(max(int(limit.text), len(systems)))


def set_control_drones(bp, drones):
    """
    Give a hybrid's blueprint the drones it always has (as xftlDrone
    elements, see ShipBlueprint.requiredDrones), room for them and some
    more in its drones systems, and the drone parts to launch them.
    """
    for elem in bp.findall("xftlDrone"):
        bp.remove(elem)
    for drone in drones:
        ET.SubElement(bp, "xftlDrone").set("name", drone)
    systems = max(1, len(bp.findall("systemList/drones")))
    slots = bp.find("droneSlots")
    if slots is None:
        slots = ET.Element("droneSlots")
        bp.insert(1, slots)
    # (each drones system has this many slots, and the ones they always have
    # are shared out between them)
    slots.text = str(max(3, -(-len(drones) // systems) + 1))
    parts = bp.find("droneList")
    if parts is not None:
        parts.set("drones", str(max(int((parts.get("drones") or "0").strip()), 2 * len(drones) + 2)))


def bigger_hybrid(front, back, name, prefix, layout, hull, cloak, origin, cloak_offset, mounts, bp, shape,
                  seam, write=True, hold=True):
    """
    The long or wide version of a hybrid, made as ship_variants makes the
    automatic versions of the vanilla ships (see auto_config_for), with both
    races' systems in its new rooms (taking turns, the front's first), and
    what the front's race is known for. Returns its blueprint, or with
    write=False, its layout, hull, origin and mounts, to preview.
    """
    f, b = front.race.lower(), back.race.lower()
    systems = []
    for pair in zip(variants.FACTION_SYSTEMS[f], variants.FACTION_SYSTEMS[b]):
        systems += pair
    mounts_count = SHAPE_MOUNTS[prefix][SHAPES.index(shape)]
    extras = {k: v for k, v in variants.FACTION_EXTRAS.get(f, {}).get(shape, {}).items() if k not in LEFT_OUT_EXTRAS}
    config = dict(extras, auto=f, systems=systems, mounts=mounts_count,
                  hull=variants.HULL[SHAPE_MOUNTS[prefix][0]], avoid_dark=True,
                  avoid_rows=(seam - SEAM_AVOID, seam + SEAM_AVOID))
    config = variants.auto_config_for(hull, bp, name, layout, origin, shape, config)
    if hold:
        config = variants.with_hold(config, shape)

    axis = "y" if shape == "long" else "x"
    a = 1 if axis == "y" else 0
    cut, add = config["cut"], config["add"]
    new = variants.stretch_layout(layout, axis, cut, add, config["rooms"])
    new.cells()
    assert new.connected(), "%s %s: not every room can be reached" % (name, shape)

    split = origin[a] + cut * ROOM + config.get("shift", 0)
    source = split + config.get("source", -1)
    add_px = add * ROOM
    new_mounts = []
    for m in mounts:
        m = dict(m)
        key = "y" if axis == "y" else "x"
        if int(m[key]) >= split:
            m[key] = str(int(m[key]) + add_px)
        new_mounts.append(m)
    big_hull = clean_band(variants.insert(hull, axis, split, add_px, source), axis, split, add_px)
    big_cloak = variants.insert(cloak, axis, split - cloak_offset[a], add_px, source - cloak_offset[a])
    # A long one too tall for its window has its tail shortened
    if axis == "y":
        rooms_end = origin[1] + max(r[1] + r[3] for r in new.rooms.values()) * ROOM
        rooms_start = origin[1] + min(r[1] for r in new.rooms.values()) * ROOM
        rows = variants.tail_rows(big_hull, rooms_end + TAIL_MARGIN, variants.MAX_LONG_HEIGHT,
                                  rooms_start - TAIL_MARGIN)
        big_hull = variants.keep_rows(big_hull, rows)
        big_cloak = variants.keep_rows(big_cloak, rows, cloak_offset[a])
        for m in new_mounts:
            m["y"] = str(variants.moved_row(rows, int(m["y"])))
        # (the rooms move up with the rows taken out of the nose)
        origin = (origin[0], variants.moved_row(rows, origin[1]))
    new_mounts += variants.extra_mounts(big_hull, axis, split, add_px, new_mounts, mounts_count - len(new_mounts))
    if not write:
        return new, big_hull, origin, new_mounts

    file_name = "%s_%s" % (name.lower(), shape)
    ship_dir = MOD / "img" / "ship"
    big_hull.save(ship_dir / ("%s_base.png" % file_name))
    big_cloak.save(ship_dir / ("%s_cloak.png" % file_name))
    for i, (piece, _, _) in enumerate(gibs(big_hull)):
        piece.save(ship_dir / ("%s_gib%d.png" % (file_name, i + 1)))
    (MOD / "data" / ("%s.txt" % file_name)).write_text(new.text())
    note = "The %s version of %s, %d %s at %s %d." % (shape, name, add, "rows longer" if axis == "y" else "columns wider",
                                                      "row" if axis == "y" else "column", cut)
    (MOD / "data" / ("%s.xml" % file_name)).write_text(
        layout_xml(front.bp.get("layout"), big_hull, origin, cloak_offset, new_mounts, note))

    # The hybrid's own blueprint, without the limits it has as a small ship
    small = ET.fromstring(ET.tostring(bp))
    for tag in ("weaponSlots", "maxSystems"):
        for elem in small.findall(tag):
            small.remove(elem)
    print("Made %s (%dx%d)" % (file_name.upper(), big_hull.width, big_hull.height))
    big = ET.fromstring(variants.blueprint_xml(small, [name], shape, file_name, file_name, file_name, config,
                                               max(layout.rooms) + 1, small.findtext("class")))
    assert big.find("systemList/drones") is not None, "%s %s: its drones system was left out" % (name, shape)
    drones = control_drones(shape, front.race, back.race)
    ensure_drones_systems(big, new.rooms, drones, shape == "long")
    ensure_doors_system(big, new.rooms, shape == "long")
    set_control_drones(big, drones)
    ET.indent(big, "\t")
    return ET.tostring(big, encoding="unicode")


def make(parts, hybrid, write=True, prefix="XFTL_HYBRID_"):
    front, back = parts[hybrid[0]], parts[hybrid[1]]
    name = "%s%s_%s" % (prefix, front.race, back.race)
    layout, hull, cloak, origin, cloak_offset, mounts, ids_f, ids_b = glue(front, back, *hybrid[2:])
    if not write:
        return name, layout, hull, origin, mounts
    file_name = name.lower()
    ship_dir = MOD / "img" / "ship"
    hull.save(ship_dir / ("%s_base.png" % file_name))
    cloak.save(ship_dir / ("%s_cloak.png" % file_name))
    for i, (piece, _, _) in enumerate(gibs(hull)):
        piece.save(ship_dir / ("%s_gib%d.png" % (file_name, i + 1)))
    (MOD / "data" / ("%s.txt" % file_name)).write_text(layout.text())
    note = "The front of %s.xml and the back of %s.xml." % (front.bp.get("layout"), back.bp.get("layout"))
    (MOD / "data" / ("%s.xml" % file_name)).write_text(
        layout_xml(front.bp.get("layout"), hull, origin, cloak_offset, mounts, note))
    print("Made %s (%dx%d)" % (name, hull.width, hull.height))
    entries = blueprint(front, back, name, layout, ids_f, ids_b, len(mounts))
    bp = ET.fromstring(entries[0])
    for shape in SHAPES:
        args = (front, back, name, prefix, layout, hull, cloak, origin, cloak_offset,
                mounts, bp, shape, front.origin[1] + hybrid[2] * ROOM)
        try:
            try:
                entries.append(bigger_hybrid(*args))
            except variants.TooTall:
                # (a long one its hold would make too tall for its window
                # goes without, see variants.with_hold)
                print("  %s %s: without a hold, as it'd be too tall" % (name, shape))
                entries.append(bigger_hybrid(*args, hold=False))
        except (AssertionError, variants.TooTall) as error:
            print("  No %s version of %s: %s" % (shape, name, error))
    return name, entries


def preview(parts, hybrids, out, prefix="XFTL_HYBRID_"):
    out.mkdir(parents=True, exist_ok=True)
    for hybrid in hybrids:
        name, layout, hull, origin, mounts = make(parts, hybrid, write=False, prefix=prefix)
        plain = Image.new("RGBA", hull.size, (40, 40, 60, 255))
        plain.alpha_composite(hull)
        rooms = plain.copy()
        draw = ImageDraw.Draw(rooms)
        for rid, (x, y, w, h) in layout.rooms.items():
            box = [origin[0] + x * ROOM, origin[1] + y * ROOM,
                   origin[0] + (x + w) * ROOM - 1, origin[1] + (y + h) * ROOM - 1]
            draw.rectangle(box, fill=(225, 225, 225, 255), outline=(60, 60, 60, 255))
            draw.text((box[0] + 3, box[1] + 2), str(rid), fill=(0, 0, 0, 255))
        for m in mounts:
            x, y = int(m["x"]), int(m["y"])
            draw.ellipse([x - 4, y - 4, x + 4, y + 4], outline=(255, 60, 60, 255), width=2)
        sheet = Image.new("RGBA", (hull.width * 2 + 10, hull.height), (0, 0, 0, 255))
        sheet.paste(plain, (0, 0))
        sheet.paste(rooms, (hull.width + 10, 0))
        sheet.resize((sheet.width * 2, sheet.height * 2), Image.NEAREST).save(out / ("%s.png" % name.lower()))
    print("Previews in", out)


def write(entries):
    text = BLUEPRINTS_FILE.read_text()
    if BEGIN_MARK in text:
        text = text[:text.index(BEGIN_MARK)] + text[text.index(END_MARK) + len(END_MARK):]
    block = "\n".join([
        BEGIN_MARK,
        "<!--",
        "    The hybrid ships (see doc/game/hybrid-ships.md). Don't edit these by hand:",
        "    change tools/hybrid_ships.py and run it again.",
        "-->",
    ] + entries + [END_MARK])
    BLUEPRINTS_FILE.write_text(text.rstrip() + "\n\n" + block + "\n")


def main():
    dat = Dat(sys.argv[1])
    blueprints = vanilla_blueprints(dat)
    entries = []
    everything = []
    for kind, (ships, prefix, list_name) in CLASSES.items():
        parts = {race: Part(dat, blueprints, race, ship) for race, ship in ships.items()}
        found = best_hybrids(parts)
        if len(sys.argv) > 2 and sys.argv[2] == "--search":
            print(kind)
            for score, front, back, cut_f, cut_b, shift in found:
                print("  %3d: %s front (cut %d) + %s back (cut %d), moved %d" % (score, front, cut_f, back, cut_b, shift))
            continue
        hybrids = [result[1:] for result in found]
        if len(sys.argv) > 3 and sys.argv[2] == "--preview":
            preview(parts, hybrids, Path(sys.argv[3]) / kind.lower(), prefix)
            continue

        names = []
        for hybrid in hybrids:
            name, parts_xml = make(parts, hybrid, prefix=prefix)
            names.append(name)
            entries += parts_xml
        entries.append(blueprint_list(list_name, names))
        # And for each vanilla ship, the hybrids made from it (which the game
        # can use in its place, see ShipGenerator.hybridFor)
        for race, ship in ships.items():
            own = [name for (front, back, *_), name in zip(hybrids, names) if race in (front, back)]
            entries.append(blueprint_list(HYBRIDS_OF + ship, own))
        everything.append(list_name)
    if entries:
        entries.append(blueprint_list(ALL_HYBRIDS, everything))
        write(entries)


if __name__ == "__main__":
    main()

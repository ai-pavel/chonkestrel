def hull_edges(image, y):
    alpha = image.getchannel("A")
    xs = [x for x in range(image.width) if alpha.getpixel((x, y)) > 200]
    return (xs[0], xs[-1]) if xs else None


def search(parts):
    """
    Every way of gluing two ships together along grid lines that don't go
    through rooms, best first: how far apart their hulls' edges are where
    they meet, and how many columns the back has to move over.
    """
    results = []
    for front in parts.values():
        rows_f = [c[1] for c in front.layout.cells()]
        for back in parts.values():
            if back is front or RACES[back.race][2] == RACES[front.race][2]:
                continue
            rows_b = [c[1] for c in back.layout.cells()]
            for cut_f in range(min(rows_f) + 1, max(rows_f) + 1):
                edges_f = hull_edges(front.hull, front.origin[1] + cut_f * ROOM - 1)
                for cut_b in range(min(rows_b) + 1, max(rows_b) + 1):
                    if not edges_f:
                        continue
                    # Cutting through rooms makes them smaller, and a front
                    # (or back) of one row is hardly any of the ship
                    penalty = CROSSING_PENALTY * (len(front.layout.crossing("y", cut_f))
                                                  + len(back.layout.crossing("y", cut_b)))
                    if cut_f - min(rows_f) < 2:
                        penalty += CROSSING_PENALTY
                    if max(rows_b) + 1 - cut_b < 2:
                        penalty += 2 * CROSSING_PENALTY
                    edges_b = hull_edges(back.hull, back.origin[1] + cut_b * ROOM)
                    if not edges_b:
                        continue
                    for shift in range(-6, 7):
                        dx = front.origin[0] - back.origin[0] + shift * ROOM
                        gap = abs(edges_f[0] - edges_b[0] - dx) + abs(edges_f[1] - edges_b[1] - dx)
                        results.append((gap + penalty, front.race, back.race, cut_f, cut_b, shift))
    results.sort()
    return results


def best_hybrids(parts):
    """
    The best way of gluing each pair of races' ships that works: with every
    room reachable, and room for the systems every ship needs.
    """
    found = {}
    for result in search(parts):
        pair = result[1:3]
        if pair in found:
            continue
        front, back = parts[pair[0]], parts[pair[1]]
        try:
            layout, _, _, _, _, mounts, ids_f, ids_b = glue(front, back, *result[3:])
            blueprint(front, back, "XFTL_HYBRID_TEST", layout, ids_f, ids_b, len(mounts))
        except AssertionError:
            continue
        found[pair] = result
    return sorted(found.values())


